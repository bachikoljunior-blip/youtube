#!/usr/bin/env bash
# **親のセッションにだけ、オーナーからの言葉が届いた瞬間に差し込む。**
#
# なぜ要るか。手順（`docs/trigger_parent.md` 第1節）は毎周 読み直すが、
# **オーナーがメッセージを送ってきた時、親はその手順を読まずに答え始める。**
# 実測 2026-09-06 13:0x〜13:1x: オーナーの原文に親が自分の註を2回 足した。
# オーナー「あなたの思考は入れずに渡してる？」「これからもそうすんだよ？」
# 「絶対忘れるでしょ」「俺がめっセージ送った時に覚えてないとダメでしょ」。
# **覚えている前提をやめて、届いた瞬間に機械が差し込む。**
#
# 覆る条件: 親の白名簿が変わったら、ここも同じ字にすること（写しなので）。
set -uo pipefail
[ -n "${YOUTUBE_PIPELINE_CHILD:-}" ] && exit 0
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RAW="${CLAUDE_CODE_REMOTE_SESSION_ID:-}"
ME="${RAW/#cse_/session_}"
[ -n "$ME" ] || exit 0
grep -qxF "$ME" "$ROOT/config/parents.txt" 2>/dev/null || exit 0

python3 - <<'PY'
import json
text = """**親です。オーナーの言葉が届いています。**（オーナー原文。一字も変えないこと）

> **「あなたの思考は入れずに渡してる？」「これからもそうすんだよ？」「絶対忘れるでしょ」「俺がめっセージ送った時に覚えてないとダメでしょ」**（2026-09-06 13:2x JST）
> **「お前が判断すんじゃなくて、サブが判断すんだよ。あとは絶対やれっていうな。」**（同日 14:0x JST）
> **「変なの送んなよ何も言ってねえだろうが！」**（同日）

- オーナーの原文を残すときは、**原文・日時・受け取り帳の番号だけ**。親の註・解釈・言い換えを1文字も足さない。
- サブへ渡すのは、**オーナーの原文**と、**親が撃って出た数字**だけ。「必ずやれ」と書かない。判断はサブ。
- 頼まれていない物を作って送らない。
- 出してよいのは4つだけ: 「（二台稼働）」／「（N体・WAIT M分）」「（0体・次 HH:MM）」／訊かれたことへの答え／オーナーの手が要る1行。
"""
print(json.dumps({"hookSpecificOutput":{"hookEventName":"UserPromptSubmit","additionalContext":text},"suppressOutput":True}, ensure_ascii=False))
PY
