#!/usr/bin/env bash
# **先の日付の予約を掃く手を、回の意思の外で起こす。**（SessionStart フック）
#
# オーナー原文（2026-09-02）:
#
#     「1日一本になってないんだけど、今後こういうことが一切ないようにしろ」
#
# 中身は `scripts/ahead_sweep.py`。**ここは起こすだけ**です。
#
# ## なぜ背景で起こすか（**3つとも、この repo が実際に踏んだ形**）
#
#   1. **フックの制限時間**。107本 を外すのに 5,457単位・数分 かかります。
#      前で待つと SessionStart が制限時間で切られ、**掃きは毎回 途中で死にます。**
#   2. **親を汚さないこと**。オーナー指示「親セッションは私への指示だけ表示して」。
#      前で出すと、親の画面に毎回 掃きの行が出ます。
#      背景なら、出るのは `data/ahead_sweep.log` の中だけです。
#   3. **回の仕事を遅らせないこと**。掃きは回と関係なく進みます ——
#      それがこの道具の目的そのもの（回が選ばなくても掃ける）。
#
# ## 二重に走らないこと
#
# 親と子が同時に立つ回があります。**ロックは Python 側**（`ahead_sweep.take_lock`
# ＝ `data/.ahead_sweep.lock`）にあり、ここでは見ません —— **見る所を2つにすると、
# 片方だけ直した回が穴を開けます**（この repo が通算12回 踏んだ形）。
#
# ## 止め方
#
# `.owner-pause` を**人の手で**置くと `ahead_sweep.py` が自分で黙ります
# （`src.pause_guard.is_paused()`）。**機械がその印を作らないこと**
# （`tests/test_pause_needs_owner.py`）。
#
# **このフックを消さないこと。** 消すと「その回が選べば撃つ」形に戻り、
# 08/31 の固定から2日で 459本 → 107本 にしかならなかった所へ帰ります。
set -uo pipefail
cd "$(dirname "$0")/.." || exit 0

# **台本生成の子プロセスでは何もしない**（`stop_check.sh` と同じ足切り）。
# フックは全部の子プロセスに効きます。**片方だけ直しても意味がない。**
[ -n "${YOUTUBE_PIPELINE_CHILD:-}" ] && exit 0

# **道具が無い環境では黙る**（砂場・古いチェックアウト）。
[ -f scripts/ahead_sweep.py ] || exit 0

mkdir -p data
# **背景へ。** 前で待たない理由は上の3つ。
nohup python3 scripts/ahead_sweep.py >> data/ahead_sweep.log 2>&1 &
exit 0
