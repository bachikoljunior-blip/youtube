#
# ## なぜ印字ではなく門か
#
# `status.py` は 06:1x に、この穴と「埋める道はその日の回が `upload` を1本 出すことだけ」まで
# **正しく印字していました。** それでも `upload` は増えていません ——
# **700行の本文の 340行目**に在るからです。271行目に同じ教訓が書いてあります:
# 「**印字に格上げしただけでは、同じ穴です —— 出ていても、読まずに終われる。**」
#
# **覆る条件**: 判定は `scripts/slot_gate.py`（API 0単位・控えだけ）。
# 控えは**上限側の見積り**なので、この門は**空を見落とす側**に外れます ——
# **鳴ったら本物**、鳴らなくても埋まっている証拠にはなりません。
# 日枠が尽きていて撃てない回のために **3回で通します。**
SLOTGATE=$(cd "$ROOT" && timeout 60 python3 scripts/slot_gate.py --gate 2>/dev/null)
SLOTRC=$?
# **`python3 <無いファイル>` も exit 2 です**（2026-09-01 に踏んだ ——
# 砂場に `slot_gate.py` を置いていない検査で、この門が「穴あり」と読み、
# 後ろの門を全部 覆い隠していました）。**印字が空でないこと**も見ます。
if [ "$SLOTRC" -eq 2 ] && [ -n "$SLOTGATE" ]; then
  SCOUNT="$STATE_DIR/claude-youtube-slot-blocks-${ME:-none}"
  SN=$(cat "$SCOUNT" 2>/dev/null || echo 0)
  if [ "$SN" -lt 3 ]; then
    echo $((SN + 1)) > "$SCOUNT"
    cat <<EOF >&2
【きょうの1本が、まだ予約にも実績にもありません】(${SN}→$((SN + 1))回目・3回で通します)

${SLOTGATE}

**この回が出したものは、その日の穴を埋めていません。**
\`fix\` も \`verdict\` も \`improve\` も、**空いた日には1本も入りません。**

- 背後で走っているもの: ${RUNNING}
- 未コミットの変更: ${DIRTY}
EOF
    printf '{"decision":"block","reason":"きょうの1本が、まだ予約にも実績にもありません。きょうの枠へ1本 入れてから終わってください（python scripts/slot_gate.py）。**先の日付には置かないこと** ＝ 規則5・固定その4"}\n'
    exit 0
  fi
  rm -f "$SCOUNT"
  cat <<EOF >&2
【3回問いました。通します】
**投稿が途切れる日を埋めないまま終わる回になります。**
理由（日枠・一時停止など）を \`docs/JOURNAL.md\` に必ず書くこと。
EOF
fi

# --- (1.45) **先の日付の予約を、0本にしないまま終わらせない**（2026-09-02） ---
#
# **オーナー原文**:
#
#     「1日一本になってないんだけど、今後こういうことが一切ないようにしろ」
#
# 規則5（固定その4）は「**先の日付には1本も置かない。先の日付が空なのが正しい状態**」。
# **規則は 08/31 に固定されました。それから2日 経って、先の日付の予約は
# 459本 → 107本 にしか減っていません**（9/24〜10/10・6.3本/日）。
# 放置すれば 09/24 から**1日6本** 出ます。
#
# ## なぜ印字でも手順でもなく、門か
#
# 減らす手（`pool_drain --apply`）は在り、`docs/trigger_main.md` §4 にも書いてあり、
# 何度も名指しされています。**それでも減らなかったのは「その回が選べば撃つ」形
# だったから**です —— 実測（09/01・`data/runs.jsonl`）は **`fix` 82% ／ `upload` 0件**。
# **選ばれない手は、撃たれません。** 271行目の教訓がそのまま当たります:
# 「**印字に格上げしただけでは、同じ穴です —— 出ていても、読まずに終われる。**」
#
# ## **引き止めを数で緩めていません**（他の門と、ここだけ違います）
#
# 他の門は「3回で通します」です。**ここは通しません** —— 通す条件を
# 回数にすると、**それが「その回が選べば撃つ」形そのもの**に戻ります。
# 代わりに、**逃げ道を1つだけ、道具の側に持たせてあります**:
#
#     日枠が尽きている → `scripts/ahead_gate.py` が自分で `upload_cap.day_quota()`
#                        に訊いて、exit 0 で通す（＋残件を受け取り帳へ）
#
# **＝ 撃てる窓では止まり、撃てない窓では止まりません。** 回の申告ではなく、
# 帳面（`data/day_quota.jsonl`）が決めます。
#
# **ただし「永久に止まる」は避けます**（`CLAUDE.md`「止まったまま死ぬほうが
# 確実に悪い」）—— **12回**で通します。1周に何度も終われる作りなので、
# ここは他の門より深く取ってあります。12回 問うても外れていないなら、
# それは日枠でも手順でもない別の故障なので、**JOURNAL に書いて次の回へ渡すほう**が速い。
#
# **覆る条件**: `house_rule.same_day_only()` が `False` になったら
# `ahead_gate` がまるごと黙るので、この門も自動で消えます。
AHEADGATE=$(cd "$ROOT" && timeout 60 python3 scripts/ahead_gate.py --gate 2>/dev/null)
AHEADRC=$?
# **`python3 <無いファイル>` も exit 2 です**（1.4 の註に実測）。印字も見ます。
if [ "$AHEADRC" -eq 2 ] && [ -n "$AHEADGATE" ]; then
  ACOUNT="$STATE_DIR/claude-youtube-ahead-blocks-${ME:-none}"
  AN=$(cat "$ACOUNT" 2>/dev/null || echo 0)
  if [ "$AN" -lt 12 ]; then
    echo $((AN + 1)) > "$ACOUNT"
    cat <<EOF >&2
【先の日付に予約が残っています】(${AN}→$((AN + 1))回目・12回で通します)

${AHEADGATE}

**「今後こういうことが一切ないようにしろ」の側です。**
外すのは日枠が要る仕事で、**この窓で撃てるなら、この回が撃つこと。**
撃てない窓ならこの門は鳴りません（道具が自分で日枠を見ています）。

- 背後で走っているもの: ${RUNNING}
- 未コミットの変更: ${DIRTY}
EOF
    printf '{"decision":"block","reason":"先の日付（明日 JST 以降）の予約が 0本 になっていません。この回で外してから終わってください（python scripts/ahead_gate.py が手順を出します）。**削除はしません** —— private の下書きへ戻すだけです"}\n'
    exit 0
  fi
  rm -f "$ACOUNT"
  cat <<EOF >&2
【12回問いました。通します】
**先の日付の予約を 0本 にしないまま終わる回になります。**
**日枠でも手順でもない別の故障です。** 何を撃って何が返ったかを
\`docs/JOURNAL.md\` に必ず書くこと（次の回はここから始めます）。
EOF
fi

# --- (2) 普通の「終わるのが最善か」。5分以内に一度問うていれば通す ---
if [ -f "$SENTINEL" ]; then
  LAST=$(cat "$SENTINEL" 2>/dev/null || echo 0)
  if [ $((NOW - LAST)) -lt 300 ]; then
    rm -f "$SENTINEL"
    exit 0
  fi
fi
echo "$NOW" > "$SENTINEL"

cat <<EOF >&2
【終わる前の確認】いま終わるのが**目標に対して**最善か、答えてから終わってください。

- 背後で走っているもの: ${RUNNING}
- 未コミットの変更: ${DIRTY}
- この回が出したもの: ${SHIP_STATE}（shipped ＝ 記録済み。印の無い回はここまで来ません）

**これは「終わるな」ではありません。** 問うているのは
「終わるかどうか」ではなく**「終わるのが最善かを考えたか」**です。

**使用量は目標のためにあります。残すこと自体に価値はありません。**
予算を理由に作業を見送らないこと。ただし**速さは別の話**で、
先に使い切ると次の回が起きられません（\`docs/TRIGGER.md\`）。

天秤にかけるのはこの3つです。

1. **投稿の予約は切れていないか。** 切れそうなら、他を削ってでも生成に使う。
   投稿が途切れるのが最大の損失。\`python scripts/status.py\` の「予約が入っていない日」。
2. **判定を先送りしていないか。** 期限の来た前提（config/hypotheses.yaml）を
   放置して終わると、推測が推測のまま残る。
3. **自分で決めた条件を惰性で守っていないか**（\`docs/CONSTRAINTS.md\`）。
   与件は目標だけです。**数字がそれを覆したら変えてよい。**

終わると決めたなら、**未コミットの変更を push してから**終わること。
そのうえでもう一度終了すれば、この確認は通ります。
EOF

printf '{"decision":"block","reason":"上の確認に答えてから終わってください"}\n'
exit 0
