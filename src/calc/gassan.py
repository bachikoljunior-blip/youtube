def _jogen_70miman(name: str) -> int:
    for label, cap in NENKAN_70MIMAN:
        if label == name:
            return cap
    raise ValueError(name)


def umari() -> list[dict]:
    """節1: 医療だけで年間限度額の何割が埋まるか（1パーセント加算は乗せない）。"""
    rows = []
    for iryo_k, nen_k, _ in KUMI_70MIMAN:
        jogen = _jogen_70miman(nen_k)
        nenkan = iryo_nenkan(iryo_k, 0)
        rows.append({
            "区分": iryo_k,
            "年間限度額（円）": jogen,
            "医療だけの年額（円）": nenkan,
            "埋まる割合（パーセント）": round(nenkan * 100 / jogen, 1),
            "残る枠（円）": jogen - nenkan,
        })
    return rows


def todoku_iryohi() -> list[dict]:
    """節2: 1パーセント加算だけで年間限度額に届く、月あたりの総医療費。"""
    rows = []
    for iryo_k, nen_k, _ in KUMI_70MIMAN:
        jogen = _jogen_70miman(nen_k)
        nokori = jogen - iryo_nenkan(iryo_k, 0)
        kiribu = next(k for n, _, k, _ in IRYO_TSUKI if n == iryo_k)
        honrai = TASUKAI_KARA - 1
        if kiribu == 0:
            rows.append({
                "区分": iryo_k,
                "1パーセント加算": "なし",
                "残る枠（円）": nokori,
                "届く総医療費（月・円）": None,
            })
            continue
        # 本来の上限の月（3か月）だけが 1パーセント加算を持つ。
        # honrai × (総医療費 − 足切り) ÷ 100 = 残る枠
        koeta = nokori * 100 / honrai
        rows.append({
            "区分": iryo_k,
            "1パーセント加算": "あり",
            "残る枠（円）": nokori,
            "届く総医療費（月・円）": int(koeta) + kiribu,
        })
    return rows


