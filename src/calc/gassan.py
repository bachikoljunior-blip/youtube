# ---- 計算 -------------------------------------------------------------
def iryo_tsuki(kubun: str, sou_iryohi: int, *, tasukai: bool = False) -> int:
    """高額療養費の、その月の自己負担上限。**総医療費は10割の額。**"""
    for name, teigaku, kiribu, ta in IRYO_TSUKI:
        if not name.startswith(kubun):
            continue
        if tasukai:
            return ta
        if kiribu == 0:
            return teigaku
        koeta = max(0, sou_iryohi - kiribu)
        return teigaku + koeta // 100
    raise ValueError(f"区分に当たらない: {kubun}")


def iryo_nenkan(kubun: str, sou_iryohi: int, *, tasukai: bool = True) -> int:
    """医療だけで1年に払う額（毎月上限まで負担が出る置き方）。"""
    honrai = TASUKAI_KARA - 1
    out = honrai * iryo_tsuki(kubun, sou_iryohi)
    if tasukai:
        out += TASUKAI_TSUKI * iryo_tsuki(kubun, sou_iryohi, tasukai=True)
    else:
        out += TASUKAI_TSUKI * iryo_tsuki(kubun, sou_iryohi)
    return out


def kaigo_nenkan(kubun: str) -> int:
    """介護だけで1年に払う額。**介護には多数回該当がない**（毎月同じ上限）。"""
    for name, cap in KAIGO_TSUKI:
        if name.startswith(kubun):
            return cap * TSUKI_PER_YEAR
    raise ValueError(f"区分に当たらない: {kubun}")


def shikyu(jikofutan: int, nenkan_jogen: int) -> int:
    """合算して戻る額。**500円以下は支給されない。**"""
    koeta = jikofutan - nenkan_jogen
    return koeta if koeta > KYUFU_SHITA else 0


