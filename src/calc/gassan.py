"""**高額介護合算療養費 —— 年間の上限は、月ごとの上限を12回払うだけでほぼ埋まる。**

医療と介護の自己負担を1年ぶん合算して、年間の限度額を超えたら戻る制度がある。
一般の解説はここで止まる —— 「年間212万円・141万円・67万円…」と段を並べて終わり。
**その段が、月ごとの上限とどういう関係にあるかは、どこにも書いていない。**

高額療養費（`kogaku`）と高額介護サービス費（`kaigo`）には、それぞれ**月ごと**の
上限がある。年間の限度額は、その月ごとの上限を1年ぶん払った額と比べて、
**どのくらい残っているのか。** ここで出しているのはその引き算です。

## 出たもの

**1. 医療だけで、年間限度額の 95.0〜96.4 パーセントが埋まる。**
毎月上限まで負担が出て、4か月目から多数回該当になる置き方だと:

    区分ウ   639,900円 ／ 670,000円 ＝ 95.5%   残る枠 **30,100円**
    区分オ   327,600円 ／ 340,000円 ＝ 96.4%   残る枠 **12,400円**

**5区分すべてが95パーセント台**に入ります。段の額は 34万円から212万円まで
6.2倍の開きがあるのに、埋まり方はほぼ同じ。**残るのは1万2千円から10万円ぶんだけ**で、
「医療と介護を合算する制度」と言いながら、**枠のほとんどは医療だけで消えています。**

**2. 区分エと区分オは、医療費がいくら高くても年間限度額に届かない。**
1パーセントの加算があるのは区分ア・イ・ウだけで、エとオは定額で頭打ちだからです。
届く側は月の総医療費で **4,218,666円・2,918,000円・1,270,333円**。

**3. 介護だけで年間限度額を超えるのは、いちばん低い段だけ。**
低所得Iの年間限度額は190,000円ですが、世帯の月額上限24,600円を12回払うと
**295,200円＝155.4パーセント**で超えます。個人の上限15,000円なら180,000円で
94.7パーセント。**同じ人が、世帯で見るか個人で見るかで、超える側と超えない側に入れ替わる。**

**4. 両方いっぱいまで使うと、戻るのは払った額の 42.6〜45.7 パーセント。**
区分ウで 1,172,700円 払って、戻るのは 502,700円。

**5. 70歳になると、同じ「住民税非課税」でも限度額が下がる。**
70歳未満の非課税は340,000円、70歳以上の低所得IIは310,000円、低所得Iは190,000円。
**同じ「住民税非課税」で 1.79倍の開き**があり、年齢だけで下がる側に動きます。
いっぽう 70歳未満の標報28〜50万円と70歳以上の現役並みIは、どちらも670,000円で同額。

**6. 限度額を超えても、超えた額が500円ちょうどまでは1円も出ない。**
501円超えて初めて501円。**500円の死に区間**がそのまま残っています。

**7. 多数回該当が無ければ、5区分すべてが医療だけで年間限度額を超えます。**
超える額は 84,800円から911,200円。多数回該当が減らしている額は
**97,200円から1,012,500円**。年間限度額に対する比で見ると、
**1パーセント加算のある区分ア・イ・ウは 47.8・47.5・48.0 パーセントで揃い**、
加算の無い区分エ・オは 19.8・28.6 パーセントしかありません。
**多数回該当は、上の3区分では年間限度額のほぼ半分を肩代わりしています。**

（ここは一度書き間違えました —— 「年間限度額そのものより大きい区分がある」と
書いて、その場で検査に落とされています。区分アの1,012,500円は限度額2,120,000円の
**半分に届きません**。**表を見てから書いても、比だけは掛け算しないと出ません。**）

## 前提の置き方（ここが独自の視点です）

**「毎月きっちり上限まで負担が出る」**という置き方をしています。これは上限側の値で、
実際には負担の出ない月があります。**この置き方をしないと、月の上限と年の限度額を
同じ物差しに載せられません。** 逆に言えば、ここで出る「残る枠」は
**いちばん狭く見積もったとき**の数字で、実際の枠はこれより広くなります。
"""

