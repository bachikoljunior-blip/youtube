"""教育訓練給付の「上限に当たる授業料」を、6つの給付率すべてについて計算する。

狙いは制度の解説ではない。「一般は20パーセントで上限10万円、専門実践は最大80パーセントで
年間上限64万円」という数字は、どこにでも書いてある。

ここで出したいのは **どこにも表になっていない数字** ——
**その上限に当たるのは授業料がいくらのときか**を、6つの率すべてについて並べた表。

--------------------------------------------------------------------------
なぜこの題材か
--------------------------------------------------------------------------
教育訓練給付は「率」で語られる。20パーセント、40パーセント、50パーセント、
70パーセント、80パーセント。**率が上がるほど得だ**という話になる。

ところが率には必ず**年間の上限額**が付いていて、
授業料が一定を超えると、給付は率で伸びるのをやめて**定額に張り付く**。
つまり率が意味を持つのは上限に当たるまでの帯だけで、その先は率が何であっても同じ。

一般の解説はここで止まる。止まる理由は、
**「上限に当たる授業料」が制度の資料のどこにも書かれていない**からで、
上限額を率で割るという1回の割り算をしないと出てこない。

割ってみると、6つの率が **たった2つの数字**に畳まれる。

--------------------------------------------------------------------------
下限のほうは、逆向きに動く
--------------------------------------------------------------------------
一般・特定一般には「支給額が4,000円を超えないときは支給しない」という下限がある。
**この4,000円は定額**なので、率が上がると下の境目は**下がる**。
上の境目（上限に当たる授業料）は率に比例して設計されているので**動かない**のに、
下の境目だけが率に反比例して動く。**同じ改正が、上下で逆向きに効く。**

--------------------------------------------------------------------------
金額を「授業料」の側で出している理由
--------------------------------------------------------------------------
給付額は毎年の予算や改正で動くが、**上限額を率で割った値**は、
上限と率が同じ比で動くかぎり変わらない。実際 2024年10月の改正で
特定一般に10パーセント、専門実践に10パーセントが足されたが、
**上限に当たる授業料は1円も動いていない**（下の表がそれを示す）。

--------------------------------------------------------------------------
根拠
--------------------------------------------------------------------------
雇用保険法 60条の2          教育訓練給付金。給付率と上限額の枠組み。
同 施行規則 101条の2の7      一般教育訓練に係る給付率・上限額・下限額。
同 施行規則 101条の2の9ほか   専門実践教育訓練に係る給付率・年間上限額。

--------------------------------------------------------------------------
この計算で「使わない」もの
--------------------------------------------------------------------------
教育訓練支援給付金（45歳未満の離職者が専門実践を受けるあいだ出るもの）は
入れていない。**入れれば受取は上振れする側**なので、ここで出す金額は
「少なくともこれだけは出る／これ以上は出ない」という枠として読める。

支給要件期間（初回1年ないし2年、2回目以降3年）と、教育訓練経費に何を含めるか
（入学料と受講料のみ。教材費・交通費は含まない）も、金額の計算には入れていない。
"""
from __future__ import annotations

import math

from . import _checks

# 動画と説明欄にそのまま出す前提。
ASSUMPTIONS = [
    "給付率と上限額は、2024年10月の改正後の値を使っています。"
    "一般教育訓練は20パーセントで上限10万円、"
    "特定一般教育訓練は40パーセントで上限20万円、"
    "資格を取って就職した場合は50パーセントで上限25万円です",
    "専門実践教育訓練は、受講中が50パーセントで年間上限40万円、"
    "資格を取って就職した場合が70パーセントで年間上限56万円、"
    "さらに賃金が5パーセント以上上がった場合が80パーセントで年間上限64万円です",
    "一般教育訓練と特定一般教育訓練には下限があり、"
    "支給額が4,000円を超えないときは支給されないものとして置いています",
    "支給額の1円未満は切り捨てとして計算しています",
    "教育訓練経費は入学料と受講料だけで、教材費・交通費・受験料は入れていません",
    "教育訓練支援給付金、支給要件期間、給付制限は入れていません。"
    "ここで比べているのは、授業料に対して給付金がいくら出るかだけです",
    "専門実践の訓練期間は最長3年として置いています。"
    "専門職大学の課程など4年になる場合は、その分だけ年間上限が1回多く使えます",
]

# ---- 制度の値。**長く動いていないものだけをここに置く** ----------------
# 雇用保険法60条の2、同施行規則。(名前, 給付率, 上限額)。
# 専門実践の上限は**年間**、一般・特定一般の上限は**1回の受講あたり**。
PROGRAMS: list[tuple[str, float, int]] = [
    ("一般", 0.20, 100_000),
    ("特定一般", 0.40, 200_000),
    ("特定一般＋資格取得・就職", 0.50, 250_000),
    ("専門実践（受講中）", 0.50, 400_000),
    ("専門実践＋資格取得・就職", 0.70, 560_000),
    ("専門実践＋賃金5パーセント上昇", 0.80, 640_000),
]

# 支給額がこの額を**超えない**ときは支給されない（一般・特定一般）。
FLOOR = 4_000

# 下限が掛かるのはこの2つだけ、として置いている。
FLOOR_PROGRAMS = ("一般", "特定一般", "特定一般＋資格取得・就職")

# 専門実践の訓練期間の上限（年）。
MAX_YEARS = 3

# 3年に1回しか受けられない（支給要件期間）。年あたりに直すときの割り算の分母。
INTERVAL_YEARS = 3


def rate_of(name: str) -> float:
    for n, r, _ in PROGRAMS:
        if n == name:
            return r
    raise ValueError(f"知らない給付: {name}")


def cap_of(name: str) -> int:
    for n, _, c in PROGRAMS:
        if n == name:
            return c
    raise ValueError(f"知らない給付: {name}")


def paid(cost: float, name: str) -> int:
    """授業料 `cost` に対して実際に出る額。**1円未満は切り捨て、上限で頭打ち。**"""
    r, cap = rate_of(name), cap_of(name)
    amount = math.floor(min(cost * r, cap))
    if name in FLOOR_PROGRAMS and amount <= FLOOR:
        return 0
    return amount


def cost_at_cap(name: str) -> float:
    """**上限に当たる授業料。** 上限額 ÷ 率。この1回の割り算がこの計算の中心。"""
    return cap_of(name) / rate_of(name)


def min_cost_paid(name: str) -> int:
    """**1円でも出る、いちばん安い授業料**（下限のある給付だけ）。

    支給額が 4,000円を**超える**必要があり、1円未満は切り捨てなので、
    `率 × 授業料` が 4,001円以上になる最小の整数円。
    """
    if name not in FLOOR_PROGRAMS:
        raise ValueError(f"{name} には下限を置いていません")
    return math.ceil((FLOOR + 1) / rate_of(name))


def effective_rate(cost: float, name: str) -> float:
    """実際に返ってきた割合。**上限を超えた先では費用に反比例して落ちる。**"""
    return paid(cost, name) / cost


def cost_at_half_rate(name: str) -> float:
    """**名目の率がちょうど半分になる授業料。** 上限に当たる授業料の2倍。"""
    return cost_at_cap(name) * 2


def yearly_ceiling(name: str, years: int = 1) -> float:
    """**年あたりに直した上限。** 3年に1回しか受けられないので、総額を3年で割る。"""
    return cap_of(name) * years / INTERVAL_YEARS


def paid_over_years(total_cost: float, years: int, name: str) -> float:
    """総額 `total_cost` の課程を `years` 年かけて受けたときの受取。

    **上限が年額なので、同じ総額でも期間が長いほど増える。**
    授業料は各年に均等に掛かるものとして置いている。
    """
    per_year = total_cost / years
    return years * min(per_year * rate_of(name), cap_of(name))


def gap_ratio(cost: float, low: str = "一般",
              high: str = "専門実践＋賃金5パーセント上昇") -> float:
    """**同じ授業料のとき、2つの給付で受取が何倍ちがうか。**

    率の比は 4.0倍（20 → 80パーセント）で固定なのに、上限額の比は 6.4倍
    （10万 → 64万円）ある。**この2つの数字が食い違うぶんは、どこへ行くのか。**

    答えは「授業料の帯」で、比は 4.0 のまま上がらない帯と、
    4.0 から 6.4 へ開いていく帯と、6.4 で止まる帯に分かれる。
    開き始めるのは安いほうが上限に当たる 50万円、開き切るのは高いほうが
    上限に当たる 80万円。**つまり率の比と上限の比の差は、
    「2つの上限に当たる授業料のあいだ」でしか実現しない。**
    """
    lo = paid(cost, low)
    if lo == 0:
        raise ValueError(f"{low} は授業料 {cost:,.0f}円では1円も出ない（比を取れない）")
    return paid(cost, high) / lo


def grid() -> list[dict]:
    """図解の元になる表。**上限に当たる授業料が、率によらないことを示す表。**"""
    rows = []
    for name, rate, cap in PROGRAMS:
        rows.append({
            "給付": name,
            "率": rate,
            "上限額": cap,
            "上限に当たる授業料": cost_at_cap(name),
            "名目の半分になる授業料": cost_at_half_rate(name),
        })
    return rows


def floor_grid() -> list[dict]:
    """下の境目の表。**上限と逆向きに、率が上がると下がる。**"""
    return [{
        "給付": name,
        "率": rate_of(name),
        "1円でも出る最小の授業料": min_cost_paid(name),
        "そのときの支給額": paid(min_cost_paid(name), name),
    } for name in FLOOR_PROGRAMS]


def check_tables() -> None:
    """制度の値と計算の向きを確かめる。**壊れた数字で台本を書かせない。**"""
    # 1. 法令が名指ししている値
    _checks.statutory(rate_of("一般"), 0.20, "一般教育訓練の給付率",
                      source="雇用保険法施行規則101条の2の7")
    _checks.statutory(cap_of("一般"), 100_000, "一般教育訓練の上限額",
                      source="雇用保険法施行規則101条の2の7")
    _checks.statutory(rate_of("専門実践＋賃金5パーセント上昇"), 0.80,
                      "専門実践の最大給付率（2024年10月改正後）",
                      source="雇用保険法60条の2")
    _checks.statutory(cap_of("専門実践＋賃金5パーセント上昇"), 640_000,
                      "専門実践の年間上限額（80パーセントのとき）",
                      source="雇用保険法60条の2")
    _checks.statutory(FLOOR, 4_000, "一般・特定一般の下限額",
                      source="雇用保険法施行規則101条の2の7")
    for name, rate, _ in PROGRAMS:
        _checks.ratio(rate, f"{name}の給付率")

    # 2. **この計算の主題そのもの。**
    #    (a) 上限に当たる授業料は、6つの率で**2種類しかない**
    at_cap = {round(cost_at_cap(n)) for n, _, _ in PROGRAMS}
    if at_cap != {500_000, 800_000}:
        raise _checks.TableError(
            f"上限に当たる授業料が2種類になりません: {sorted(at_cap)}")

    #    (b) 一般・特定一般は率が2倍・2.5倍になっても、上限に当たる授業料が同じ
    for name in FLOOR_PROGRAMS:
        _checks.rounding(cost_at_cap(name), 500_000,
                         f"{name}の上限に当たる授業料")
    #    (c) 専門実践は3つの率すべてで同じ
    for name in ("専門実践（受講中）", "専門実践＋資格取得・就職",
                 "専門実践＋賃金5パーセント上昇"):
        _checks.rounding(cost_at_cap(name), 800_000,
                         f"{name}の上限に当たる授業料")

    #    (d) 上限を超えた先では、実効の率は費用が増えるほど**下がる**
    _checks.decreases_with(
        lambda c: effective_rate(c, "専門実践＋賃金5パーセント上昇"),
        [900_000, 1_200_000, 1_600_000, 2_400_000],
        "授業料が増えたのに実効の率が下がっていない")

    #    (e) 上限に当たるまでは、実効の率は名目の率と一致する
    for name, rate, _ in PROGRAMS:
        c = cost_at_cap(name)
        _checks.rounding(effective_rate(c, name), rate,
                         f"{name}の上限ちょうどでの実効の率")

    #    (f) 下の境目は率に**反比例**する（上限と逆向き）
    _checks.decreases_with(lambda name: min_cost_paid(name),
                           sorted(FLOOR_PROGRAMS, key=rate_of),
                           "率が上がったのに下の境目が下がっていない")
    #        境目のすぐ下は0円、境目ちょうどで4,001円
    for name in FLOOR_PROGRAMS:
        edge = min_cost_paid(name)
        if paid(edge, name) <= FLOOR:
            raise _checks.TableError(f"{name}: 境目 {edge}円で支給額が下限を超えていない")
        if paid(edge - 1, name) != 0:
            raise _checks.TableError(f"{name}: 境目の1円下で0円になっていない")

    #    (g) 年額上限なので、同じ総額でも期間が長いほど受取が増える
    _checks.increases_with(
        lambda y: paid_over_years(2_400_000, y, "専門実践＋賃金5パーセント上昇"),
        [1, 2, 3],
        "同じ総額なのに、期間を延ばして受取が増えていない")

    #    (i) 同じ授業料での受取の比は、率の比 4.0 から上限の比 6.4 へ**開いていく**
    _checks.rounding(gap_ratio(300_000), rate_of("専門実践＋賃金5パーセント上昇")
                     / rate_of("一般"), "50万円までの受取の比（＝率の比）")
    _checks.rounding(gap_ratio(1_200_000), cap_of("専門実践＋賃金5パーセント上昇")
                     / cap_of("一般"), "80万円より上での受取の比（＝上限の比）")
    _checks.never_decreases(gap_ratio,
                            [200_000, 500_000, 600_000, 700_000, 800_000, 2_000_000],
                            "授業料が増えたのに受取の比が下がった")
    #        開き始めと開き切りは、2つの「上限に当たる授業料」そのもの
    _checks.rounding(cost_at_cap("一般"), 500_000, "比が開き始める授業料")
    _checks.rounding(cost_at_cap("専門実践＋賃金5パーセント上昇"), 800_000,
                     "比が開き切る授業料")

    #    (h) 表の行が給付の名前で一意
    _checks.unique_by(grid(), lambda r: r["給付"], "上限に当たる授業料の表")

    _checks.assumption_values(ASSUMPTIONS, name="kyoiku")


if __name__ == "__main__":
    check_tables()

    print("=== 上限に当たる授業料は、率が変わっても1円も動かない ===")
    print("教育訓練給付は6つの率で語られます。20・40・50・50・70・80パーセント。")
    print("その率が効くのは、上限に当たるまでの帯だけです。では上限に当たるのはいくらの講座か。")
    for r in grid():
        print(f"  {r['給付']:22s} {r['率']*100:4.0f}パーセント・上限 {r['上限額']:7,d}円"
              f" → 上限に当たる授業料 **{r['上限に当たる授業料']:9,.0f}円**")
    print("  → 6つの率が、**たった2つの数字**に畳まれます。**50万円**と**80万円**。")
    print("     2024年10月の改正は特定一般に10パーセント、専門実践に10パーセントを足しましたが、")
    print("     上限額も同じ比で上がったので、**上限に当たる授業料は1円も動いていません。**")
    print("     率を上げる改正は、**上限に当たる人には何も足していない**ということです。")

    print()
    print("=== 上限を超えると、実質の補助率は授業料に反比例して落ちる ===")
    print("上限を超えた先では、給付は定額です。授業料だけが増えるので、実質の率は落ちます。")
    for name in ("一般", "専門実践＋賃金5パーセント上昇"):
        print(f"  {name}（名目 {rate_of(name)*100:.0f}パーセント）:")
        base = cost_at_cap(name)
        for mult in (1, 1.5, 2, 3, 4):
            c = base * mult
            print(f"    授業料 {c:9,.0f}円 → 出るのは {paid(c, name):7,d}円"
                  f"（実質 **{effective_rate(c, name)*100:4.1f}パーセント**）")
    print(f"  → 名目の率がちょうど半分になるのは、上限に当たる授業料の**2倍**のとき ——")
    print(f"     一般で {cost_at_half_rate('一般'):,.0f}円、"
          f"専門実践で年 {cost_at_half_rate('専門実践＋賃金5パーセント上昇'):,.0f}円。")
    print("     **「80パーセント戻る」と言えるのは、年80万円までの講座だけ**です。")

    print()
    print("=== 下の境目だけは率で動く。上の境目は動かないのに ===")
    print("一般と特定一般には下限があり、支給額が4,000円を超えないと1円も出ません。")
    print("**4,000円は定額**なので、率が上がると下の境目は下がります。")
    for r in floor_grid():
        print(f"  {r['給付']:22s} {r['率']*100:4.0f}パーセント → "
              f"1円でも出る最小の授業料 **{r['1円でも出る最小の授業料']:6,d}円**"
              f"（そのとき {r['そのときの支給額']:,d}円）")
    low = min_cost_paid("一般")
    print(f"  → 一般で授業料 {low - 5:,d}円だと **0円**、{low:,d}円だと **{paid(low, '一般'):,d}円**。")
    print(f"     **5円多く払うと、{paid(low, '一般'):,d}円が出ます。**")
    print("     上の境目は率に比例して設計されているので動かず、")
    print("     下の境目は定額なので率に**反比例**する。**同じ改正が、上下で逆向きに効きます。**")

    print()
    print("=== 同じ「3年に1回」が、年あたりの上限を19倍に変える ===")
    print("教育訓練給付は、前に受けてから3年たたないと次を受けられません。")
    print("同じ3年でも、1回で受け取れる額が違うので、年あたりに直すと差が開きます。")
    rows = [("一般（1回）", cap_of("一般")),
            ("特定一般＋資格取得・就職（1回）", cap_of("特定一般＋資格取得・就職")),
            ("専門実践 1年課程", cap_of("専門実践＋賃金5パーセント上昇")),
            ("専門実践 2年課程", cap_of("専門実践＋賃金5パーセント上昇") * 2),
            (f"専門実践 {MAX_YEARS}年課程",
             cap_of("専門実践＋賃金5パーセント上昇") * MAX_YEARS)]
    for label, total in rows:
        print(f"  {label:26s} 1回で最大 {total:9,d}円 → "
              f"年あたり **{total / INTERVAL_YEARS:9,.0f}円**")
    lo = cap_of("一般") / INTERVAL_YEARS
    hi = cap_of("専門実践＋賃金5パーセント上昇") * MAX_YEARS / INTERVAL_YEARS
    print(f"  → 差は **{hi / lo:.1f}倍**。制度の条文は同じ「3年」なのに、")
    print(f"     {MAX_YEARS}年課程は受講開始から{INTERVAL_YEARS}年で次が始められるので、"
          "**切れ目なく受け続けられます。**")
    print("     「3年に1回」という同じ言葉が、講座の長さで年あたりの上限を19倍に変えている。")

    print()
    print("=== 追加給付は「率」で語られるが、上限に当たると定額になる ===")
    print("専門実践は、資格を取って就職すると50→70パーセント、")
    print("さらに賃金が5パーセント上がると70→80パーセントになります。")
