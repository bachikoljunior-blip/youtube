# ---- 制度の値 ----------------------------------------------------------
KYUYO_MIN = 550_000            # 給与所得控除の最低額（所得税法28条3項）
BASIC_INCOME = 480_000         # 所得税の基礎控除
BASIC_RESIDENT = 430_000       # 住民税の基礎控除
RECONSTRUCTION_TAX = 0.021     # 復興特別所得税（所得税額に対して）
RESIDENT_RATE = 0.10           # 住民税の所得割の標準税率
SPOUSE_INCOME_TAX_RATE = 0.05  # 配偶者本人の所得税率（最低税率の帯）

# 本人（控除を受ける側）の合計所得の3つの列。
# **3分の2・3分の1は割り算ではなく、条文が名指しした整数です。**
MAIN_TIERS = ("900万円以下", "900万円超950万円以下", "950万円超1000万円以下")

# 配偶者の合計所得の段。(その段の上限, 所得税の控除, 住民税の控除) を
# **本人の列ごと**に持つ。上限 None は「そこで0になる」ことを表す。
#
# **段の切れ目は所得税と住民税で同じ**で、違うのは金額のほうです
# （住民税は上限33万円なので、上2段が同じ額でつぶれます）。
STEPS: list[tuple[int, tuple[int, int, int], int]] = [
    #  上限（合計所得）  所得税の控除（900万以下 / 950万以下 / 1000万以下）  住民税
    (950_000,   (380_000, 260_000, 130_000), 330_000),
    (1_000_000, (360_000, 240_000, 120_000), 330_000),
    (1_050_000, (310_000, 210_000, 110_000), 310_000),
    (1_100_000, (260_000, 180_000,  90_000), 260_000),
    (1_150_000, (210_000, 140_000,  70_000), 210_000),
    (1_200_000, (160_000, 110_000,  60_000), 160_000),
    (1_250_000, (110_000,  80_000,  40_000), 110_000),
    (1_300_000, ( 60_000,  40_000,  20_000),  60_000),
    (1_330_000, ( 30_000,  20_000,  10_000),  30_000),
]

# 配偶者特別控除が始まる合計所得（配偶者控除38万円が満額で付く上限）
SPOUSE_DEDUCTION_START = 480_000

# 本人の所得税の限界税率。**この5つで崖の深さが決まります。**
MAIN_TAX_RATES = (0.05, 0.10, 0.20, 0.23, 0.33)

# 条文の値そのもの。**割り算で作らないことを毎回確かめるために置いています。**
ANCHORS = {
    "900万円以下": (380_000, 360_000, 310_000, 260_000, 210_000,
                    160_000, 110_000, 60_000, 30_000),
    "900万円超950万円以下": (260_000, 240_000, 210_000, 180_000, 140_000,
                             110_000, 80_000, 40_000, 20_000),
    "950万円超1000万円以下": (130_000, 120_000, 110_000, 90_000, 70_000,
                              60_000, 40_000, 20_000, 10_000),
}


# ---- 給与収入と合計所得の行き来 ----------------------------------------
def kyuyo_deduction(income: int) -> int:
    """給与所得控除。**この表が扱うのは103万円〜202万円なので、下2帯で足ります。**"""
    if income <= 1_625_000:
        return KYUYO_MIN
    if income <= 1_800_000:
        return round(income * 0.4 - 100_000)
    if income <= 3_600_000:
        return round(income * 0.3 + 80_000)
    if income <= 6_600_000:
        return round(income * 0.2 + 440_000)
    if income <= 8_500_000:
        return round(income * 0.1 + 1_100_000)
    return 1_950_000


def shotoku_of(income: int) -> int:
    """給与収入 → 合計所得金額。"""
    return max(0, income - kyuyo_deduction(income))


def income_of(shotoku: int) -> int:
    """合計所得金額 → それを生む給与収入。**段を年収で言うために要ります。**

    **「収入×40％−10万円」の帯だけ、合計所得は 0.6×収入＋10万円**です
    （ほかの帯は控除が足し算なので「収入×係数−定数」）。**ここだけ符号が逆**で、
    `juminzei` は 2026-08-17 に `+` のまま書いて素通りさせています
    （往復検査がその帯を1点も踏んでいなかった）。**同じ表なので同じ穴があります。**
    """
    if shotoku <= 1_625_000 - KYUYO_MIN:
        return shotoku + KYUYO_MIN
    if shotoku <= round(1_800_000 * 0.6) + 100_000:
        return round((shotoku - 100_000) / 0.6)
    if shotoku <= round(3_600_000 * 0.7) - 80_000:
        return round((shotoku + 80_000) / 0.7)
    if shotoku <= round(6_600_000 * 0.8) - 440_000:
        return round((shotoku + 440_000) / 0.8)
    if shotoku <= round(8_500_000 * 0.9) - 1_100_000:
        return round((shotoku + 1_100_000) / 0.9)
    return shotoku + 1_950_000


# ---- 控除額を引く ------------------------------------------------------
def _tier_index(tier: str) -> int:
    try:
        return MAIN_TIERS.index(tier)
    except ValueError:
        raise _checks.TableError(f"本人の所得の列がありません: {tier}")


def deduction(shotoku: int, tier: str = "900万円以下") -> dict:
    """配偶者の合計所得から、所得税と住民税の控除額を引く。

    **48万円以下は配偶者控除（38万円・住民税33万円）**で、そこから上が
    配偶者特別控除です。**金額が同じなので、段の1つ目は境目に見えません。**
    """
    col = _tier_index(tier)
    if shotoku <= SPOUSE_DEDUCTION_START:
        # 配偶者控除。本人の列で 38 / 26 / 13 万円（住民税は 33 / 22 / 11 万円）
        return {"所得税": (380_000, 260_000, 130_000)[col],
                "住民税": (330_000, 220_000, 110_000)[col],
                "段": 0, "種類": "配偶者控除"}
    for i, (upper, tax_row, resident) in enumerate(STEPS, start=1):
        if shotoku <= upper:
            # 住民税側も本人の列で縮みます。**縮め方は所得税と同じ比**で、
            # 条文が名指ししているのは 33 / 22 / 11 万円の並びです。
            shrink = (1.0, 22 / 33, 11 / 33)[col]
            return {"所得税": tax_row[col],
                    "住民税": _round_to_10000(resident * shrink),
                    "段": i, "種類": "配偶者特別控除"}
    return {"所得税": 0, "住民税": 0, "段": len(STEPS) + 1, "種類": "なし"}


def _round_to_10000(value: float) -> int:
    """住民税側の縮んだ額は万円単位。**端数を残すと段差が1円ずれます。**"""
    return int(round(value / 10_000) * 10_000)


# ---- 世帯の手取りへの効き ----------------------------------------------
def household_tax_saved(shotoku: int, rate: float,
                        tier: str = "900万円以下") -> int:
    """控除があることで、**本人**の税金がいくら減っているか。

    所得税ぶんは復興特別所得税を上乗せします（`RECONSTRUCTION_TAX`）。
    """
    d = deduction(shotoku, tier)
    income_tax = d["所得税"] * rate * (1 + RECONSTRUCTION_TAX)
    resident_tax = d["住民税"] * RESIDENT_RATE
    return round(income_tax + resident_tax)


def spouse_own_tax(shotoku: int) -> int:
    """**配偶者自身**が払う所得税と住民税。稼いだぶんが全部残るわけではない。"""
    taxable_income = max(0, shotoku - BASIC_INCOME)
    taxable_resident = max(0, shotoku - BASIC_RESIDENT)
    income_tax = taxable_income * SPOUSE_INCOME_TAX_RATE * (1 + RECONSTRUCTION_TAX)
    return round(income_tax + taxable_resident * RESIDENT_RATE)


def household_net(shotoku: int, rate: float, tier: str = "900万円以下") -> int:
    """世帯の手取りのうち、**配偶者の収入で動く分だけ**を取り出した額。

    ＝ 配偶者の給与収入 − 配偶者自身の税 ＋ 控除で本人が浮かせた税。
    **本人の給与そのものは、どの段でも同じなので入れていません**
    （入れても全部の行に同じ定数が乗るだけで、崖の深さは変わりません）。
    """
    return (income_of(shotoku) - spouse_own_tax(shotoku)
            + household_tax_saved(shotoku, rate, tier))


# ---- 9つの崖 ----------------------------------------------------------
def cliff(step: int, rate: float, tier: str = "900万円以下") -> dict:
    """段を1円またいだとき、世帯の手取りがいくら減るか。

    `step` は 1〜9（`STEPS` の何段目を出るか）。
    **またいだ側は合計所得が1円多いだけ**なので、稼ぎの増えぶんは1円です。
    """
    if not 1 <= step <= len(STEPS):
        raise _checks.TableError(f"段は1〜{len(STEPS)}です: {step}")
    edge = STEPS[step - 1][0]
    before, after = deduction(edge, tier), deduction(edge + 1, tier)
    saved_before = household_tax_saved(edge, rate, tier)
    saved_after = household_tax_saved(edge + 1, rate, tier)
    return {
        "段": step,
        "合計所得の境目": edge,
        "年収でいうと": income_of(edge),
        "所得税の控除": before["所得税"],
        "所得税の控除（またいだ後）": after["所得税"],
        "所得税の控除の減り": before["所得税"] - after["所得税"],
        "住民税の控除": before["住民税"],
        "住民税の控除（またいだ後）": after["住民税"],
        "住民税の控除の減り": before["住民税"] - after["住民税"],
        "世帯の手取りの減り": saved_before - saved_after,
        "住民税が動いたか": before["住民税"] != after["住民税"],
    }


def cliffs(rate: float, tier: str = "900万円以下") -> list[dict]:
    """9段ぶんまとめて。"""
    return [cliff(i, rate, tier) for i in range(1, len(STEPS) + 1)]


def recovery(step: int, rate: float, tier: str = "900万円以下") -> dict:
    """崖で減ったぶんを取り返すには、あといくら稼げばいいか。

    **段の中では控除が動かない**ので、稼いだぶんから配偶者自身の税を引いた
    残りだけが積み上がります。**その残りの率で割れば、必要な追加の年収**が出ます。
    """
    c = cliff(step, rate, tier)
    edge = c["合計所得の境目"]
    base = household_net(edge, rate, tier)
    # またいだ直後から、1万円ずつ合計所得を増やして元に戻る点を探す。
    # **段の上限を超えると次の崖に落ちる**ので、そこで打ち切ります。
    upper = STEPS[step][0] if step < len(STEPS) else edge + 2_000_000
    got, extra = None, None
    shotoku = edge + 1
    while shotoku <= upper:
        if household_net(shotoku, rate, tier) >= base:
            got, extra = shotoku, income_of(shotoku) - c["年収でいうと"]
            break
        shotoku += 1_000
    return {
        "段": step,
        "年収でいうと": c["年収でいうと"],
        "世帯の手取りの減り": c["世帯の手取りの減り"],
        "元に戻る合計所得": got,
        "あと必要な年収": extra,
        "同じ段の中で戻るか": got is not None and got <= upper,
    }


def wall_150() -> dict:
    """**「150万円の壁」の正体**。9段のうち何段目で、深さは何番目か。"""
    rows = cliffs(0.20)
    edge = shotoku_of(1_500_000)
    step = next(r for r in rows if r["合計所得の境目"] >= edge)
    depths = sorted((r["世帯の手取りの減り"] for r in rows), reverse=True)
    return {
        "年収": 1_500_000,
        "合計所得": edge,
        "何段目か": step["段"],
        "落差": step["世帯の手取りの減り"],
        "深さの順位": depths.index(step["世帯の手取りの減り"]) + 1,
        "いちばん深い崖": depths[0],
        "いちばん深い崖との比": round(depths[0] / step["世帯の手取りの減り"], 2),
    }


def zero_income() -> dict:
    """控除が0になる年収。**世に言う「201万6千円の壁」の裏取り。**"""
    last = STEPS[-1][0]
    return {"合計所得": last, "年収でいうと": income_of(last),
            "1円こえた年収": income_of(last + 1)}


def check_tables() -> None:
    """制度の値と計算の向きを確かめる。**壊れた数字で台本を書かせない。**"""
    # 1. 法令が名指ししている値
    _checks.statutory(KYUYO_MIN, 550_000, "給与所得控除の最低額",
                      source="所得税法28条3項（2020年分から）")
    _checks.statutory(BASIC_INCOME, 480_000, "所得税の基礎控除",
                      source="所得税法86条")
    _checks.statutory(BASIC_RESIDENT, 430_000, "住民税の基礎控除",
                      source="地方税法314条の2")
    _checks.statutory(SPOUSE_DEDUCTION_START, 480_000,
                      "配偶者特別控除が始まる合計所得", source="所得税法83条の2")
    _checks.ratio(RECONSTRUCTION_TAX, "復興特別所得税")
    _checks.ratio(RESIDENT_RATE, "住民税の所得割の標準税率")
    _checks.ratio(SPOUSE_INCOME_TAX_RATE, "配偶者本人の所得税率")

    # 2. **条文の値そのものと突き合わせる。**
    #    ここが本体です —— 3分の2・3分の1は割り算ではなく、条文の整数です。
    #    38万円の3分の2は 25.33万円ですが、条文は 26万円と書いています。
    for col, tier in enumerate(MAIN_TIERS):
        got = tuple(row[1][col] for row in STEPS)
        if got != ANCHORS[tier]:
            raise _checks.TableError(
                f"{tier} の列が条文と違います: {got} ≠ {ANCHORS[tier]}")
    # **割り算で作っていたら落ちること**を、逆から見ておく。
    divided = tuple(round(v * 2 / 3 / 10_000) * 10_000
                    for v in ANCHORS["900万円以下"])
    if divided == ANCHORS["900万円超950万円以下"]:
        raise _checks.TableError(
            "2列目が「3分の2の割り算」と一致しました。条文の整数でないおそれ")

    # 3. 表の形
    _checks.ascending([u for u, _t, _r in STEPS], "段の上限", strict=True)
    _checks.unique_by(STEPS, lambda r: r[0], "段の上限")
    for col, tier in enumerate(MAIN_TIERS):
        # 控除は段が上がるほど減る（同額の段は無い）
        _checks.ascending([row[1][col] for row in STEPS][::-1],
                          f"{tier} の控除額", strict=True)
    # 住民税側は上2段が同額。**strict にすると落ちるので、ここだけ非 strict**
    _checks.ascending([r for _u, _t, r in STEPS][::-1], "住民税の控除額")

    # 4. 給与収入と合計所得の行き来。**帯の切れ目とその内側を踏むこと**
    for income in (550_000, 1_030_000, 1_500_000, 1_624_999, 1_625_000,
                   1_680_000, 1_799_999, 1_800_000, 1_800_001,
                   2_016_000, 2_100_000, 3_599_999, 3_600_000):
        got = income_of(shotoku_of(income))
        if abs(got - income) > 1:
            raise _checks.TableError(
                f"給与収入{income:,}円の往復: {got:,} になった")
    _checks.increases_with(shotoku_of,
                           (1_030_000, 1_500_000, 1_700_000, 1_900_000,
                            2_500_000),
                           "給与収入が増えたのに合計所得が増えていない")
    _checks.increases_with(income_of,
                           (480_000, 950_000, 1_100_000, 1_330_000,
                            1_500_000),
                           "合計所得が増えたのに、それを生む給与収入が増えていない")

    # 5. **主題その1**: 段の1つ目だけ、住民税が動かない
    rows = cliffs(0.20)
    moved = [r["段"] for r in rows if r["住民税が動いたか"]]
    if moved != list(range(2, len(STEPS) + 1)):
        raise _checks.TableError(
            f"住民税が動く段が想定と違います: {moved}")

    # 6. **主題その2**: 崖の深さは3種類以上に分かれる。
    #
    #    **ここは最初 `< 5` で書いて落ちました**（2026-08-17）。実際は
    #    **[4084, 12210, 15210×5, 9126×2] の4種類**で、真ん中の5段が
    #    まったく同じ落差です（どれも控除が 5万円 / 5万円 ずつ減るため）。
    #    **「9段ぜんぶ深さが違う」は思い込みで、事実は逆でした** ——
    #    ちがうのは端の4段だけです。`_template.py` が「docstring は最後」と
    #    言っているのは、この形の書き損じを止めるためです。
    depths = [r["世帯の手取りの減り"] for r in rows]
    if len(set(depths)) < 3:
        raise _checks.TableError(f"崖の深さがそろいすぎています: {depths}")
    _checks.greater(max(depths), min(depths) * 2,
                    "いちばん深い崖が、いちばん浅い崖の2倍に届かない")

    # 7. **主題その3**: 崖は本人の税率が高いほど深い
    _checks.increases_with(lambda r: cliff(3, r)["世帯の手取りの減り"],
                           MAIN_TAX_RATES,
                           "本人の税率が上がったのに崖が深くなっていない")

    # 8. **主題その4**: 控除が0になるのは年収201万6千円のあたり
    z = zero_income()
    _checks.digits(z["年収でいうと"], 2_000_000, 2_030_000,
                   "配偶者特別控除が0になる直前の年収")

    # 9. **崖はどれも「1円で減る」向きであること。** 0や負なら崖ではない
    for r in rows:
        if r["世帯の手取りの減り"] <= 0:
            raise _checks.TableError(
                f"{r['段']}段目の落差が {r['世帯の手取りの減り']} 円です")

    # 10. **取り返せること。** 段の中で戻らないなら、それは崖ではなく壁
    for step in range(1, len(STEPS) + 1):
        rec = recovery(step, 0.20)
        if rec["元に戻る合計所得"] is None:
            raise _checks.TableError(f"{step}段目が取り返せません")

    # 11. 前提の文に、値が書いてあること
    _checks.assumption_values(ASSUMPTIONS, name="haiguusha")


