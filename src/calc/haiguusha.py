    "したがって、ここで言えるのは税金の側の話だけです。"
    "社会保険料が発生する年収では、ここで出した額よりずっと大きく手取りが減ります",
    "配偶者の収入は給与だけとしています。給与所得控除の最低額は55万円です",
    "給与所得控除は式をそのまま使い、収入金額を4千円単位に切り下げる丸めはしていません。"
    "そのため境目の年収は、丸めたあとの値と数千円ずれます",
    "配偶者本人にかかる所得税と住民税も引いています。"
    "所得税は5パーセント、住民税の所得割は10パーセントで置いています",
    "所得税には復興特別所得税2.1パーセントを上乗せしています",
    "配偶者本人の基礎控除は所得税48万円、住民税43万円としています",
    "社会保険料控除・生命保険料控除などの、ほかの所得控除は0円としています。"
    "実際にあれば、ここで出した税額より小さくなります",
