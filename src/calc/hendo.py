def guard_grid(rates: tuple[float, ...] = (0.020, 0.030, 0.035, 0.040, 0.050),
               principal: int = PRINCIPAL, years: int = YEARS,
               start: float = START_RATE, at: int = RISE_AT) -> list[dict]:
    """**未払利息を1円も出さないために、毎月いくら上乗せしておけばよいか。**

    ## なぜこの表を足したか（2026-09-01・規則3 の improve）

    上の7つの表は、**何が起きるか**を全部 出しています。
    **どうすれば起きないか**を出す表が1つもありませんでした ——
    視聴者が自分の金で動ける数は、そこにしかありません。

    ## 出し方（掛け算1回。近似ではありません）

    未払利息が積むのは、**その月の利息が返済額を上回った月**だけです
    （`simulate` の `payment >= interest` の枝）。据え置きの60回のあいだ
    返済額は動かないので、**上回るかどうかは「上がった月の利息」で決まります。**

        上がった月の利息 ＝ floor(その月の残高 × 新しい年利 ÷ 12)
        要る上乗せ       ＝ max(0, その利息 − いまの返済額)

    **残高は「上がる前」の返済で決まるので、上乗せ額の計算に上げ幅は要りません**
    （残高は上げ幅に依らない）。そして**上乗せするほど残高は速く減る**ので、
    上がった月がいちばん厳しく、**そこを越えれば以降は自動で越えます。**
    ＝ この1点だけで足ります。

    **これは「元金が減る額」ではありません。** ちょうどこの額だと、その月の
    元金充当は 0円 です（利息とぴったり同額）。**未払利息が積まないだけ** ——
    元金を動かしたいなら、この上に積むこと。

    ## 覆る条件

    - ~~**未払利息に利息を付ける約款では、これでは足りません**（`ASSUMPTIONS` の4）~~
      **→ 誤りでした**（2026-09-01 に実測して取り消した）。**この額でちょうど足ります。**
      利息が乗る相手は**積んだ未払利息**で、この額はそれを **0円 に保つ**からです
      —— 0円 に何を掛けても 0円。実測（付ける約款で回し直した）:

          3.5% 上乗せ  8,552円 → 未払利息 **0円**
          4.0% 上乗せ 22,753円 → 未払利息 **0円**
          5.0% 上乗せ 51,155円 → 未払利息 **0円**

      **＝ 止めるコストは、約款では変わりません。**
      変わるのは**止めなかったときの代償**だけです（`compound_grid()`：
      4.0% で一括が **×1.61**、5.0% で **×3.17**）。
      **この2つを混ぜないこと** —— 混ぜると「約款によっては打つ手が無い」に
      読めますが、実際は**打つ手は同じで、打たなかったときの穴が深いだけ**です
    - 金利が**二段以上**上がる契約では、上がるたびに引き直すこと
      （この表は `path` が一段の場合を出しています）
    - 上乗せを「繰上返済」で入れると、多くの銀行では**残高が直接 減る**ので
      要る額はこれより小さくなります。ここは**毎月の返済額に足す**形の数です
    """
    base = simulate(principal, years, ((0, start),))
    # 上がる月の**直前**の残高（`rows[m]["残高"]` は、その月の返済の**あと**）。
    before = principal if at == 0 else base["rows"][at - 1]["残高"]
    pay = base["first_payment"]
    rows = []
    for r in rates:
        interest = interest_of(before, r)
        extra = max(0, interest - pay)
        rows.append({
            "上がった先の年利": f"{r * 100:.1f}%",
            "上がった月の残高": before,
            "その月の利息": interest,
            "いまの返済額": pay,
            "要る上乗せ": extra,
            "上乗せ後の毎月": pay + extra,
            "元の何倍": f"{(pay + extra) / pay:.2f}倍",
        })
    return rows


def compound_grid(rates: tuple[float, ...] = (0.035, 0.040, 0.050),
                  principal: int = PRINCIPAL, years: int = YEARS,
                  start: float = START_RATE, at: int = RISE_AT) -> list[dict]:
    """**未払利息にも利息が付く約款だと、最終回の一括はいくらになるか。**

    ## なぜこの表を足したか（2026-09-01・規則3 の improve）

    `ASSUMPTIONS` の4 は 08-31 から
    「未払利息には利息を付けない前提で積んでいます。**利息を付ける約款なら、
    この計算より大きくなります**」と言っています。
    **どの表も、いくら大きくなるかを出していませんでした。**

    **自分で名指しした穴を、自分で埋めていない**形です。しかも向きが悪い ——
    **断りは「小さく出している」側**なので、読んだ人は
    「まあ多少は大きいのだろう」と受け取ります。実際は:

        上がった先 3.5%   一括   410,496円 →   523,887円（**×1.28**）
        上がった先 4.0%   一括 1,094,544円 → 1,765,742円（**×1.61**）
        上がった先 5.0%   一括 4,164,960円 → **13,193,096円**（**×3.17**）

    **5.0% では、一括が 1,300万円 を超えます。** 借入 3,500万円 の **38%** です。

    ## なぜ 5.0% だけ桁が変わるか（**未払利息が 0 で止まらなくなる**）

    利息を付けない約款では、未払利息は「毎月の不足ぶん」を足すだけなので
    **一次で増えます**。付ける約款では、その累計にも利率が乗るので
    **複利で増えます** —— そして未払利息が増えるほど翌月の利息が増え、
    不足がさらに増える。**5.0% では 420回のあいだに残高が返し切れず**、
    一括に **残高 6,240,621円 ＋ 未払利息 6,952,475円** が残ります
    （利息を付けない側は残高 0円・未払利息だけ）。

    ## この表と `guard_grid()` を、混ぜないこと

    **止めるのに要る上乗せ額は、約款で1円も変わりません**
    （`guard_grid()` の「覆る条件」に実測）。**0円 に何を掛けても 0円** だからです。
    **変わるのは、止めなかったときの代償だけ。**

    ## 覆る条件

    - 未払利息に**別の**（多くは低い）利率を当てる約款を出すようになったら、
      `simulate()` に利率をもう1つ渡すこと。いまは**同じ利率**を乗せています
    - 未払利息を月々の返済へ割り付ける約款を出すなら、`simulate()` の
      見直しの枝の註（「**両方に乗せないこと**」）が先に効きます
    """
    rows = []
    for r in rates:
        path = ((0, start), (at, r))
        a = simulate(principal, years, path)
        b = simulate(principal, years, path, compound_unpaid=True)
        rows.append({
            "上がった先": f"{r * 100:.1f}%",
            "付けない約款の一括": a["balloon"],
            "付ける約款の一括": b["balloon"],
            "差": b["balloon"] - a["balloon"],
            "何倍": f"{b['balloon'] / a['balloon']:.2f}倍" if a["balloon"] else "—",
            "付ける約款の残り残高": b["balloon"] - b["unpaid"],
        })
    return rows


def split_grid(rates: tuple[float, ...] = (0.020, 0.030, 0.040, 0.050),
               principal: int = PRINCIPAL, years: int = YEARS,
               start: float = START_RATE, at: int = RISE_AT) -> list[dict]:
    """**その差額は、2つのルールのどちらが作っているのか。**

    ## なぜこの表を足したか（2026-09-01・規則3 の improve）

    `rule_grid()` は **「ルールあり」対「ルールなし」の2択**しか出しません。
    ところが「ルール」は**別々の2つ**です ——
    **5年ルール**（返済額を60回すえ置く）と
    **125パーセントルール**（見直しの上げ幅を1.25倍で頭打ちにする）。
    **付いている契約・片方だけの契約・どちらも無い契約が、実際にあります**
    （`ASSUMPTIONS` の3 が「付いていない契約もある」と言っている相手）。

    **この計算は最初から両方を別の旗で持っていました**
    （`simulate(five_year_rule=..., cap_125=...)`）。
    **それでも、どの表も一度も分けていませんでした** ——
    動画は 4.0% の例で「ルールありのほうが **5,716,767円 多い**」と言うだけで、
    **その 5,716,767円 の内訳を言っていません。**

    ## 実測（3,500万円・35年・当初0.5%・13回目から上昇）

    **足していく順に置くと、内訳は円まで足し合わさります**:

        上がった先 4.0%
          どちらも無し                63,495,265円
          ＋5年ルール                 65,120,750円   **＋1,625,485円**（28.4%）
          ＋125パーセントルール       69,212,032円   **＋4,091,282円**（71.6%）
                                                     計 5,716,767円 ＝ `rule_grid()` の「差」

    **重いのは 125パーセントルールのほうです。** そして金利が高いほど偏ります ——
    125 側の取り分は 2.0% で **21.6%**、3.0% で **48.4%**、4.0% で **71.6%**、
    5.0% で **81.5%**。

    **理由は、止まる場所が違うから**です。5年ルールは**60回で必ず解けます**
    （61回目に必要額まで上がる）。125パーセントルールは
    **上がり切るまで解けません** —— `catchup_grid()` の実測で、
    4.0% の例は **21年目（241回目）**まで頭打ちが続きます。
    5年ルールが 48回ぶんの未払利息（1,092,144円）を作るのに対し、
    125 側は**そのあと 180回、返済額を実力より低く抑え続けます。**

    ## 「125パーセントルールだけ」を欄にしていない理由（**この模型では出せません**）

    2×2 の4つ目の枡（`five_year_rule=False, cap_125=True`）は
    **この模型では意味のある数になりません。**
    5年ルールを外すと、見直しは「**利率が動いた回**」にしか起きません
    （`simulate()` の `due`）。`ASSUMPTIONS` の2 のとおり
    **この計算では利率は一段だけ動く**ので、見直しは**生涯に1回きり**になり、
    そこで掛かった 1.25倍 の頭打ちが**420回のあいだ一度も解けません。**
    出てくる総支払額は 81,524,957円（4.0%）で、**両方付いた契約より 1,200万円 多い** ——
    ルールを1つ外したのに重くなる、という**模型の作りが出した数**です。

    **これは「125だけの契約は不利」という発見ではありません。** 実物では
    利率が動くたびに見直しが入り、そのたびに 1.25倍 まで上げ直せます。
    **だから欄にしません。**

    ## 覆る条件

    - `ASSUMPTIONS` の2 を変えて、**利率を複数回 動かす**ようになったら、
      4つ目の枡は意味のある数になります。そのときは
      `five_year_rule=False, cap_125=True` の列を足すこと
      （上の「欄にしていない理由」ごと書き直すこと）
    - 内訳は**足す順**で変わりうる量です（片方だけを外した2通りの
      引き算は一致しません）。ここは「無し → 5年 → 125」の**一本道**で、
      **和は `rule_grid()` の「差」に円まで一致します**
      （検査 `check_tables()` の 10）。**別の順で出した数と混ぜないこと**
    """
    rows = []
    for r in rates:
        path = ((0, start), (at, r))
        none = simulate(principal, years, path,
                        five_year_rule=False, cap_125=False)["total"]
        five = simulate(principal, years, path,
                        five_year_rule=True, cap_125=False)["total"]
        both = simulate(principal, years, path,
                        five_year_rule=True, cap_125=True)["total"]
        gap = both - none
        rows.append({
            "上がった先": f"{r * 100:.1f}%",
            "どちらも無し": none,
            "5年ルールだけ": five,
            "5年ルールの寄与": five - none,
            "両方": both,
            "125%ルールの寄与": both - five,
            "差の合計": gap,
            "125%の取り分": f"{(both - five) / gap * 100:.1f}%" if gap else "—",
        })
    return rows

