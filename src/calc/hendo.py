def check_tables() -> None:
    """契約の値と、計算の向きを確かめる。**壊れた数字で台本を書かせない。**"""
    _checks.assumption_values(ASSUMPTIONS, name="hendo")

    # 1. 契約の値（**法令ではないので `statutory` は使わない**）
    if REVIEW_MONTHS != 60:
        raise _checks.TableError(
            f"5年ルールの据え置き回数が {REVIEW_MONTHS}。5年 ＝ 60回のはず")
    if CAP_RATIO != 1.25:
        raise _checks.TableError(
            f"125パーセントルールの上限が {CAP_RATIO}。1.25 のはず")

    # 2. 元利均等の式が、教科書の形と合っていること
    #    金利0なら「元金 ÷ 回数」に落ちる
    _checks.rounding(level_payment(3_600_000, 0.0, 360), 10_000,
                     "金利0・360回の返済額")
    #    3,500万円・35年・0.5パーセントの毎月返済額
    _checks.rounding(level_payment(PRINCIPAL, START_RATE,
                                   YEARS * MONTHS_PER_YEAR), 90_855,
                     "3,500万円・35年・0.5パーセントの毎月返済額")

    # 3. 向き —— 上がった先が高いほど、未払利息も総支払額も増える
    _checks.increases_with(
        lambda r: simulate(PRINCIPAL, YEARS,
                           ((0, START_RATE), (RISE_AT, r)))["total"],
        [0.02, 0.03, 0.04, 0.05],
        "上がった先の金利が高いのに、総支払額が増えていない")
    _checks.increases_with(
        lambda r: simulate(PRINCIPAL, YEARS,
                           ((0, START_RATE), (RISE_AT, r)))["unpaid"],
        [0.035, 0.04, 0.045, 0.05],
        "上がった先の金利が高いのに、未払利息が増えていない")

    # 4. **この計算の主題そのもの** —— 遅く上がるほど未払利息は小さい
    _checks.decreases_with(
        lambda m: simulate(PRINCIPAL, YEARS,
                           ((0, START_RATE), (m, 0.040)))["unpaid"],
        [0, 12, 24, 36, 48],
        "上がるのが遅いのに、未払利息が減っていない")

    # 5. **ルールが付いたほうが総額は多い**（この表の一番の主張）
    for r in (0.02, 0.03, 0.04, 0.05):
        on = simulate(PRINCIPAL, YEARS, ((0, START_RATE), (RISE_AT, r)))
        off = simulate(PRINCIPAL, YEARS, ((0, START_RATE), (RISE_AT, r)),
                       five_year_rule=False, cap_125=False)
        _checks.greater(on["total"], off["total"],
                        f"上がった先 {r * 100:.1f}% で、"
                        "ルールありの総支払額がルールなし以下")

    # 6. **元金が止まる金利は、借入額に依らない**（割ると消える）
    seen = {row["元金が止まる金利"] for row in amount_grid()}
    if len(seen) != 1:
        raise _checks.TableError(
            f"元金が止まる金利が借入額で変わっている: {sorted(seen)}。"
            "返済額は元金に比例するので、割れば消えるはず")

    # 7. 期間が長いほど、元金が止まる金利は低い（同じ当初金利で）
    _checks.decreases_with(
        lambda y: freeze_rate(
            PRINCIPAL, level_payment(PRINCIPAL, START_RATE,
                                     y * MONTHS_PER_YEAR)),
        [20, 25, 30, 35],
        "期間が長いのに、元金が止まる金利が下がっていない")

    # 9. **保存則 —— 払った総額は、元金と利息の合計と1円もずれない。**
    #
    # **この検査が無かったせいで、2026-08-31 まで総支払額が過大でした**
    # （3,500万円・35年・0.5%→4.0% で **1,324,334円**。動画の冒頭に出る
    #  「ルールあり／なしの差」が 6,611,976円 と、90万円ほど大きく出ていた）。
    # 原因は見直しの `need` に未払利息を混ぜていたことで、**残高が予定より
    # 早く尽き、そのあとも満額を数え、さらに未払利息を満額 請求**していました。
    #
    # 1〜8 はどれも**向き**（増えるか・減るか・重なっていないか）しか見ておらず、
    # **量が合っているか**を見る検査が1つもありませんでした。
    # 向きの検査は、全部の行が同じ倍率でずれても通ります。
    #
    # 上下 1円 は許します（利息は切り捨て・返済額は切り上げなので、
    # 端数が最終回に寄ります）。
    for rate, rule in ((0.040, True), (0.040, False),
                       (0.030, True), (0.050, True), (0.005, True)):
        got = simulate(PRINCIPAL, YEARS, ((0, START_RATE), (RISE_AT, rate)),
                       five_year_rule=rule, cap_125=rule)
        interest_sum = sum(row["利息"] for row in got["rows"])
        _checks.conserves(
            got["total"], [PRINCIPAL, interest_sum],
            f"上がった先 {rate * 100:.1f}%・ルール{'あり' if rule else 'なし'} の総支払額",
            names=["元金", "利息"])

    # 8. 表の行が重なっていないこと
    _checks.unique_by(rise_grid(), lambda r: r["上がった先"], "上がった先")
    _checks.unique_by(timing_grid(), lambda r: r["何回目から上がるか"],
                      "上がる回")

    # 10. **`guard_grid` を、`simulate` と突き合わせる**（2026-09-01 に足した）。
    #
    # あの表は掛け算1回で出しています（据え置き中は返済額が動かないので、
    # 上がった月の利息だけで決まる）。**同じ答えが、回ごとに解く側からも
    # 出ることを確かめます** —— 出どころが2つあるなら、片方が壊れたら気づけます。
    #
    #     要る上乗せ 0円   → その金利では未払利息が 1円も積まない
    #     要る上乗せ >0円  → その金利では必ず積む
    #
    # **この検査が守るのは向きです。** 上乗せした後の額（＝ 利息と同額）で
    # 元金が 0円 になることは、`payment >= interest` の枝がそのまま言っています。
    for row in guard_grid():
        rate = float(row["上がった先の年利"].rstrip("%")) / 100
        got = simulate(PRINCIPAL, YEARS, ((0, START_RATE), (RISE_AT, rate)))
        if row["要る上乗せ"] == 0 and got["unpaid"] != 0:
            raise _checks.TableError(
                f"上がった先 {row['上がった先の年利']}: guard_grid は上乗せ不要と"
                f"言っているのに、simulate は未払利息 {got['unpaid']:,}円 を積んでいる")
        if row["要る上乗せ"] > 0 and got["unpaid"] == 0:
            raise _checks.TableError(
                f"上がった先 {row['上がった先の年利']}: guard_grid は上乗せ "
                f"{row['要る上乗せ']:,}円 が要ると言っているのに、"
                "simulate は未払利息を1円も積んでいない")
        # **上乗せ後の額は、その月の利息とぴったり同じ**（元金充当 0円 の点）
        if row["要る上乗せ"] > 0 and row["上乗せ後の毎月"] != row["その月の利息"]:
            raise _checks.TableError(
                f"上がった先 {row['上がった先の年利']}: 上乗せ後の毎月 "
                f"{row['上乗せ後の毎月']:,} が、その月の利息 "
                f"{row['その月の利息']:,} と一致しない")
    _checks.unique_by(guard_grid(), lambda r: r["上がった先の年利"], "上がった先の年利")

    # 11. **`compound_grid` の2つの主張**（2026-09-01 に足した）。
    #
    #     (1) 付ける約款のほうが、**必ず**重い（`ASSUMPTIONS` の4 の向き）
    #     (2) **止めるのに要る上乗せ額は、約款で変わらない** ——
    #         `guard_grid` の額を毎月 上乗せすれば、付ける約款でも未払利息は 0円
    #
    # (2) は `guard_grid` の「覆る条件」が **08-31 から誤って逆を書いていた**所です
    # （「この約款ではこれでは足りません」）。**0円 に何を掛けても 0円** なので、
    # ちょうど足ります。**動画で言う話が変わるので、機械の側で守ります。**
    for row in compound_grid():
        if row["付ける約款の一括"] < row["付けない約款の一括"]:
            raise _checks.TableError(
                f"上がった先 {row['上がった先']}: 未払利息に利息を付けたのに"
                "一括が小さくなっている（`ASSUMPTIONS` の4 と向きが逆）")
    for row in guard_grid():
        if row["要る上乗せ"] <= 0:
            continue
        rate = float(row["上がった先の年利"].rstrip("%")) / 100
        # 「毎月の返済額に上乗せする」を、回ごとに解く側で回し直す
        bal, unpaid, pay = PRINCIPAL, 0, row["上乗せ後の毎月"]
        for m in range(YEARS * MONTHS_PER_YEAR):
            r_m = rate_at(m, ((0, START_RATE), (RISE_AT, rate)))
            interest = interest_of(bal + unpaid, r_m)      # ← 付ける約款
            if pay >= interest:
                bal -= min(pay - interest, bal)
            else:
                unpaid += interest - pay
            if bal <= 0:
                break
        if unpaid != 0:
            raise _checks.TableError(
                f"上がった先 {row['上がった先の年利']}: guard_grid の上乗せ "
                f"{row['要る上乗せ']:,}円 で、付ける約款だと未払利息 "
                f"{unpaid:,}円 が残る（`guard_grid` の「覆る条件」を書き直すこと）")


    # 12. **`split_grid` の内訳は、`rule_grid` の「差」に円まで足し合わさる**
    #     （2026-09-01 に足した）。
    #
    # 内訳は「無し → 5年 → 125」の一本道で作っています。**足す順を変えると
    # 数は変わりますが、和は変わりません** —— その和が `rule_grid()` の
    # 「差」と1円でもずれたら、どちらかの列が別の前提で解かれています。
    # **動画は内訳のほうを読み上げるので、機械の側で縛ります。**
    #
    # **向きも縛ります**: 5年ルールは60回で必ず解けるのに対し、
    # 125パーセントルールは上がり切るまで解けない（`catchup_grid()` で
    # 4.0% は 241回目まで）。**だから 4.0% 以上では 125 側のほうが重い。**
    _by_rate = {row["上がった先"]: row for row in rule_grid()}
    for row in split_grid():
        want = _by_rate[row["上がった先"]]["差"]
        _checks.conserves(
            want, [row["5年ルールの寄与"], row["125%ルールの寄与"]],
            f"上がった先 {row['上がった先']} の rule_grid の「差」",
            names=["5年ルールの寄与", "125%ルールの寄与"])
        if row["どちらも無し"] > row["5年ルールだけ"]:
            raise _checks.TableError(
                f"上がった先 {row['上がった先']}: 5年ルールを付けたのに"
                "総支払額が減っている")
    for row in split_grid(rates=(0.040, 0.050)):
        if row["125%ルールの寄与"] <= row["5年ルールの寄与"]:
            raise _checks.TableError(
                f"上がった先 {row['上がった先']}: 125%ルールの寄与 "
                f"{row['125%ルールの寄与']:,} が 5年ルールの寄与 "
                f"{row['5年ルールの寄与']:,} 以下。"
                "未払利息が積む帯では 125 側が重いはず（`split_grid` の註）")
    _checks.unique_by(split_grid(), lambda r: r["上がった先"], "上がった先")

    # 13. **`overtake_grid` の主張 —— ルールありの毎月は、必ず追い越す**
    #     （2026-09-01 に足した）。
    #
    # 5 は**総支払額**の向きだけを縛っています。**毎月のほうは、どの検査も
    # 見ていませんでした** —— 動画が「据え置かれる」で止まっていた所です。
    #
    # 縛るのは3つ:
    #   (1) どの金利でも、ルールありの**最後の毎月**は、どちらも無しの毎月より高い
    #   (2) 追い越す回は、据え置きが解けたあと（＝ 61回目以降）にしか来ない
    #   (3) その回の返済額は、`simulate()` の見直しの回に実際に在る
    #
    # **(1) が破れたら、動画の締めを書き直すこと**（「あとで上乗せして返す」が
    # 成り立たなくなります）。**平均と混ぜないこと** —— 据え置きの60回を
    # 平均に入れると 1.0倍 を割ります（`overtake_grid` の「覆る条件」）。
    for row in overtake_grid():
        rate = float(row["上がった先"].rstrip("%")) / 100
        got = simulate(PRINCIPAL, YEARS, ((0, START_RATE), (RISE_AT, rate)))
        if row["追い越す回"] is None:
            raise _checks.TableError(
                f"上がった先 {row['上がった先']}: ルールありの毎月が、"
                "どちらも無しの毎月を一度も追い越していない"
                "（`overtake_grid` の主張が成り立っていません）")
        _checks.greater(
            row["ルールありの最後の毎月"], row["どちらも無しの毎月"],
            f"上がった先 {row['上がった先']} の、ルールありの最後の毎月")
        if row["追い越す回"] <= REVIEW_MONTHS:
            raise _checks.TableError(
                f"上がった先 {row['上がった先']}: 追い越す回 {row['追い越す回']} が"
                f"据え置きの {REVIEW_MONTHS}回 の中に来ている。"
                "据え置き中は返済額が動かないはず")
        if row["追い越す回"] not in {p["月"] for p in got["payments"]}:
            raise _checks.TableError(
                f"上がった先 {row['上がった先']}: 追い越す回 {row['追い越す回']} が"
                "`simulate()` の見直しの回に無い")
    _checks.unique_by(overtake_grid(), lambda r: r["上がった先"], "上がった先")


