"""**予定納税 —— 課税所得が1円増えるだけで、翌年に10万円を先に払わされる。**

前年の所得税が15万円以上だった人は、翌年の7月と11月に、その3分の1ずつを
前払いさせられる（所得税法第104条）。一般の解説はここで止まる ——
「予定納税基準額が15万円以上なら予定納税」と条文をなぞって終わり。
**その15万円が、所得の側でどこに立っているのかは、どこにも書いていない。**

ここでやっているのは、そこを引き戻す計算です。速算表と復興特別所得税2.1パーセントを
通して、**基準額15万円ちょうどになる課税所得**を1円単位で出し、その1円の左右で
何が起きるかを並べています。

## 出たもの

**1. 崖は課税所得 2,444,150円に立っている。1円手前は0円、崖の上は10万円。**

    課税所得 2,444,149円  →  基準額 149,999円  →  7月 0円・11月 0円
    課税所得 2,444,150円  →  基準額 150,000円  →  7月 50,000円・11月 50,000円

**課税所得が1円ふえると、先に払う額が0円から100,000円に跳ねます。**
制度の側の段差は「15万円か、14万9,999円か」の1円ですが、
**その1円が動かすのは、翌年の資金繰りの10万円**です。

**2. 増えた税は、割合でちょうど3倍になって3月に来る。**
先払いは前年の額で固定されているので、今年ふえたぶんは全部3月の確定申告に乗ります。
先払いが年税額の3分の2なら、3月に残るのは3分の1。**だから増分は3倍に拡大されます。**

    課税所得 500万円 → 年税額が 17.5% ふえると、3月の支払いは **52.4%** ふえる
    課税所得 800万円 → 年税額が 15.3% ふえると、3月の支払いは **45.8%** ふえる
    課税所得1200万円 → 年税額が 16.3% ふえると、3月の支払いは **49.0%** ふえる

**帯がちがっても、比は 3.0倍で揃います。** これは偶然ではなく、
3月に残るのが必ず3分の1だからです（速算表のどの段でも同じ）。

**3. 逆に、所得が落ちても先払いは減りません。** 落ちる幅が
**19.1〜24.2パーセント**を超えると、7月と11月の2回だけで今年の年税額を追い越します。

    前年 500万円 → 19.1% 落ちたところ（404万円）で追い越す
    前年 800万円 → 23.1% 落ちたところ（615万円）で追い越す
    前年2000万円 → 24.2% 落ちたところ（1,516万円）で追い越す

**幅は所得と一緒には動きません**（20.3 → 20.3 → 19.1 → 23.1 → 20.4 → 24.2）。
速算表の段のどこに落ちるかで決まるので、**上の所得ほど余裕がある、とは言えません。**

**4. 減額申請は1円下がれば出せるが、戻る額は所得で3.78倍ちがう。**
課税所得が1パーセント下がったときに減る先払いは、100円あたり **7.20円から27.20円**。
同じ「1パーセント下がった」でも、**低いほうは4分の1しか戻りません。**

**5. 源泉徴収でこれが消える線は、年税額の 26.9パーセントから 95.2パーセントまで開く。**
基準額は源泉徴収税額を引いた後の額なので、引かれていれば予定納税は消えます。
その線を年税額に対する割合で見ると:

    課税所得 300万円  →  年税額の **26.9%** が源泉されていれば消える
    課税所得2000万円  →  年税額の **95.2%** ないと消えない

**所得が上がるほど、源泉徴収では逃がしてもらえなくなります。**

**6. 3分の1にしたときの100円未満の切り捨ては、2回ぶんで最大199.33円。**
基準額150,299円の1回ぶんは50,000円で、150,000円の人と**同額**です。
299円の差は、先払いの上では消えます。

**7. その崖を手前に引いているのは、復興特別所得税2.1パーセントです。**
復興特別所得税が無ければ、崖は課税所得 2,475,000円に立ちます。いまは 2,444,150円。
**課税所得で30,850円ぶん手前**に来ていて、そこで乗っている復興特別所得税は
**わずか3,085円**。**3,085円の税が、100,000円の前払いを発生させています（32.4倍）。**

## 前提の置き方（ここが独自の視点です）

**課税所得を横軸に取り、源泉徴収税額を0円として置いています。** 予定納税基準額は
本来「前年分の所得税額から源泉徴収税額を引いた額」なので、源泉のある人は崖の位置が
右にずれます。**節5がそのずれ幅そのものを出しています。**
また、譲渡所得・一時所得・雑所得の一部など、基準額の計算から除かれるものは
入れていません。**入れると人によって答えが変わり、崖の位置が1円単位で言えなくなります。**
"""
from __future__ import annotations

from . import _checks

ASSUMPTIONS = [
    "予定納税は、前年分の予定納税基準額が15万円以上の人に、"
    "第1期（7月）と第2期（11月）で基準額の3分の1ずつを前払いさせる制度です",
    "予定納税基準額は、前年分の所得税額から源泉徴収税額を引いて、"
    "復興特別所得税2.1パーセントを足した額として置いています",
    "所得税は速算表で出しています。課税所得195万円まで5パーセント、"
    "330万円まで10パーセント・控除97,500円、695万円まで20パーセント・控除427,500円、"
    "900万円まで23パーセント・控除636,000円、1,800万円まで33パーセント・控除1,536,000円、"
    "4,000万円まで40パーセント・控除2,796,000円、それ以上は45パーセント・控除4,796,000円です",
    "源泉徴収税額は0円として置いています。これは崖の位置を1円単位で言うための置き方で、"
    "源泉のある人は崖が右にずれます。ずれ幅そのものも計算に入れてあります",
    "1回ぶんの予定納税額は、3分の1にしてから100円未満を切り捨てています",
    "入れていないもの: 譲渡所得・一時所得など予定納税基準額から除かれる所得、"
    "住民税の予定納付、減額申請が認められるかどうかの判断",
]

# ---- 制度の値 -----------------------------------------------------------
LINE = 150_000          # 予定納税基準額がこの額以上で予定納税が要る（所得税法第104条）
FUKKO_RATE = 0.021      # 復興特別所得税（基準所得税額の2.1パーセント）
SHARE = 3               # 第1期・第2期に、それぞれ基準額の3分の1

# 所得税の速算表（課税所得の上限, 税率, 控除額）。最上段の上限は None
TAX_TABLE: list[tuple[int | None, float, int]] = [
    (1_950_000, 0.05, 0),
    (3_300_000, 0.10, 97_500),
    (6_950_000, 0.20, 427_500),
    (9_000_000, 0.23, 636_000),
    (18_000_000, 0.33, 1_536_000),
    (40_000_000, 0.40, 2_796_000),
    (None, 0.45, 4_796_000),
]


def tax_of(taxable: float) -> float:
    """速算表を引く（基準所得税額。復興特別所得税を含まない）。"""
    for cap, rate, sub in TAX_TABLE:
        if cap is None or taxable <= cap:
            return taxable * rate - sub
    raise ValueError(f"速算表に当たらない: {taxable}")


def base_tax(taxable: int) -> int:
    """課税所得から基準所得税額（円未満切り捨て）。"""
    return int(tax_of(taxable))


def with_fukko(base: int) -> int:
    """復興特別所得税を足した額（円未満切り捨て）。"""
    return int(base * (1 + FUKKO_RATE))


def kijun(taxable: int, withheld: int = 0) -> int:
    """予定納税基準額 ＝（基準所得税額 − 源泉徴収税額）に復興特別所得税を足した額。"""
    return max(0, with_fukko(max(0, base_tax(taxable) - withheld)))


def hitsuyou(kijungaku: int) -> bool:
    return kijungaku >= LINE


def ikkai(kijungaku: int) -> int:
    """1回ぶんの予定納税額。3分の1にして100円未満を切り捨てる。"""
    if not hitsuyou(kijungaku):
        return 0
    return (kijungaku // SHARE) // 100 * 100


def maebarai(kijungaku: int) -> int:
    """7月と11月の合計（＝先に払わされる額）。"""
    return ikkai(kijungaku) * 2


# ---- 節1: 15万円の崖を、所得の側に戻す ---------------------------------
def _taxable_for_kijun(target: int) -> int:
    """予定納税基準額がちょうど `target` 以上になる、いちばん小さい課税所得（円単位）。"""
    lo, hi = 0, 60_000_000
    while lo < hi:
        mid = (lo + hi) // 2
        if kijun(mid) >= target:
            hi = mid
        else:
            lo = mid + 1
    return lo


def cliff() -> list[dict]:
    """崖の1円手前と、崖のちょうど上。"""
    x = _taxable_for_kijun(LINE)
    rows = []
    for label, t in (("崖の1円手前", x - 1), ("崖のちょうど上", x)):
        k = kijun(t)
        rows.append({
            "位置": label,
            "課税所得（円）": t,
            "予定納税基準額（円）": k,
            "7月（円）": ikkai(k),
            "11月（円）": ikkai(k),
            "先に払う合計（円）": maebarai(k),
        })
    return rows


# ---- 節2: 源泉徴収がいくらあれば、予定納税は消えるか --------------------
def genzen() -> list[dict]:
    rows = []
    for t in (3_000_000, 5_000_000, 7_000_000, 10_000_000, 20_000_000):
        full = kijun(t)
        # 基準額が15万円未満になる、いちばん小さい源泉徴収税額
        lo, hi = 0, base_tax(t)
        while lo < hi:
            mid = (lo + hi) // 2
            if kijun(t, mid) < LINE:
                hi = mid
            else:
                lo = mid + 1
        rows.append({
            "課税所得（円）": t,
            "予定納税基準額（源泉0・円）": full,
            "消える源泉徴収税額（円）": lo,
            "年税額に対する割合（パーセント）": round(lo / with_fukko(base_tax(t)) * 100, 1),
        })
    return rows


# ---- 節3: 所得が何パーセント落ちるまでなら、前払いが年税額を超えないか --
def haraisugi() -> list[dict]:
    rows = []
    for t in (2_500_000, 3_500_000, 5_000_000, 8_000_000, 12_000_000, 20_000_000):
        pay = maebarai(kijun(t))
        # 今年の年税額が pay を下回る、いちばん大きい課税所得
        lo, hi = 0, t
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if with_fukko(base_tax(mid)) < pay:
                lo = mid
            else:
                hi = mid - 1
        rows.append({
            "前年の課税所得（円）": t,
            "先に払う合計（円）": pay,
            "払いすぎになる課税所得（円）": lo,
            "落ちる幅（パーセント）": round((t - lo) / t * 100, 1),
        })
    return rows


# ---- 節4: 減額申請は1円下がれば出せる。戻る額はいくらか ----------------
def genkaku() -> list[dict]:
    rows = []
    for t in (2_500_000, 3_500_000, 5_000_000, 8_000_000, 12_000_000, 20_000_000):
        now = maebarai(kijun(t))
        after = maebarai(kijun(int(t * 0.99)))
        rows.append({
            "前年の課税所得（円）": t,
            "1パーセント下がった課税所得（円）": int(t * 0.99),
            "減る先払い（円）": now - after,
            "課税所得の減り（円）": t - int(t * 0.99),
            "減った所得100円あたり（円）": round((now - after) / ((t - int(t * 0.99)) / 100), 2),
        })
    return rows


# ---- 節5: 増えた税は、全部3月に来る ------------------------------------
def sangatsu() -> list[dict]:
    rows = []
    for t in (3_500_000, 5_000_000, 8_000_000, 12_000_000):
        base = with_fukko(base_tax(t))
        pay = maebarai(kijun(t))
        for up in (0, 10, 20):
            this = with_fukko(base_tax(int(t * (1 + up / 100))))
            rows.append({
                "前年の課税所得（円）": t,
                "今年の増え（パーセント）": up,
                "今年の年税額（円）": this,
                "3月に払う額（円）": this - pay,
                "年税額の増え（パーセント）": round((this - base) / base * 100, 1),
                "3月の増え（パーセント）": round(
                    (this - pay - (base - pay)) / (base - pay) * 100, 1),
            })
    return rows


# ---- 節6: 100円未満の切り捨ては、2回ぶん効く ---------------------------
def hasuu() -> list[dict]:
    rows = []
    for k in (LINE, LINE + 299, 500_000, 500_299, 1_000_199):
        exact = k / SHARE
        rows.append({
            "予定納税基準額（円）": k,
            "3分の1（切り捨て前・円）": round(exact, 2),
            "1回ぶん（円）": ikkai(k),
            "2回で切り捨てた額（円）": round(exact * 2 - maebarai(k), 2),
        })
    return rows


# ---- 節7: 復興特別所得税が、崖を手前に引き寄せている --------------------
def fukko_cliff() -> list[dict]:
    with_x = _taxable_for_kijun(LINE)

    def _plain(target: int) -> int:
        lo, hi = 0, 60_000_000
        while lo < hi:
            mid = (lo + hi) // 2
            if base_tax(mid) >= target:
                hi = mid
            else:
                lo = mid + 1
        return lo

    without_x = _plain(LINE)
    fukko_at_cliff = kijun(with_x) - base_tax(with_x)
    return [{
        "復興特別所得税": "含めない",
        "崖に立つ課税所得（円）": without_x,
        "そこでの基準所得税額（円）": base_tax(without_x),
    }, {
        "復興特別所得税": "含める（いまの制度）",
        "崖に立つ課税所得（円）": with_x,
        "そこでの基準所得税額（円）": base_tax(with_x),
    }, {
        "復興特別所得税": "差",
        "崖に立つ課税所得（円）": without_x - with_x,
        "そこでの基準所得税額（円）": fukko_at_cliff,
    }]


def check_tables() -> None:
    _checks.statutory(LINE, 150_000, "予定納税が要る基準額", source="所得税法第104条")
    _checks.statutory(FUKKO_RATE, 0.021, "復興特別所得税の率",
                      source="東日本大震災からの復興のための施策を実施するために必要な財源の確保に関する特別措置法第13条")
    _checks.ratio(FUKKO_RATE, "復興特別所得税の率")
    _checks.bracket_table(TAX_TABLE, tax_of, name="所得税の速算表")

    # 崖: 1円手前は0円、崖の上は先払いが出る
    c = {r["位置"]: r for r in cliff()}
    _checks.rounding(c["崖の1円手前"]["先に払う合計（円）"], 0, "崖の1円手前の先払い")
    _checks.greater(c["崖のちょうど上"]["先に払う合計（円）"], 99_000,
                    "崖のちょうど上の先払いが10万円に届いていない")
    _checks.greater(c["崖のちょうど上"]["予定納税基準額（円）"], LINE - 1,
                    "崖のちょうど上の基準額が15万円に届いていない")

    # 予定納税額は基準額に対して増える一方
    _checks.never_decreases(lambda k: ikkai(k), [150_000, 300_000, 900_000, 3_000_000],
                            "基準額が増えたのに1回ぶんが増えていない")
    _checks.increases_with(lambda t: kijun(t), [2_000_000, 4_000_000, 8_000_000],
                           "課税所得が増えたのに基準額が増えていない")

    # 先払いは基準額の3分の2を超えない
    for k in (150_000, 400_000, 1_234_567):
        _checks.greater(k * 2 / 3 + 1, maebarai(k), f"基準額{k}円の先払いが3分の2を超えた")

    _checks.unique_by(haraisugi(), lambda r: r["前年の課税所得（円）"], "払いすぎの表")
    _checks.unique_by(genzen(), lambda r: r["課税所得（円）"], "源泉徴収の表")

    # 復興特別所得税は崖を手前に引く（同じにはならない）
    f = fukko_cliff()
    _checks.greater(f[2]["崖に立つ課税所得（円）"], 0,
                    "復興特別所得税を入れても崖の位置が動いていない")


if __name__ == "__main__":
    check_tables()
    print("制度の値の検査: 通過")

    print("\n=== 予定納税の15万円の崖は、課税所得のどこに立っているか ===")
    for row in cliff():
        print(row)

    print("\n=== 源泉徴収がいくらあれば、予定納税は消えるか ===")
    for row in genzen():
        print(row)

    print("\n=== 所得が何パーセント落ちると、先払いが今年の年税額を超えるか ===")
    for row in haraisugi():
        print(row)

    print("\n=== 減額申請は1円下がれば出せる。1パーセントで戻るのはいくらか ===")
    for row in genkaku():
        print(row)

    print("\n=== 今年ふえた税は、全部3月に来る ===")
    for row in sangatsu():
        print(row)

    print("\n=== 100円未満の切り捨ては、2回ぶん効く ===")
    for row in hasuu():
        print(row)

    print("\n=== 復興特別所得税2.1パーセントが、崖を課税所得の手前に引き寄せている ===")
    for row in fukko_cliff():
        print(row)
