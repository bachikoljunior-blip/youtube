"""インボイスの2割特例 —— **これは「実質みなし仕入率80パーセント」で、小売業と1円も違いません。**

2割特例は「売上の消費税額の20パーセントを納める」制度です（平成28年改正法附則51条の2）。
簡易課税は「売上の消費税額 × (1 − みなし仕入率)」を納めます（消費税法37条）。

**第2種事業（小売業）のみなし仕入率は80パーセント**なので、
1 − 0.80 ＝ 0.20。**2割特例とまったく同じ式**です。

    業種（簡易課税）      みなし仕入率   納める割合   税抜売上800万円のとき   2割特例との差
      第1種 卸売業           90%         10%        80,000円       **−80,000円**
      第2種 小売業           80%         20%       160,000円              0円
      第3種 製造業等         70%         30%       240,000円       ＋80,000円
      第4種 その他（飲食店等） 60%         40%       320,000円      ＋160,000円
      第5種 サービス業等      50%         50%       400,000円      ＋240,000円
      第6種 不動産業         40%         60%       480,000円      ＋320,000円

**簡易課税のほうが安いのは、6業種のうち卸売業の1つだけ**です。
そしてその1つは **ちょうど半額**（10% 対 20%）。
いちばん重い不動産業では、2割特例が **3分の1** になります。

## 本則課税との分岐点は、どの業種でも 80パーセントちょうどです

本則課税は「売上の消費税額 − 仕入の消費税額」なので、
課税仕入率を r とすると納める割合は (1 − r)。**2割特例と等しくなるのは r ＝ 80%** で、
**この数字は業種にも売上にもよりません。**

    課税仕入率   本則課税     2割特例    安いほう
      50%      400,000円   160,000円   2割特例
      70%      240,000円   160,000円   2割特例
      80%      160,000円   160,000円   **同額**
      90%       80,000円   160,000円   本則課税

**簡易課税との分岐は業種ごとに 40〜90パーセントと散らばる**のに、
**2割特例との分岐は1点に集まります。2割特例は、業種の違いを消す制度です。**

## 「みなし仕入率が高い業種ほど得」は、2割特例では逆になります

簡易課税では、みなし仕入率が高い業種ほど納税が軽くなります。
**2割特例に切り替えると、その順番がそのまま「損した額」の順番になります** ——
もともと軽かった卸売業だけが損をし、**重かった業種ほど得をする。**

    第6種 不動産業（40%）  → **320,000円 得**
    第1種 卸売業（90%）    → **80,000円 損**

**差は 400,000円**（税抜売上800万円）。同じ制度が、業種によって符号ごと入れ替わります。

## 売上1,000万円を1円超えると、消えていた業種差が戻ります

2割特例は**基準期間の課税売上高1,000万円以下**の事業者だけが使えます。
1,000万円のときの納税は、**どの業種でも 200,000円**です。
超えた年の2年後には簡易課税へ戻るので、**業種差がそこで復活します。**

    第1種 卸売業     200,000円 → 100,000円   **0.50倍**
    第2種 小売業     200,000円 → 200,000円    1.00倍
    第5種 サービス業  200,000円 → 500,000円   **2.50倍**
    第6種 不動産業   200,000円 → 600,000円   **3.00倍**

**同じ1円の売上増が、業種によって「半分になる」とも「3倍になる」とも働きます。**

## 3年ぶんで見ると、選び方の差は売上の数パーセントになります

2割特例は令和8年9月30日までを含む課税期間が対象です。
税抜売上800万円で3年ぶんを並べると:

    第6種 不動産業   2割特例 480,000円 ／ 簡易課税 1,440,000円   差 **960,000円**
    第1種 卸売業     2割特例 480,000円 ／ 簡易課税   240,000円   差 −240,000円

**不動産業の差 960,000円は、3年間の税抜売上 2,400万円の 4.00パーセント**です。
**届出を1枚出すか出さないかで動く額としては、いちばん大きい部類**になります。

## 100円未満の切り捨ては、割合には効きません

消費税の納付税額は100円未満を切り捨てます（国税通則法119条1項）。
**この切り捨てが効くのは、売上税額が 100円で割り切れないときだけ**です。
税抜売上が1,000円単位なら売上税額は100円単位になり、
**どの業種のみなし仕入率を掛けても、切り捨ては1円も動きません**
（10・20・30・40・50・60パーセントは、いずれも100の倍数を100の倍数に写すため）。

**切り捨てが動くのは本則課税の側**で、課税仕入率が 0.5パーセント刻みのような
半端な値のときだけです。**制度の差を見るときに、丸めを気にする必要はありません。**
"""
from __future__ import annotations

from . import _checks

# ---- 制度の値 -----------------------------------------------------------
# 消費税と地方消費税をあわせた税率（消費税法29条・地方税法72条の83）。
TAX_PCT = 10
TAX_RATE = TAX_PCT / 100

# 簡易課税のみなし仕入率（消費税法施行令57条1項・5項）。
# 第1種 卸売業、第2種 小売業、第3種 製造業等、第4種 その他（飲食店業など）、
# 第5種 サービス業等、第6種 不動産業。
# **整数の百分率で持ちます。** 0.80 を浮動小数で持つと 1 − 0.80 が 0.19999…になり、
# 100円未満切り捨てが 159,999円 → 159,900円 と1段ずれて、
# **「2割特例と1円も違わない」というこの表の主題そのものが壊れます**（実際に踏みました）。
MINASHI_PCT = {1: 90, 2: 80, 3: 70, 4: 60, 5: 50, 6: 40}
MINASHI = {
    1: (MINASHI_PCT[1] / 100, "卸売業"),
    2: (MINASHI_PCT[2] / 100, "小売業"),
    3: (MINASHI_PCT[3] / 100, "製造業等"),
    4: (MINASHI_PCT[4] / 100, "その他（飲食店業など）"),
    5: (MINASHI_PCT[5] / 100, "サービス業等"),
    6: (MINASHI_PCT[6] / 100, "不動産業"),
}

# 2割特例（平成28年改正法附則51条の2）。納付税額は売上税額の8割を控除した残り
# ＝ 売上税額の20パーセント。
NIWARI_PCT = 20
NIWARI_RATE = NIWARI_PCT / 100

# 2割特例が使える基準期間の課税売上高の上限（免税事業者だった者が対象）。
NIWARI_CAP = 10_000_000

# 簡易課税を選べる基準期間の課税売上高の上限（消費税法37条1項）。
KANI_CAP = 50_000_000

# 納付税額の100円未満切り捨て（国税通則法119条1項）。
ROUND_UNIT = 100

ASSUMPTIONS = [
    "インボイス登録で課税事業者になった個人事業主が、消費税をいくら納めるかを"
    "計算しています。本則課税・簡易課税・2割特例の3つを並べています",
    "消費税率は10パーセントとして計算しています。"
    "軽減税率8パーセントの売上や仕入は入れていません",
    "売上はすべて税抜の額として置いています。売上にかかる消費税額は、"
    "税抜売上の10パーセントです",
    "簡易課税のみなし仕入率は、第1種の卸売業が90パーセント、"
    "第2種の小売業が80パーセント、第3種の製造業等が70パーセント、"
    "第4種のその他が60パーセント、第5種のサービス業等が50パーセント、"
    "第6種の不動産業が40パーセントとして計算しています",
    "2割特例は、売上にかかる消費税額の20パーセントを納めるものとして計算しています。"
    "基準期間の課税売上高が1,000万円以下の事業者が対象で、"
    "令和8年9月30日までを含む課税期間に使えます",
    "簡易課税は基準期間の課税売上高が5,000万円以下の事業者が選べるものとしています。"
    "選ぶには事前の届出が必要で、原則として2年間は変えられませんが、"
    "その期間の縛りはこの計算に入れていません",
    "納付税額は100円未満を切り捨てています",
    "1つの事業だけを営んでいるものとして置いています。"
    "複数の種類の事業がある場合の簡易課税の計算は入れていません",
    "所得税・住民税・国民健康保険料は入れていません。消費税だけの計算です",
    "納めた消費税が翌年の必要経費になる分（税込経理の場合）は入れていません",
]


# ---- 3つの納め方 --------------------------------------------------------
def sales_tax(sales: int) -> int:
    """売上にかかる消費税額。**税抜売上の10パーセント。**"""
    return sales * TAX_PCT // 100


def _floor100(value: float) -> int:
    """納付税額の100円未満切り捨て（国税通則法119条1項）。"""
    return int(value) // ROUND_UNIT * ROUND_UNIT


def honsoku(sales: int, purchase_ratio: float) -> int:
    """本則課税。**売上税額 − 仕入税額。** `purchase_ratio` は課税仕入率。"""
    return _floor100(round(sales_tax(sales) * (1 - purchase_ratio), 6))


def kani(sales: int, kind: int) -> int:
    """簡易課税。**売上税額 × (1 − みなし仕入率)。整数で計算します**（上の注記）。"""
    return _floor100(sales_tax(sales) * (100 - MINASHI_PCT[kind]) // 100)


def niwari(sales: int) -> int:
    """2割特例。**売上税額 × 20パーセント。業種を見ません。**"""
    return _floor100(sales_tax(sales) * NIWARI_PCT // 100)


def niwari_equivalent_ratio() -> float:
    """2割特例を「みなし仕入率」に言い換えた値。**0.80 ＝ 第2種と同じ。**"""
    return (100 - NIWARI_PCT) / 100


# ---- 節1・2: 業種べつに並べる -------------------------------------------
SALES = 8_000_000


def kind_grid(sales: int = SALES) -> list[dict]:
    """業種べつの簡易課税と、2割特例との差。**符号が業種で入れ替わります。**"""
    n = niwari(sales)
    rows = []
    for kind, (rate, name) in sorted(MINASHI.items()):
        k = kani(sales, kind)
        rows.append({
            "種別": kind, "業種": name, "みなし仕入率": rate,
            "納める割合": round(1 - rate, 2),
            "簡易課税": k, "2割特例": n,
            "差（簡易 − 2割特例）": k - n,
            "倍率": k / n if n else 0.0,
        })
    return rows


def kani_wins(sales: int = SALES) -> list[dict]:
    """簡易課税のほうが安い業種。**卸売業の1つだけです。**"""
    return [r for r in kind_grid(sales) if r["差（簡易 − 2割特例）"] < 0]


def same_as_niwari(sales: int = SALES) -> list[dict]:
    """2割特例とまったく同額になる業種。**第2種（小売業）。**"""
    return [r for r in kind_grid(sales) if r["差（簡易 − 2割特例）"] == 0]


# ---- 節3: 本則課税との分岐点 --------------------------------------------
PURCHASE_RATIOS = [0.0, 0.3, 0.5, 0.6, 0.7, 0.75, 0.8, 0.85, 0.9, 1.0]


def honsoku_grid(sales: int = SALES) -> list[dict]:
    """課税仕入率べつの本則課税と、2割特例との比較。"""
    n = niwari(sales)
    rows = []
    for r in PURCHASE_RATIOS:
        h = honsoku(sales, r)
        rows.append({
            "課税仕入率": r, "本則課税": h, "2割特例": n,
            "差（本則 − 2割特例）": h - n,
            "安いほう": "同額" if h == n else ("本則課税" if h < n else "2割特例"),
        })
    return rows


def honsoku_break_even() -> float:
    """本則課税と2割特例が同額になる課税仕入率。**0.80。業種によりません。**"""
    return (100 - NIWARI_PCT) / 100


def break_even_is_flat(sales_list: list[int] | None = None) -> bool:
    """分岐点が売上によらないこと。**どの売上でも 80パーセントちょうど。**"""
    be = honsoku_break_even()
    for s in (sales_list or [1_000_000, 5_000_000, 8_000_000, 30_000_000]):
        if honsoku(s, be) != niwari(s):
            return False
    return True


# ---- 節4: 簡易課税との分岐は業種ごとに散らばる --------------------------
def kani_break_evens() -> list[dict]:
    """簡易課税と本則課税が同額になる課税仕入率。**みなし仕入率そのもの。**"""
    return [{"種別": k, "業種": name, "分岐点": rate}
            for k, (rate, name) in sorted(MINASHI.items())]


def break_even_spread() -> dict:
    """分岐点の散らばりを、2割特例と簡易課税で比べる。"""
    kb = [r["分岐点"] for r in kani_break_evens()]
    return {
        "簡易課税の分岐点": sorted(set(kb)),
        "簡易課税の幅": max(kb) - min(kb),
        "2割特例の分岐点": [honsoku_break_even()],
        "2割特例の幅": 0.0,
    }


# ---- 節5: 売上1,000万円の壁 ---------------------------------------------
def cap_cliff() -> list[dict]:
    """基準期間1,000万円で2割特例が切れたとき、業種べつに何倍になるか。"""
    n = niwari(NIWARI_CAP)
    rows = []
    for kind, (rate, name) in sorted(MINASHI.items()):
        k = kani(NIWARI_CAP, kind)
        rows.append({
            "種別": kind, "業種": name,
            "2割特例": n, "簡易課税": k,
            "倍率": k / n if n else 0.0,
            "増える額": k - n,
        })
    return rows


# ---- 節6: 3年ぶん -------------------------------------------------------
NIWARI_YEARS = 3


def three_years(sales: int = SALES) -> list[dict]:
    """2割特例が使える3年ぶんの合計と、売上に対する割合。"""
    rows = []
    for r in kind_grid(sales):
        diff = (r["簡易課税"] - r["2割特例"]) * NIWARI_YEARS
        rows.append({
            "種別": r["種別"], "業種": r["業種"],
            "2割特例3年": r["2割特例"] * NIWARI_YEARS,
            "簡易課税3年": r["簡易課税"] * NIWARI_YEARS,
            "差": diff,
            "3年の売上に対する割合": diff / (sales * NIWARI_YEARS),
        })
    return rows


# ---- 節7: 丸めは割合に効かない ------------------------------------------
def rounding_bites(sales: int = SALES) -> list[dict]:
    """100円未満切り捨てが実際に効いた組み合わせ。**簡易課税では効きません。**"""
    out = []
    for kind in sorted(MINASHI):
        raw = sales_tax(sales) * (100 - MINASHI_PCT[kind]) / 100
        if _floor100(round(raw, 6)) != int(round(raw)):
            out.append({"種別": kind, "切り捨て前": raw, "切り捨て後": _floor100(raw)})
    return out


def grid(sales: int = SALES) -> list[dict]:
    """図解の元になる表。"""
    return kind_grid(sales)


def check_tables() -> None:
    """制度の値と、この計算の主題そのものを確かめる。"""
    _checks.statutory(NIWARI_RATE, 0.20, "2割特例で納める割合",
                      source="平成28年改正法附則51条の2")
    _checks.statutory(NIWARI_CAP, 10_000_000, "2割特例の基準期間の課税売上高の上限",
                      source="平成28年改正法附則51条の2")
    _checks.statutory(KANI_CAP, 50_000_000, "簡易課税を選べる課税売上高の上限",
                      source="消費税法37条1項")
    _checks.statutory(ROUND_UNIT, 100, "納付税額の切り捨て単位",
                      source="国税通則法119条1項")
    _checks.statutory(TAX_PCT, 10, "消費税および地方消費税の税率（百分率）",
                      source="消費税法29条・地方税法72条の83")
    for kind, want in ((1, 0.90), (2, 0.80), (3, 0.70),
                       (4, 0.60), (5, 0.50), (6, 0.40)):
        _checks.statutory(MINASHI[kind][0], want,
                          f"第{kind}種事業のみなし仕入率",
                          source="消費税法施行令57条")
        _checks.ratio(MINASHI[kind][0], f"第{kind}種事業のみなし仕入率")
    _checks.ratio(NIWARI_RATE, "2割特例で納める割合")
    _checks.assumption_values(ASSUMPTIONS, name="invoice")

    # 1. 売上が増えれば納税も増える（**符号を落としていないこと**）
    _checks.increases_with(niwari, [1_000_000, 5_000_000, 10_000_000],
                           "売上が増えたのに2割特例の納税が増えていない")

    # 2. **この表の主題。** 2割特例は第2種（小売業80%）と1円も違わない
    _checks.rounding(niwari_equivalent_ratio(), MINASHI[2][0],
                     "2割特例をみなし仕入率に言い換えた値")
    same = same_as_niwari()
    if [r["種別"] for r in same] != [2]:
        raise _checks.TableError(
            f"2割特例と同額になる業種が第2種だけではありません: "
            f"{[r['種別'] for r in same]}")

    # 3. **簡易課税が安いのは卸売業の1つだけ**で、それはちょうど半額
    wins = kani_wins()
    if [r["種別"] for r in wins] != [1]:
        raise _checks.TableError(
            f"簡易課税のほうが安い業種が第1種だけではありません: "
            f"{[r['種別'] for r in wins]}")
    _checks.close(wins[0]["倍率"], 0.5,
                  "卸売業の簡易課税が2割特例の何倍か", tol=1e-6)

    # 4. **本則との分岐点は 80パーセントで、売上にも業種にもよらない**（節3）
    _checks.rounding(honsoku_break_even(), 0.80, "本則課税と2割特例の分岐点")
    if not break_even_is_flat():
        raise _checks.TableError(
            "本則課税と2割特例の分岐点が、売上によって動いています")

    # 5. **簡易課税との分岐は散らばり、2割特例との分岐は1点**（節4）
    sp = break_even_spread()
    if len(sp["簡易課税の分岐点"]) <= len(sp["2割特例の分岐点"]):
        raise _checks.TableError(
            f"簡易課税の分岐点が散らばっていません: {sp['簡易課税の分岐点']}")
    _checks.greater(sp["簡易課税の幅"], sp["2割特例の幅"],
                    "簡易課税の分岐点の幅が2割特例より広くない")

    # 6. **1,000万円の壁は、業種で「半分」にも「3倍」にもなる**（節5）
    cliff = cap_cliff()
    lo = min(r["倍率"] for r in cliff)
    hi = max(r["倍率"] for r in cliff)
    _checks.close(lo, 0.5, "1,000万円の壁を越えたときの最小の倍率", tol=1e-6)
    _checks.close(hi, 3.0, "1,000万円の壁を越えたときの最大の倍率", tol=1e-6)
    _checks.unique_by(cliff, lambda r: r["種別"], "1,000万円の壁の表")

    # 7. **簡易課税では100円未満の切り捨てが1円も効かない**（節7）
    if rounding_bites():
        raise _checks.TableError(
            f"簡易課税で切り捨てが効いています: {rounding_bites()}")

