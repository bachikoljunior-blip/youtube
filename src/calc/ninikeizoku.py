# ---- 任意継続の側 -------------------------------------------------------
def rate_for(age: int) -> float:
    """その年齢にかかる率。**介護保険料率は40〜64歳だけ乗ります。**"""
    return KENPO_RATE + (KAIGO_RATE if KAIGO_FROM <= age <= KAIGO_TO else 0.0)


def hyoushuu_of(nenshu: int) -> int:
    """前年の年収 → 退職時の標準報酬月額（等級表の上下で止める）。"""
    return min(max(nenshu // 12, HYOUSHUU_MIN), NINI_CAP * 100)


def nini_hyoushuu(nenshu: int) -> int:
    """任意継続で使う標準報酬月額。**上限で止まるのがこの制度の本体です。**"""
    return min(hyoushuu_of(nenshu), NINI_CAP)


def nini_premium(nenshu: int, age: int = 45) -> int:
    """任意継続の年間保険料。"""
    return round(nini_hyoushuu(nenshu) * rate_for(age)) * 12


def zaishoku_premium(nenshu: int, age: int = 45) -> int:
    """在職中の自己負担（労使折半）。**上限で止まりません。**"""
    return round(hyoushuu_of(nenshu) * rate_for(age) / ROUSHI_SETSUHAN) * 12


def baisuu_grid(age: int = 45) -> list[dict]:
    """標準報酬月額ごとの「在職中の何倍か」。**2倍で止まらず、1倍を割ります。**"""
    rows = []
    for h in (200_000, 300_000, 400_000, 500_000, 600_000, 700_000, 900_000):
        nenshu = h * 12
        zai = zaishoku_premium(nenshu, age)
        ni = nini_premium(nenshu, age)
        rows.append({
            "標準報酬月額": h,
            "在職中の自己負担": zai,
            "任意継続": ni,
            "倍率": round(ni / zai, 3),
            "差額": ni - zai,
        })
    return rows


def baisuu_ichi() -> int:
    """在職中と任意継続がちょうど同額になる標準報酬月額。

    **率にも介護保険料率にもよりません。** 折半の2分の1と上限が打ち消し合うので、
    答えはいつも上限のちょうど2倍です。
    """
    return NINI_CAP * ROUSHI_SETSUHAN


# ---- 国保の側（`kokuho` をそのまま使う。**同じ表を二度書かない**）-------
def shotoku_of(nenshu: int) -> int:
    """前年の年収 → 総所得金額等（給与だけ）。"""
    return nenshu - salary_deduction(nenshu)


def kokuho_premium(nenshu: int, members: int = 1, age: int = 45) -> int:
    """世帯の国民健康保険料（年額）。"""
    return kokuho.premium(shotoku_of(nenshu), members, age)["保険料"]


# ---- 逆転点 -------------------------------------------------------------
def crossover(members: int = 1, age: int = 45, *,
              step: int = 1_000, upto: int = 15_000_000) -> dict | None:
    """国保が任意継続より高くなる、最初の前年の年収。

    **見つからない（＝いつも任意継続のほうが安い）ときは None。**
    """
    for nenshu in range(0, upto + 1, step):
        ni = nini_premium(nenshu, age)
        kh = kokuho_premium(nenshu, members, age)
        if kh > ni:
            prev = max(0, nenshu - step)
            return {
                "世帯人数": members,
                "年齢": age,
                "年収": nenshu,
                "任意継続": ni,
                "国保": kh,
                "1段手前の国保": kokuho_premium(prev, members, age),
                "1段手前の年収": prev,
                "飛び越えた額": kh - kokuho_premium(prev, members, age),
            }
    return None


def crossover_grid(age: int = 45, upto_members: int = 5) -> list[dict]:
    """世帯人数ごとの逆転点。**年収ではなく人数が効いていることが出ます。**"""
    rows = []
    for m in range(1, upto_members + 1):
        c = crossover(m, age)
        # **年収0で既に逆転している ＝ 全域で任意継続のほうが安い。**
        # ここは長らく `逆転なし: c is None` で見ていましたが、`crossura` は
        # 年収0の行から見るので **None にはなりません**（2026-08-18 に検査で
        # 気づいた）。**印字の分岐が一度も通らず、4人世帯の行に
        # 「年収0円で国保のほうが高くなる」という誤解を招く見出しが出ていました。**
        zenniki = c is not None and c["年収"] == 0
        rows.append({
            "世帯人数": m,
            "逆転する年収": c["年収"] if c else 0,
            "全域で任意継続が安い": zenniki,
            "逆転なし": c is None,
            "そこでの任意継続": c["任意継続"] if c else nini_premium(0, age),
            "そこでの国保": c["国保"] if c else kokuho_premium(0, m, age),
        })
    return rows


def jump_at_crossover(members: int, age: int = 45) -> dict | None:
    """逆転が「追い越し」か「崖で飛び越えた」かを分ける。

    軽減の割合が1段落ちたところで逆転したなら、それは崖です。
    """
    c = crossover(members, age)
    if c is None:
        return None
    lo = kokuho.premium(shotoku_of(c["1段手前の年収"]), members, age)
    hi = kokuho.premium(shotoku_of(c["年収"]), members, age)
    return {
        "世帯人数": members,
        "年収": c["年収"],
        # **`kokuho` の「軽減の割合」はパーセントです**（7割軽減 → 70）。
        # 「割」で刷るときは必ず10で割ること（2026-08-18 にここで踏んだ。
        # 同じ形が `kokuho` の見出しで前の回に出ている）。
        "手前の軽減": lo["軽減の割合"] // 10,
        "そこでの軽減": hi["軽減の割合"] // 10,
        "手前の軽減パーセント": lo["軽減の割合"],
        "そこでの軽減パーセント": hi["軽減の割合"],
        "落ちたポイント": lo["軽減の割合"] - hi["軽減の割合"],
        "手前の国保": lo["保険料"],
        "そこでの国保": hi["保険料"],
        "飛び越えた額": hi["保険料"] - lo["保険料"],
        "任意継続": c["任意継続"],
        "崖で飛び越えたか": lo["軽減の割合"] != hi["軽減の割合"],
    }


def keigen_kintou(members: int, points: int, age: int = 45) -> int:
    """軽減が `points` ポイント落ちたときに増える均等割。

    **均等割の合計 × 人数 × ポイント**なので、
    「2人×30ポイント」と「3人×20ポイント」は同じ額になります。
    """
    total = sum(int(kokuho.RATES[n]["均等割"]) for n in kokuho.parts_for(age))
    return round(total * members * points / 100)


# ---- 2年目 -------------------------------------------------------------
def second_year(nenshu: int, members: int = 1, age: int = 45) -> dict:
    """退職して収入が無くなった2年目。**任意継続は据え置き、国保は落ちます。**"""
    ni = nini_premium(nenshu, age)          # 退職時の標準報酬月額で固定
    kh = kokuho_premium(0, members, age)    # 前年の所得が0
    return {
        "1年目の年収": nenshu,
        "2年目の任意継続": ni,
        "2年目の国保": kh,
        "倍率": round(ni / kh, 2) if kh else 0.0,
        "差額": ni - kh,
    }


def two_year_total(nenshu: int, members: int = 1, age: int = 45) -> list[dict]:
    """2年ぶんの合計を、3つの選び方で並べる。"""
    y1_ni = nini_premium(nenshu, age)
    y1_kh = kokuho_premium(nenshu, members, age)
    y2_ni = y1_ni
    y2_kh = kokuho_premium(0, members, age)
    return [
        {"選び方": "2年とも任意継続", "1年目": y1_ni, "2年目": y2_ni,
         "合計": y1_ni + y2_ni},
        {"選び方": "2年とも国保", "1年目": y1_kh, "2年目": y2_kh,
         "合計": y1_kh + y2_kh},
        {"選び方": "1年目は任意継続、2年目は国保", "1年目": y1_ni, "2年目": y2_kh,
         "合計": y1_ni + y2_kh},
    ]


# ---- 40歳の壁 -----------------------------------------------------------
def kaigo_wall(members: int = 1) -> dict:
    """39歳と40歳で、両方の保険料と逆転点がどう動くか。"""
    before = crossover(members, KAIGO_FROM - 1)
    after = crossover(members, KAIGO_FROM)
    return {
        "世帯人数": members,
        "39歳の逆転する年収": before["年収"] if before else 0,
        "40歳の逆転する年収": after["年収"] if after else 0,
        "逆転点の動き": ((after["年収"] if after else 0)
                     - (before["年収"] if before else 0)),
        "39歳の任意継続": nini_premium(4_000_000, KAIGO_FROM - 1),
        "40歳の任意継続": nini_premium(4_000_000, KAIGO_FROM),
    }


def best_two_year(nenshu: int, members: int = 1, age: int = 45) -> dict:
    """**2年ぶんで、いちばん安い選び方**（`two_year_total` の中の最小）。"""
    rows = two_year_total(nenshu, members, age)
    best = min(rows, key=lambda r: r["合計"])
    return dict(best)


def missed_deadline_cost(nenshu: int, members: int = 1, age: int = 45) -> dict:
    """**申請の20日を1日過ぎると、いくら失うか。**

    任意継続は「退職日の翌日から20日以内」に申請しないと選べません
    （健康保険法37条1項）。**過ぎた人に残るのは国保だけ**です。
    だからこの門の値段は、**2年ぶんの最安と、国保だけで通した場合の差**。

    **1日の遅れが、いくらになるか。** 期限そのものは日数で書いてありますが、
    払うのは円で、しかも2年ぶんまとめて来ます。
    """
    rows = {r["選び方"]: r["合計"] for r in two_year_total(nenshu, members, age)}
    best = best_two_year(nenshu, members, age)
    only_kokuho = rows["2年とも国保"]
    loss = only_kokuho - best["合計"]
    return {
        "年収": nenshu,
        "世帯人数": members,
        "年齢": age,
        "申請できる日数": NINI_APPLY_DAYS,
        "間に合った場合の最安": best["合計"],
        "その選び方": best["選び方"],
        "間に合わなかった場合": only_kokuho,
        "1日遅れて失う額": loss,
        "1日あたりに直すと": loss / NINI_APPLY_DAYS if NINI_APPLY_DAYS else 0.0,
    }


def deadline_grid(members: int = 1, age: int = 45) -> list[dict]:
    """年収べつに、20日の門の値段を並べる。**0円の帯があるのが主題です。**"""
    return [missed_deadline_cost(n, members, age)
            for n in (2_000_000, 3_000_000, 4_000_000, 5_000_000,
                      6_000_000, 8_000_000, 10_000_000)]


def check_tables() -> None:
    """制度の値と計算の向きを確かめる。"""
    _checks.ratio(KENPO_RATE, "健康保険の一般保険料率")
    _checks.ratio(KAIGO_RATE, "介護保険料率")
    _checks.statutory(NINI_MAX_YEARS, 2, "任意継続でいられる年数",
                      source="健康保険法38条1号")
    _checks.statutory(NINI_APPLY_DAYS, 20, "任意継続の申請期限（日）",
                      source="健康保険法37条1項")
    _checks.statutory(NINI_MIN_MONTHS, 2, "任意継続に必要な被保険者期間（月）",
                      source="健康保険法3条4項")
    _checks.statutory(NINI_CAP, 300_000, "任意継続の標準報酬月額の上限",
                      source="健康保険法47条・協会けんぽの平均額")

    # 1. 上限より下では、任意継続はちょうど在職中の2倍
    for h in (100_000, 200_000, NINI_CAP):
        n = h * 12
        _checks.close(nini_premium(n) / zaishoku_premium(n), 2.0,
                      f"標準報酬月額{h:,}円での任意継続の倍率")

    # 2. 上限より上では、標準報酬月額が増えても任意継続は1円も増えない
    flat = {nini_premium(h * 12) for h in (400_000, 600_000, 900_000)}
    if len(flat) != 1:
        raise _checks.TableError(
            f"上限をこえても任意継続の保険料が動いています: {sorted(flat)}")

    # 3. ちょうど同額になる標準報酬月額は、率によらず上限の2倍
    ichi = baisuu_ichi()
    _checks.statutory(ichi, NINI_CAP * 2, "在職中と同額になる標準報酬月額",
                      source="上限 × 労使折半の分母")
    _checks.rounding(nini_premium(ichi * 12), zaishoku_premium(ichi * 12),
                     "標準報酬月額60万円での任意継続と在職中")
    # その上では、退職したほうが安い
    _checks.greater(zaishoku_premium(900_000 * 12), nini_premium(900_000 * 12),
                    "標準報酬月額90万円で、在職中の自己負担が任意継続以下")

    # 4. 在職中の自己負担は上限で止まらない（＝止まる任意継続と必ず交わる）
    _checks.increases_with(lambda h: zaishoku_premium(h * 12),
                           [400_000, 600_000, 900_000],
                           "標準報酬月額が増えたのに在職中の自己負担が増えていない")

    # 5. 国保は人数が増えると必ず高くなる（均等割）。任意継続は動かない
    _checks.increases_with(lambda m: kokuho_premium(3_000_000, m),
                           [1, 2, 3, 4],
                           "被保険者が増えたのに国保が増えていない")

    # 6. だから逆転する年収は、人数が増えるほど下がる
    crosses = [crossover_grid()[i]["逆転する年収"] for i in range(4)]
    _checks.ascending([-c for c in crosses],
                      "世帯人数が増えたのに逆転する年収が下がっていない")

    # 7. 崖の高さは「均等割 × 人数 × ポイント」なので、2人×30 と 3人×20 は同額
    _checks.rounding(keigen_kintou(2, 30), keigen_kintou(3, 20),
                     "2人世帯の30ポイントと3人世帯の20ポイントの崖")

    # 8. 2年目は、任意継続のほうが必ず高い（据え置き 対 7割軽減）
    s = second_year(4_800_000)
    _checks.greater(s["2年目の任意継続"], s["2年目の国保"],
                    "2年目に、任意継続が国保より高くなっていない")

    # 9. 2年ぶんの合計は「1年目は任意継続、2年目は国保」が最小か、同点
    totals = two_year_total(4_800_000)
    mixed = next(r for r in totals if r["選び方"].startswith("1年目"))
    for r in totals:
        if r["合計"] < mixed["合計"]:
            raise _checks.TableError(
                f"混ぜた選び方より安い選び方があります: {r['選び方']} {r['合計']:,}円")

    # **20日の門の値段。** 主題は「0円の帯がある」こと
    for n in (2_000_000, 3_000_000, 4_000_000):
        if missed_deadline_cost(n)["1日遅れて失う額"] != 0:
            raise _checks.TableError(f"年収{n}円で、国保のほうが安いのに門の値段が出ている")
    for n in (5_000_000, 8_000_000, 10_000_000):
        if missed_deadline_cost(n)["1日遅れて失う額"] <= 0:
            raise _checks.TableError(f"年収{n}円で、門の値段が0以下になっている")
    # 年収が上がるほど、逃した損は大きくなる（任意継続が上限で止まるから）
    _checks.increases_with(lambda n: missed_deadline_cost(n)["1日遅れて失う額"],
                           [5_000_000, 6_000_000, 8_000_000, 10_000_000],
                           "年収が上がったのに、20日を逃す損が増えていない")
    # 最安は必ず3つの選び方の中にあり、国保だけを上回らない
    for n in (2_000_000, 5_000_000, 10_000_000):
        rows = two_year_total(n)
        b = best_two_year(n)
        if b["合計"] != min(r["合計"] for r in rows):
            raise _checks.TableError(f"年収{n}円の最安が、3つの選び方の最小と違う")
        if b["合計"] > [r for r in rows if r["選び方"] == "2年とも国保"][0]["合計"]:
            raise _checks.TableError(f"年収{n}円で、最安が国保だけより高い")
    # 上限で止まるので、**高年収ほど任意継続の2年合計は同じ額に張り付く**
    if nini_premium(8_000_000) != nini_premium(10_000_000):
        raise _checks.TableError("上限をこえた年収どうしで、任意継続の保険料が違う")

