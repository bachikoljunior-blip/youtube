"""任意継続と国民健康保険 —— **「退職すると保険料が2倍」は、標準報酬月額60万円までの話です。**

退職後の健康保険は、任意継続被保険者になるか、国民健康保険に入るかを選びます。
一般の解説は「任意継続は会社負担がなくなるので在職中の2倍。国保は自治体しだい。
どちらが安いかは計算してみるしかない」で止まります。

**その2倍が、上のほうで成り立たなくなります。**

任意継続の保険料は「退職時の標準報酬月額」と「その保険者の全被保険者の
標準報酬月額の平均額」の**低いほう**で決まります（健康保険法47条）。
協会けんぽの平均額は30万円なので、**標準報酬月額が30万円をこえた人は、
いくら高くても同じ保険料**になります。在職中の自己負担は折半なので
標準報酬月額に比例して増え続ける —— つまり2つは必ずどこかで交わります。

    標準報酬月額 20万円   在職中 139,080円 → 任意継続 278,160円   **2.000倍**
    標準報酬月額 40万円   在職中 278,160円 → 任意継続 417,240円   1.500倍
    標準報酬月額 60万円   在職中 417,240円 → 任意継続 417,240円   **1.000倍**
    標準報酬月額 90万円   在職中 625,860円 → 任意継続 417,240円   **0.667倍**

（40〜64歳＝介護保険料率を上乗せした額です。39歳以下なら 240,000 / 360,000 /
360,000 / 360,000 になりますが、**倍率の列は1桁も変わりません。**）

**標準報酬月額60万円の人は、退職しても保険料が1円も変わりません。**
それより上の人は、**退職したほうが健康保険料が安くなります。**
この60万円は上限30万円のちょうど2倍で、率がいくつでも動きません
（折半の2分の1と、上限で止まることが打ち消し合うため）。

## 国保と比べると、決めているのは年収ではありません

同じ前提で国民健康保険と並べると、逆転する年収はこうなります（40〜64歳）。

    世帯1人   前年の年収 **431万8千円** で国保のほうが高くなる
    世帯2人   **160万1千円**
    世帯3人   **98万1千円**
    世帯4人   **年収0円でも任意継続のほうが安い**

**任意継続の保険料は、扶養している家族が何人いても1円も増えません。**
国保には扶養という考え方がなく、**均等割が頭数ぶん**かかります。だから
「どちらが安いか」は、年収よりも**人数**でほとんど決まってしまいます。

## その逆転は、追い越しですらありません

世帯1人のところは、国保がじりじり伸びて追い越します（1,000円上げると約100円）。
**ところが2人と3人は違います。** 国保の軽減が切れる1円で、

    世帯2人  年収1,600,000円 **162,890円** → 1,601,000円 **212,579円**（+49,689円）
    世帯3人  年収  980,000円  **74,340円** → 981,000円 **124,029円**（+49,689円）

**国保が任意継続を、1回の崖で飛び越えます。**
2人の崖（5割軽減→2割軽減）と3人の崖（7割軽減→5割軽減）が**同額**なのは偶然ではなく、
落ちるポイントが 2人×30 と 3人×20 で**どちらも均等割の0.6人分**だからです。

## そして2年目に、必ずひっくり返ります

任意継続の保険料は退職時の標準報酬月額で決まるので、**2年間そのまま**です。
国保は前年の所得で決まるので、退職して収入が無くなれば**翌年度に7割軽減まで落ちます。**

    2年目  任意継続 **417,240円**（据え置き） 対 国保 **24,780円**   **16.8倍**

令和4年1月から、任意継続被保険者は**申し出るだけで資格を喪失できます**
（健康保険法38条7号）。それ以前は「保険料を払わない」以外に抜ける道がありませんでした。
**1年目は任意継続、2年目は国保**という選び方が、制度として選べるようになっています。
"""
