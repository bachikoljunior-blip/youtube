# ---- 制度の値（地方税法第147条・自動車税種別割。2019年10月1日の改正）------
# (区分名, 2019年9月30日までの登録の税率, 2019年10月1日以降の登録の税率, 13年超の重課後)
HAIKIRYO: list[tuple[str, int, int, int]] = [
    ("1,000cc以下", 29_500, 25_000, 33_900),
    ("1,000cc超1,500cc以下", 34_500, 30_500, 39_600),
    ("1,500cc超2,000cc以下", 39_500, 36_000, 45_400),
    ("2,000cc超2,500cc以下", 45_000, 43_500, 51_700),
    ("2,500cc超3,000cc以下", 51_000, 50_000, 58_600),
    ("3,000cc超3,500cc以下", 58_000, 57_000, 66_700),
    ("3,500cc超4,000cc以下", 66_500, 65_500, 76_400),
    ("4,000cc超4,500cc以下", 76_500, 75_500, 87_900),
    ("4,500cc超6,000cc以下", 88_000, 87_000, 101_200),
    ("6,000cc超", 111_000, 110_000, 127_600),
]

# 軽自動車税種別割（四輪以上・自家用）
# (区分名, 2015年3月31日までの新規検査, 2015年4月1日以降, 13年超の重課後)
KEI: list[tuple[str, int, int, int]] = [
    ("軽・乗用・自家用", 7_200, 10_800, 12_900),
    ("軽・貨物・自家用", 4_000, 5_000, 6_000),
]

JUKA_RATE = Decimal("0.15")   # 公表されている「おおむね15パーセント」
# **`float` で持たないこと**（2026-08-18 20:3x に踏んだ）。`88_000 * 1.15` は
# `101200.00000000001` になるので、「切り捨てなのだから掛けた額を超えない」という
# **この計算の主題そのものの検査が、割り切れる区分で誤って落ちます。**
ROUND_UNIT = 100        # 掛けたあと、この単位より下を切り捨てる
GASOLINE_YEARS = 13     # ガソリン車。**超えた**ことが条件
DIESEL_YEARS = 11       # ディーゼル車


def _pct(after: int, before: int) -> float:
    """`before` から `after` へ上がったときの、上がり幅の割合（パーセント）。"""
    return (after - before) / before * 100


# ---- 節1: 実効の重課率は15.00パーセントちょうどではない --------------------
def jikko_ritsu() -> list[dict]:
    rows = []
    for name, old, _new, juka in HAIKIRYO:
        rows.append({
            "排気量の区分": name,
            "重課前の税額（円）": old,
            "重課後の税額（円）": juka,
            "実効の重課率（パーセント）": round(_pct(juka, old), 4),
            "ちょうど15パーセントか": "はい" if juka == old * (1 + JUKA_RATE) else "いいえ",
        })
    return rows


# ---- 節2: 増える額は3.77倍ひらく -----------------------------------------
def zougaku() -> list[dict]:
    lo = min(j - o for _n, o, _w, j in HAIKIRYO)
    rows = []
    for name, old, _new, juka in HAIKIRYO:
        rows.append({
            "排気量の区分": name,
            "重課前の税額（円）": old,
            "1年で増える額（円）": juka - old,
            "いちばん小さい区分の何倍か": round((juka - old) / lo, 4),
            "重課前の税額が29,500円の何倍か": round(old / HAIKIRYO[0][1], 4),
        })
    return rows


# ---- 節3: 軽自動車の「約20パーセント」は旧税率の車では79パーセント ---------
def kei_juka() -> list[dict]:
    """軽自動車の重課後の額は**新旧で分かれていない**。だから旧税率だけ跳ねる。"""
    rows = []
    for name, old, new, juka in KEI:
        rows.append({
            "区分": name,
            "2015年3月までの新規検査（円）": old,
            "2015年4月以降の新規検査（円）": new,
            "13年超の税額（円）": juka,
            "旧からの上がり幅（パーセント）": round(_pct(juka, old), 4),
            "新からの上がり幅（パーセント）": round(_pct(juka, new), 4),
        })
    # 比べる相手として、乗用車のいちばん低い区分を同じ表に置く
    low = min(HAIKIRYO, key=lambda r: _pct(r[3], r[1]))
    rows.append({
        "区分": f"（比較）乗用車 {low[0]}",
        "2015年3月までの新規検査（円）": low[1],
        "2015年4月以降の新規検査（円）": low[1],
        "13年超の税額（円）": low[3],
        "旧からの上がり幅（パーセント）": round(_pct(low[3], low[1]), 4),
        "新からの上がり幅（パーセント）": round(_pct(low[3], low[1]), 4),
    })
    return rows


def juka_haba() -> float:
    """同じ「重課」という言葉が持っている幅（いちばん高い率 ÷ いちばん低い率）。"""
    highest = max(_pct(j, o) for _n, o, _w, j in KEI)
    lowest = min(_pct(j, o) for _n, o, _w, j in HAIKIRYO)
    return highest / lowest


# ---- 節4: 重課が始まる年度は「初度登録の年度＋14」 -------------------------
def kaishi_nendo(start: int = 2008, end: int = 2022) -> list[dict]:
    rows = []
    for year in range(start, end + 1):
        rows.append({
            "初度登録の年度": year,
            "ガソリン車の重課開始年度": year + GASOLINE_YEARS + 1,
            "ディーゼル車の重課開始年度": year + DIESEL_YEARS + 1,
            "適用される税率": "2019年10月以降" if year >= 2019 else "2019年9月まで",
            "2026年度に重課されているか": "はい" if year + GASOLINE_YEARS + 1 <= 2026 else "いいえ",
        })
    return rows


# ---- 節5: 13年目からの累計 -----------------------------------------------
RUIKEI_LABEL = "1,000cc以下は1年あたりいくら増えたか（円）"


def ruikei(years: int = 10) -> list[dict]:
    rows = []
    for n in range(1, years + 1):
        row: dict = {"重課になってからの年数": n}
        for name, old, _new, juka in (HAIKIRYO[0], HAIKIRYO[2], HAIKIRYO[4], HAIKIRYO[9]):
            row[f"{name}の累計（円）"] = (juka - old) * n
        rows.append(row)
    # **「1年あたり」と書く列は、必ず年で割ること**（`_checks.per_unit_steps`）。
    # 累計をそのまま並べて「1年あたり」と見出しを付ける形は、2026-08-15 に
    # `taishoku.py` が実際にやって素通りしています。
    steps = _checks.per_unit_steps(rows, "重課になってからの年数",
                                   f"{HAIKIRYO[0][0]}の累計（円）",
                                   label=RUIKEI_LABEL, x_unit="年")
    for row, step in zip(rows, steps):
        row[RUIKEI_LABEL] = "—" if step is None else step
    return rows


# ---- 節6: 切り捨てで消える額 ---------------------------------------------
def kirisute_gokei() -> float:
    """10区分あわせて、切り捨てで消えた額。**散文で足さないこと。**"""
    return float(sum(old * (1 + JUKA_RATE) - juka for _n, old, _w, juka in HAIKIRYO))


def kirisute_kiki() -> float:
    """同じ75円が、率へ与える効きの幅（いちばん深い区分 ÷ いちばん浅い区分）。"""
    same = [(_pct(j, o), 15.0 - _pct(j, o))
            for _n, o, _w, j in HAIKIRYO
            if abs(float(o * (1 + JUKA_RATE)) - j - 75.0) < 1e-9]
    return max(k for _r, k in same) / min(k for _r, k in same)


def kirisute() -> list[dict]:
    rows = []
    for name, old, _new, juka in HAIKIRYO:
        exact = old * (1 + JUKA_RATE)   # Decimal。float だと割り切れる区分で崩れる
        rows.append({
            "排気量の区分": name,
            "掛けただけの額（円）": float(exact),
            "重課後の税額（円）": juka,
            "切り捨てられた額（円）": float(exact - juka),
            "率がいくつ下がったか（ポイント）": round(15.0 - _pct(juka, old), 4),
        })
    return rows


# ---- 節7: 重課された車は、新しい車の何倍払っているか ----------------------
def shinsha_hi() -> list[dict]:
    rows = []
    for name, _old, new, juka in HAIKIRYO:
        rows.append({
            "排気量の区分": name,
            "2019年10月以降に登録した車の税額（円）": new,
            "13年超で重課された車の税額（円）": juka,
            "差（円）": juka - new,
            "何倍か": round(juka / new, 4),
        })
    return rows


def check_tables() -> None:
    # 1. 法令・公表資料が名指ししている値
    _checks.statutory(HAIKIRYO[0][1], 29_500, "1,000cc以下の2019年9月までの税率",
                      source="地方税法第147条（2019年10月改正前）")
    _checks.statutory(HAIKIRYO[0][2], 25_000, "1,000cc以下の2019年10月以降の税率",
                      source="地方税法第147条（2019年10月改正）")
    _checks.statutory(HAIKIRYO[0][3], 33_900, "1,000cc以下の13年超の税額",
                      source="自動車税種別割の重課（おおむね15パーセント）")
    _checks.statutory(HAIKIRYO[9][3], 127_600, "6,000cc超の13年超の税額",
                      source="自動車税種別割の重課（おおむね15パーセント）")
    _checks.statutory(KEI[0][2], 10_800, "軽・乗用・自家用の2015年4月以降の税額",
                      source="地方税法第444条（2015年度改正）")
    _checks.statutory(KEI[0][3], 12_900, "軽・乗用・自家用の13年超の税額",
                      source="軽自動車税種別割の重課")
    _checks.ratio(float(JUKA_RATE), "公表されている重課の率")

    # 2. 表の形（区分の重複と、税額の並び）
    _checks.unique_by(HAIKIRYO, lambda r: r[0], "排気量の区分")
    _checks.unique_by(KEI, lambda r: r[0], "軽自動車の区分")
    _checks.ascending([r[1] for r in HAIKIRYO], "重課前の税額", strict=True)
    _checks.ascending([r[2] for r in HAIKIRYO], "2019年10月以降の税額", strict=True)
    _checks.ascending([r[3] for r in HAIKIRYO], "重課後の税額", strict=True)

    # 3. この計算の主題そのもの
    # 3-1. 重課後は必ず重課前より高く、**掛けただけの額は決して超えない**（切り捨てなので）
    for name, old, new, juka in HAIKIRYO:
        _checks.greater(juka, old, f"{name}で重課後が重課前以下")
        _checks.greater(old, new, f"{name}で2019年10月の引き下げになっていない")
        exact = old * (1 + JUKA_RATE)
        if juka > exact:
            raise _checks.TableError(
                f"{name}: 重課後 {juka:,}円 が、掛けただけの額 "
                f"{exact:,.2f}円 を超えています（切り捨てのはず）")
        if exact - juka >= ROUND_UNIT:
            raise _checks.TableError(
                f"{name}: 切り捨てが {ROUND_UNIT}円 以上あります"
                f"（{exact:,.2f} → {juka:,}）")

    # 3-2. **実効率は15.00を1つも超えない。そしてちょうど15.00が2区分ある**
    rates = [_pct(j, o) for _n, o, _w, j in HAIKIRYO]
    if max(rates) > 15.0 + 1e-9:
        raise _checks.TableError(f"実効の重課率が15パーセントを超えました: {max(rates)}")
    exact = [n for (n, o, _w, j) in HAIKIRYO if abs(_pct(j, o) - 15.0) < 1e-9]
    if len(exact) != 2:
        raise _checks.TableError(
            f"ちょうど15.00パーセントの区分が2つではありません: {exact}")
    _checks.close(min(rates), 14.782608695652174, "いちばん低い実効の重課率")

    # 3-3. **旧税率の軽自動車は、乗用車のどの区分よりも上がり幅が大きい**（主題そのもの）
    kei_old = _pct(KEI[0][3], KEI[0][1])
    _checks.greater(kei_old, max(rates), "旧税率の軽自動車が乗用車より上がっていない")
    _checks.close(kei_old, 79.16666666666667, "旧税率の軽・乗用の上がり幅")
    _checks.close(juka_haba(), kei_old / min(rates), "重課という言葉の幅")

    # 3-4. **重課の開始年度は登録が新しいほど後ろへ動く**（同じ年に止まらない）
    _checks.increases_with(lambda y: y + GASOLINE_YEARS + 1, [2013, 2019, 2026],
                           "登録が新しいのに重課の開始年度が後ろへ動いていない")
    _checks.greater(2019 + GASOLINE_YEARS + 1, 2026,
                    "2019年度に登録した車が2026年度で既に重課されている")

    # 3-5. 累計は年数に**比例する**（1年あたりが毎年同じ額であること）
    per_year = [r[RUIKEI_LABEL] for r in ruikei()[1:]]
    if set(per_year) != {float(HAIKIRYO[0][3] - HAIKIRYO[0][1])}:
        raise _checks.TableError(
            f"累計の1年あたりが一定ではありません: {sorted(set(per_year))}")
    _checks.increases_with(lambda n: ruikei(n)[-1][f"{HAIKIRYO[0][0]}の累計（円）"],
                           [1, 5, 10], "年数が増えたのに累計が増えていない")

    # 3-6. **新しい車との倍率は、排気量が大きいほど下がる**（額は単調でない）
    ratios = [j / n for _name, _o, n, j in HAIKIRYO]
