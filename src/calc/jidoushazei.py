"""**自動車税の13年超重課 —— 同じ「重課」で、上がり方が5.3554倍ちがう。**

13年を超えた車は自動車税が重くなる。一般の解説はここで止まる ——
「おおむね15パーセント重課、軽自動車は約20パーセント」と率を2つ並べて終わり。
**その15パーセントが、区分ごとに何パーセントになっているかは表の外にある。**

重課後の税額は率で書かれておらず、**区分ごとに実額で決まっています**
（29,500円→33,900円というように）。掛けたあとに100円未満を切り捨てるので、
**実効の率は区分ごとに違います。** ここで出しているのは、その違いと、
軽自動車まで並べたときに「重課」という1語がどれだけ幅を持つかです。

## 出たもの

**1. 実効の重課率は15パーセントちょうどではない。10区分のうち2つだけがちょうど15.0。**

    1,000cc超1,500cc以下  34,500円 → 39,600円  **14.7826%**  ← いちばん低い
    3,000cc超3,500cc以下  58,000円 → 66,700円  **15.0%**  ← ちょうど15パーセント
    4,500cc超6,000cc以下  88,000円 → 101,200円 **15.0%**  ← ちょうど15パーセント

10区分のうち**ちょうど15.0パーセントは2区分だけ**で、残る8区分は
100円未満の切り捨てのぶんだけ下にいます。幅は **0.2174ポイント**。
**いちばん低いのは1,000cc超1,500cc以下**で、区分の順番とも税額の順番とも一致しません
（14.9153 → **14.7826** → 14.9367 → 14.8889 → … と、いったん下がって戻ります）。

**2. 増える額は、区分のあいだで3.7727倍ひらく。**
4,400円（1,000cc以下）から16,600円（6,000cc超）まで。
**率はほぼ一定なのに額は3.7727倍**で、これは元の税額が3.7627倍ひらいているからです。
**増額の幅（3.7727倍）のほうが、元の税額の幅（3.7627倍）よりわずかに広い** ——
切り捨てが小さい区分ほど深く効くので、比が少しだけ開きます。

**3. 軽自動車の「約20パーセント」は、旧税率の車では79.1667パーセント。**

    軽・乗用・自家用（2015年4月以降に新規検査） 10,800円 → 12,900円  **19.4444%**
    軽・乗用・自家用（2015年3月までに新規検査） **7,200円** → 12,900円  **79.1667%**

重課後の額は新旧で分かれておらず、**どちらも12,900円**です。だから
**2015年3月までに新規検査した軽自動車だけ、13年超で79.1667パーセント上がります。**
乗用車のいちばん低い14.7826パーセントと比べると、**同じ「重課」という言葉が
5.3554倍の幅**を持っていることになります。

**4. 重課が始まるのは「初度登録の年度に14を足した年度」。ディーゼルは12を足した年度。**
ガソリン車は13年超、ディーゼル車は11年超なので、**同じ年に登録しても
重課の開始年度は2年ずれます。** そして 2019年10月の税率引き下げ以降に
登録された車は、**いちばん早いものでも2033年度から**です ——
**いま重課されている車は、全部が引き下げ前の税率の車**ということになります。

**5. 重課ぶんだけで、1,000cc以下でも5年で22,000円。6,000cc超なら83,000円。**
13年目からの累計です。**車検2回分に相当する額が、税金の差だけで出ます。**

**6. 切り捨てで消えるのは、1台あたり最大75円。ただし率への効きは小さい区分ほど大きい。**
10区分あわせて425円で、**2区分は1円も切り捨てられていません**（割り切れる）。
そして**同じ75円でも効きが違います** —— 1,000cc超1,500cc以下では **0.2174ポイント**、
4,000cc超4,500cc以下では **0.098ポイント**。**同じ額なのに2.2174倍の差**です。

**7. 重課された車は、同じ排気量の新しい車の1.16倍から1.356倍を毎年払っている。**
2019年10月以降の税率と比べたものです。**倍率は排気量が小さいほど大きく、
1,000cc以下の1.356倍から6,000cc超の1.16倍まで単調に下がります。**
ところが**額の差は単調ではありません** —— 9,400円（1,500cc以下）から
2,000cc超2,500cc以下で**8,200円へ下がり**、そこからまた上がります。

## 前提の置き方（ここが独自の視点です）

**税額は自家用の乗用車だけを置いています。** 営業用・貨物・三輪以下は入れていません。
**重課の対象外**（電気自動車、天然ガス車、メタノール車、一般社団法人が定める
ガソリンハイブリッド）は、そもそもこの表に載りません。
軽自動車は**四輪以上の自家用（乗用・貨物）だけ**で、営業用は入れていません。

**「13年超」の数え方は、初度登録の年度に14を足す形に置いています。**
4月1日時点で13年を超えていることが条件なので、**登録が3月でも5月でも、
年度で見れば同じだけ先**になります。日で数える版は置いていません。

**重課後の税額は、率ではなく公表されている実額を持っています。**
掛け算で作ると切り捨ての位置がずれるので、**実額を置いて、率のほうを計算しています。**
"""
