"""**厚生年金保険料は月給に比例しない。32段の階段で、段の中では1円も動かない。**

一般の解説はここで止まります ——「標準報酬月額の等級で決まります」。
**では、どの月給からどの月給までが同じ段なのか。段をまたぐと年間いくら増えるのか。
昇給額より保険料の増えぶんが大きくなる境界はどこか。** そこは誰も出していません。

ここで出すのは、その3つを32段ぜんぶ計算した結果です。とくに3つめ ——
**「昇給したのに、その年の手取りが減る月給の組み合わせ」**は、
段の幅と段差の両方を掛け合わせないと出てこないので、表のどこにも載っていません。

## この計算が言いたいこと

**段の中は平らです。** 報酬月額 310,000円 と 329,000円 は、月19,000円ちがうのに
厚生年金保険料は**まったく同じ**（どちらも標準報酬月額 320,000円）。

**境界は垂直です。** 309,000円 → 310,000円 の 1,000円の昇給で、
標準報酬月額は 300,000円 → 320,000円 に跳びます。本人負担は 9.15% なので
月 **1,830円**、年 **21,960円** 増えます。**昇給は年 12,000円**です。
差し引き **年 9,960円のマイナス** —— これが「昇給して減る」の正体です。

## ただし、それで話を終えると誤情報になります

**標準報酬月額が上がると、将来の厚生年金も上がります。** 報酬比例部分は
平均標準報酬額 × 5.481/1000 × 月数 なので、この計算では**取り返すまでの年数**も
出します（出さないと「損」だけが残り、事実の半分になります）。

**厚生年金だけを扱います。** 健康保険・介護保険の料率は都道府県と年度で動くので、
**法律で固定されている 18.3% だけで話を閉じます**（`ASSUMPTIONS` に明記）。
健康保険を混ぜると、段差の額が「いつの・どこの」話か言えなくなります。

## 裏取り（2026-08-16 に当たった）

- 32等級・1等級 88,000円 ～ 32等級 650,000円、料率 **18.3%**（2017年9月から固定）
  … 日本年金機構「厚生年金保険の保険料」
- 境界は**隣り合う標準報酬月額の中点**。**8点で照合して合っている**
  （1等級<93,000／2等級 93,000〜101,000／3等級 101,000〜107,000／
  19等級 290,000〜310,000／20等級 310,000〜330,000／21等級 330,000〜350,000／
  31等級 605,000〜635,000／32等級 635,000以上）
  … `ANCHORS` に入れて `check_tables()` で毎回突き合わせています
- 報酬比例部分の給付乗率 **5.481/1000**（2003年4月以降の期間）
  … 総報酬制の導入後の乗率

**`ANCHORS` が要るのは、中ほどの等級を思い出しで書いていないと言えないからです。**
中点の規則と両端だけ合っていても、途中の1段を書き間違えると
**その前後2つの境界がずれます。** 8点は等級表の端・低い側・中ほど・高い側に散らしてあり、
**1段でも取り違えれば、どれかの点が外れます。**
"""
from __future__ import annotations

from . import _checks

ASSUMPTIONS = [
    "厚生年金保険料だけの計算です。健康保険料と介護保険料は入れていません",
    "外した理由は、健康保険の料率が都道府県と年度で変わるためです。厚生年金の保険料率は"
    "18.3パーセントで、2017年9月から法律で固定されています",
    "保険料率は18.3パーセントで、会社と本人で半分ずつ負担するため、"
    "本人の負担は9.15パーセントです",
    "標準報酬月額は32の等級に分かれ、1等級が8万8千円、32等級が65万円です",
    "各等級の報酬月額の境目は、隣り合う標準報酬月額のちょうど中間の額です",
    "将来もらう年金は、報酬比例部分だけを見ています。"
    "平均標準報酬額に1000分の5.481と加入月数をかけた額です",
    "年金を取り返すまでの年数は、税金と物価の変動を入れていません",
    "賞与にかかる保険料は入れていません。標準賞与額は1回150万円が上限で、"
    "月給とは別に計算されるためです",
]

# ---- 制度の値 --------------------------------------------------------------
RATE = 0.183                 # 厚生年金保険料率（2017年9月から固定）
HALF = RATE / 2              # 本人負担 9.15%
BENEFIT_MULT = 5.481 / 1000  # 報酬比例部分の給付乗率（2003年4月以降）

# 32等級の標準報酬月額（1等級 → 32等級）。**境界はこの中点から導く**
GRADES = [
    88_000, 98_000, 104_000, 110_000, 118_000, 126_000, 134_000, 142_000,
    150_000, 160_000, 170_000, 180_000, 190_000, 200_000, 220_000, 240_000,
    260_000, 280_000, 300_000, 320_000, 340_000, 360_000, 380_000, 410_000,
    440_000, 470_000, 500_000, 530_000, 560_000, 590_000, 620_000, 650_000,
]

# 公表資料で実際に読んだ点。(等級, 標準報酬月額, 下限 or None, 上限 or None)
# **思い出しで書いた中ほどの等級を、ここで落とすためにあります。**
ANCHORS = [
    (1, 88_000, None, 93_000),
    (2, 98_000, 93_000, 101_000),
    (3, 104_000, 101_000, 107_000),
    (19, 300_000, 290_000, 310_000),
    (20, 320_000, 310_000, 330_000),
    (21, 340_000, 330_000, 350_000),
    (31, 620_000, 605_000, 635_000),
    (32, 650_000, 635_000, None),
]


def bounds(i: int) -> tuple[int | None, int | None]:
    """`i` 番目（0起点）の等級の報酬月額の範囲。境界は隣との中点。"""
    low = None if i == 0 else (GRADES[i - 1] + GRADES[i]) // 2
    high = None if i == len(GRADES) - 1 else (GRADES[i] + GRADES[i + 1]) // 2
    return low, high


def grade_of(monthly: int) -> int:
    """報酬月額から標準報酬月額を引く。**上下は張り付く**（頭打ち・底打ち）。"""
    for i in range(len(GRADES)):
        low, high = bounds(i)
        if (low is None or monthly >= low) and (high is None or monthly < high):
            return GRADES[i]
    raise ValueError(f"等級に当たらない: {monthly}")


def premium(monthly: int) -> int:
    """本人負担の厚生年金保険料（月額・円）。**1円未満は切り捨て。**"""
    return int(grade_of(monthly) * HALF)


def flat_bands() -> list[dict]:
    """**段の中は平ら。** 各等級で「月給がいくら動いても保険料が同じ」幅を出す。"""
    rows = []
    for i, std in enumerate(GRADES):
        low, high = bounds(i)
        if low is None or high is None:
            continue                      # 上下の等級は幅が無限なので出さない
        rows.append({
            "等級": i + 1,
            "標準報酬月額": std,
            "この月給から": low,
            "この月給まで": high - 1,
            "同じ保険料の幅": high - 1 - low,
            "本人負担(月)": int(std * HALF),
        })
    return rows


def steps() -> list[dict]:
    """**境界は垂直。** 段をまたぐと年間いくら増えるか。"""
    rows = []
    for i in range(1, len(GRADES)):
        low, _ = bounds(i)
        jump = GRADES[i] - GRADES[i - 1]
        per_month = int(GRADES[i] * HALF) - int(GRADES[i - 1] * HALF)
        rows.append({
            "この月給で上の段へ": low,
            "標準報酬月額の跳び": jump,
            "保険料の増(月)": per_month,
            "保険料の増(年)": per_month * 12,
        })
    return rows


def raise_is_negative(min_raise: int = 1_000) -> list[dict]:
    """**昇給したのに、その年の手取りが減る組み合わせ。**

    段の境界をまたぐ最小の昇給（境界の1円下 → 境界）を考えます。
    **昇給は年 `min_raise` × 12 円**、保険料の増は段差ぶん。
    **後者が大きい段だけを返します。**

    ここが「表のどこにも載っていない数字」です —— 段の幅と段差の両方を
    掛け合わせないと出てきません。
    """
    rows = []
    for i in range(1, len(GRADES)):
        low, _ = bounds(i)
        before, after = low - min_raise, low
        cost = (premium(after) - premium(before)) * 12
        gain = min_raise * 12
        if cost <= gain:
            continue
        rows.append({
            "昇給前の月給": before,
            "昇給後の月給": after,
            "昇給(年)": gain,
            "保険料の増(年)": cost,
            "差引(年)": gain - cost,
        })
    return rows


def payback(monthly_before: int, monthly_after: int, months: int = 12) -> dict:
    """**取り返すまでの年数。** 段が上がると将来の厚生年金も上がる。

    報酬比例部分 ＝ 平均標準報酬額 × 5.481/1000 × 月数。
    ここでは「その段で `months` か月働いたぶん」の差だけを見ます。
    """
    std_before, std_after = grade_of(monthly_before), grade_of(monthly_after)
    cost = (premium(monthly_after) - premium(monthly_before)) * months
    yearly = (std_after - std_before) * BENEFIT_MULT * months
    return {
        "標準報酬月額(前)": std_before,
        "標準報酬月額(後)": std_after,
        f"保険料の増({months}か月)": cost,
        "年金の増(年・生涯)": round(yearly, 1),
        "取り返す年数": round(cost / yearly, 1) if yearly else None,
    }


def payback_table() -> list[dict]:
    """**段差ごとに、何年もらえば取り返すか。** 1年ぶん納めた場合。"""
    rows = []
    for i in range(1, len(GRADES)):
        low, _ = bounds(i)
        p = payback(low - 1_000, low)
        rows.append({
            "月給": low,
            "標準報酬月額の跳び": p["標準報酬月額(後)"] - p["標準報酬月額(前)"],
            "保険料の増(年)": p["保険料の増(12か月)"],
            "年金の増(年)": p["年金の増(年・生涯)"],
            "取り返す年数": p["取り返す年数"],
        })
    return rows


def check_tables() -> None:
    """制度の値と計算の向きを確かめる。**壊れた数字で台本を書かせない。**"""
    # 1. 法令が名指ししている値
    _checks.statutory(RATE, 0.183, "厚生年金保険料率",
                      source="日本年金機構 厚生年金保険の保険料（2017年9月から固定）")
    _checks.ratio(RATE, "厚生年金保険料率")
    _checks.ratio(HALF, "本人負担の率")
    _checks.statutory(BENEFIT_MULT, 5.481 / 1000, "報酬比例部分の給付乗率",
                      source="総報酬制（2003年4月以降の期間）")

    # 2. 等級表の形。**32段・両端・昇順**
    _checks.statutory(len(GRADES), 32, "等級の数",
                      source="日本年金機構（1等級8万8千円〜32等級65万円）")
    _checks.statutory(GRADES[0], 88_000, "1等級の標準報酬月額", source="同上")
    _checks.statutory(GRADES[-1], 650_000, "32等級の標準報酬月額", source="同上")
    _checks.ascending(GRADES, "標準報酬月額", strict=True)

    # 3. **公表資料で実際に読んだ8点と突き合わせる。**
    #    中ほどの等級を1段でも取り違えると、前後の境界がずれてここで落ちます。
    for no, std, low, high in ANCHORS:
        i = no - 1
        _checks.statutory(GRADES[i], std, f"{no}等級の標準報酬月額",
                          source="公表資料で読んだ点（ANCHORS）")
        got_low, got_high = bounds(i)
        if got_low != low or got_high != high:
            raise _checks.TableError(
                f"{no}等級の報酬月額の範囲が公表資料と合いません: "
                f"導いた値 {got_low}〜{got_high} / 読んだ値 {low}〜{high}")

    # 4. 計算の向き（**この計算の主題そのもの**）
    _checks.never_decreases(premium, [88_000, 200_000, 320_000, 650_000, 900_000],
                            "月給が上がったのに保険料が下がっている")

    # **段の中は平ら**（主題の片方）。同じ等級の下端と上端で保険料が同じこと
    for row in flat_bands():
        lo, hi = row["この月給から"], row["この月給まで"]
        if premium(lo) != premium(hi):
            raise _checks.TableError(
                f"{row['等級']}等級の中で保険料が動いています: "
                f"{lo}円→{premium(lo)}円 / {hi}円→{premium(hi)}円")

    # **境界は垂直**（主題のもう片方）。1円で必ず跳ぶこと
    for row in steps():
        edge = row["この月給で上の段へ"]
        if premium(edge) <= premium(edge - 1):
            raise _checks.TableError(
                f"月給{edge}円の境界で保険料が跳んでいません")
        _checks.rounding(premium(edge) - premium(edge - 1),
                         row["保険料の増(月)"], f"月給{edge}円の段差")

    # 頭打ち・底打ち。**上限を超えても増えない／下限を下回っても減らない**
    _checks.rounding(premium(650_000), premium(2_000_000), "上限の頭打ち")
    _checks.rounding(premium(88_000), premium(10_000), "下限の底打ち")

    # 昇給で減る組み合わせが**実際に在ること**（無ければこの動画は成立しない）
    neg = raise_is_negative()
    if not neg:
        raise _checks.TableError(
            "昇給で手取りが減る境界が1つも出ていません。段差か率の置き方が壊れています")
    for row in neg:
        _checks.greater(row["保険料の増(年)"], row["昇給(年)"],
                        "差引がマイナスの行なのに保険料の増が昇給を下回っています")

    # 取り返す年数は**正で、有限**（年金が増えないなら計算が壊れている）
    for row in payback_table():
        if not row["取り返す年数"] or row["取り返す年数"] <= 0:
            raise _checks.TableError(
                f"月給{row['月給']}円の取り返す年数が出ていません: {row}")

    # **32段すべてで同じ年数になることを、画面で言っています。**
    # 言うなら検査すること —— 率の置き方を変えたら、この主張は静かに嘘になります。
    # （比が 9.15% ÷ 0.5481% に約分され、標準報酬月額の跳びが消えるため）
    yrs = {row["取り返す年数"] for row in payback_table()}
    if len(yrs) != 1:
        raise _checks.TableError(
            f"取り返す年数が段によってちがいます: {sorted(yrs)}。"
            "画面では「32段すべてで同じ」と言っているので、どちらかが誤りです")
    _checks.rounding(yrs.pop(), round(HALF / BENEFIT_MULT, 1),
                     "取り返す年数（率の比に約分されるはず）")

    # **見出しが「(年)」と言っている列は、本当に12倍か。**
    #
    # `_checks.per_unit_steps` はここでは使えません。あれは「1〇〇あたり」と
    # 宣言した列を実際に割る道具で、こちらの列は率ではなく**額**です。
    # ただし **taishoku.py と同じ壊れ方（嘘が見出しの側にある）はここにも在ります** ——
    # `(月)` と `(年)` を並べた表で、後者が12倍になっていない形。
    # **値だけ見る検査は素通りする**ので、対応そのものを書きます。
    for row in steps():
        _checks.rounding(row["保険料の増(年)"], row["保険料の増(月)"] * 12,
                         f"月給{row['この月給で上の段へ']}円の段差の年額")
    for row in raise_is_negative():
        _checks.rounding(row["昇給(年)"], 1_000 * 12, "昇給の年額")
        _checks.rounding(row["差引(年)"],
                         row["昇給(年)"] - row["保険料の増(年)"], "差引の年額")


if __name__ == "__main__":
    check_tables()
    print("制度の値の検査: 通過")

    print("\n=== 厚生年金保険料が1円も増えない月給の幅（32段の階段）===")
    print(f"（保険料率 {RATE:.1%}・本人負担 {HALF:.2%}）")
    print(f"{'等級':>4}{'標準報酬月額':>13}{'この月給から':>13}{'ここまで同じ':>13}"
          f"{'幅':>9}{'本人負担(月)':>13}")
    for r in flat_bands():
        print(f"{r['等級']:>4}{r['標準報酬月額']:>12,}円{r['この月給から']:>12,}円"
              f"{r['この月給まで']:>12,}円{r['同じ保険料の幅']:>8,}円"
              f"{r['本人負担(月)']:>12,}円")
    widest = max(flat_bands(), key=lambda r: r["同じ保険料の幅"])
    print(f"→ いちばん広いのは {widest['等級']}等級。"
          f"月給が {widest['同じ保険料の幅']:,}円ちがっても保険料は同じ")

    print("\n=== 月給1,000円の昇給で厚生年金保険料が跳ぶ境界と、その段差 ===")
    print(f"{'この月給で上の段へ':>18}{'標準報酬月額の跳び':>18}"
          f"{'保険料の増(月)':>15}{'保険料の増(年)':>15}")
    for r in steps():
        print(f"{r['この月給で上の段へ']:>17,}円{r['標準報酬月額の跳び']:>17,}円"
              f"{r['保険料の増(月)']:>14,}円{r['保険料の増(年)']:>14,}円")
    big = max(steps(), key=lambda r: r["保険料の増(年)"])
    print(f"→ いちばん大きい段差は月給 {big['この月給で上の段へ']:,}円の境界。"
          f"年 {big['保険料の増(年)']:,}円")

    print("\n=== 昇給したのにその年の手取りが減る月給の組み合わせ ===")
    neg = raise_is_negative()
    print(f"（月1,000円＝年12,000円の昇給で、境界をまたぐ場合。{len(neg)}件）")
    print(f"{'昇給前の月給':>14}{'昇給後の月給':>14}{'昇給(年)':>12}"
          f"{'保険料の増(年)':>15}{'差引(年)':>12}")
    for r in neg:
        print(f"{r['昇給前の月給']:>13,}円{r['昇給後の月給']:>13,}円"
              f"{r['昇給(年)']:>11,}円{r['保険料の増(年)']:>14,}円"
              f"{r['差引(年)']:>11,}円")
    worst = min(neg, key=lambda r: r["差引(年)"])
    print(f"→ いちばん損なのは 月給 {worst['昇給前の月給']:,}円 → "
          f"{worst['昇給後の月給']:,}円。年 {-worst['差引(年)']:,}円のマイナス")

    print("\n=== 段が上がったぶんの厚生年金を取り返すのは、32段すべてで同じ年数 ===")
    print("（1年ぶん多く納めた場合。報酬比例部分だけ・物価と税は入れていない）")
    print(f"{'月給':>12}{'標準報酬月額の跳び':>18}{'保険料の増(年)':>15}"
          f"{'年金の増(年)':>14}{'取り返す年数':>13}")
    for r in payback_table():
        print(f"{r['月給']:>11,}円{r['標準報酬月額の跳び']:>17,}円"
              f"{r['保険料の増(年)']:>14,}円{r['年金の増(年)']:>13,.1f}円"
              f"{r['取り返す年数']:>11.1f}年")
    yrs = [r["取り返す年数"] for r in payback_table()]
    print(f"→ 取り返す年数は 32段すべてで {min(yrs):.1f}年。**1段も外れない**")
    print(f"   月給にも段差の大きさにもよらないのは、比が "
          f"{HALF:.4f} ÷ {BENEFIT_MULT:.6f} = {HALF / BENEFIT_MULT:.1f} に約分され、"
          "標準報酬月額の跳びが分子と分母から消えるため")
