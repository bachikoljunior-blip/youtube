                           # （62 は「1枚12秒まで止まってよい」の名残りで、
                           #   同じ文書の「1〜2秒ごとに変える」と矛盾していた）


def segment_range(min_chars: int, max_chars: int, is_short: bool) -> tuple[int, int]:
    """セグメント数の目安を出す。

    **ショートは 5〜6 の直値**です（2026-08-09 の決定。上の定数の理由を読むこと）。
    文字数から引いていたのを**やめました。** ショートに長尺の式
    （`min_chars/130` 〜 `max_chars/80`）を通すと **0〜2 個**になり、
    同じプロンプトの「セグメントは5〜6個」という直書きと食い違っていました。
    **食い違ったときは直書きのほうが勝ちます**（モデルは日本語の文を読む）。
    つまり計算値は**最初から効いていませんでした。**

    **長尺は 130／80文字のまま**にしてあります。触る根拠がまだありません
    （実測が 0〜4再生しかなく、何を直せばよいか分からない）。
    """
    if not is_short:
        return int(min_chars / 130), int(max_chars / 80)
    return SHORT_SEGMENTS_LO, SHORT_SEGMENTS_HI

