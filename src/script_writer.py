def used_bars(exclude: str = "") -> list[str]:
    """これまでの動画で chart に出した数値を集める。

    `exclude` に自分のテーマIDを渡すこと。**作り直しで捨てた自分の台本まで
    禁止してしまう**（2026-08-07、繰上げを撃ち直したら前回案の「43万2千円」が
    使用済み扱いになり、訴求の弱い「0.76倍」に逃げた）。
    見たいのは**他の動画と被っていないか**であって、自分の過去案ではない。

    **台本を書く側は過去の動画を知らない。** だから同じ calc を使うと、
    同じ行を選んで同じ図を出す。2026-08-07、年金の繰上げが繰下げと
    3本同じ棒を出した（`180万円・255万6千円・331万2千円`）。
    違いは配色だけで、**ポリシーの「繰り返しのように感じられるコンテンツ」**に当たる。

    `verify.py` が投稿前に止めるが、**止めるだけでは作り直しが繰り返される。**
    先に「これは使用済み」と伝えて、別の行を選ばせる。
    """
    import json

    from . import bars

    # **`build/` は .gitignore に入っていて、コンテナをまたがない。**
    # ここだけを見ていると、新しい実行環境では比較対象がゼロになり、
    # 「使用済み」を1件も伝えないまま黙って通る（`src/bars.py` の冒頭）。
    # 公開済みの棒は `data/published_bars.json` から取る。
    seen: set[str] = set(bars.published_displays(exclude=exclude))
    build = config.ROOT / "build"
    if not build.exists():
        return sorted(seen)
    for path in sorted(build.glob("*/script.json")):
        if exclude and path.parent.name == exclude:
            continue
        try:
            script = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        for seg in script.get("segments") or []:
            v = seg.get("visual") or {}
            if v.get("kind") == "chart":
                for b in v.get("bars") or []:
                    if b.get("display"):
                        seen.add(str(b["display"]))
    return sorted(seen)


def calc_block(topic: dict) -> str:
    """テーマに紐づいた計算を実行して、その出力をそのまま台本の材料にする。

    これが無いと台本を書く側は数字を**発明する**しかない。裏の取れない数字を
    動画に入れないという方針に対して、これは致命的な穴だった。実際これまでは
    常駐セッションが手で台本を書くことで塞いでいたが、それでは自動で回らない。

    topics.yaml に `calc: モジュール名` を書いておくと、`python -m src.calc.<名前>`
    を実行して、標準出力と ASSUMPTIONS を丸ごとプロンプトに入れる。
    台本を書く側は**そこにある数字しか使えない**。
    """
    name = str(topic.get("calc", "")).strip()
    if not name:
        return ""

    import importlib
    import subprocess
    import sys

    try:
        module = importlib.import_module(f".calc.{name}", package="src")
    except ImportError as exc:
        raise RuntimeError(f"テーマ {topic['id']} の calc: {name} が読み込めません: {exc}") from exc

    # 表の取り違えはここで止める。壊れた数字で台本を書かせない。
    if hasattr(module, "check_tables"):
        module.check_tables()

    proc = subprocess.run(
        [sys.executable, "-m", f"src.calc.{name}"],
        capture_output=True, text=True, timeout=300,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"src.calc.{name} が失敗しました: {proc.stderr[-500:]}")

    # **数字が1つも出ていないなら、この仕組みは何も守っていない。**
    # 2026-08-05 に発覚: kojo・shitsugyo・zangyo は関数を定義するだけで
    # `__main__` が無く、標準出力が空だった。calc_block は空のコードブロックを
    # 返し、台本を書く側は「使ってよい数字」がゼロの状態で書いていた。
    # つまり**数字を発明させないために作った仕組みが、半分のテーマで開いていた。**
    # 静かに通すのが一番悪い。ここで止める。
    if not re.search(r"\d", proc.stdout):
        raise RuntimeError(
            f"src.calc.{name} が数字を1つも出力していません。"
            f"`python -m src.calc.{name}` で表が出るように `__main__` を書くこと。"
            "空のまま台本を書かせると、数字を発明させることになります"
        )

    stdout = proc.stdout

    # **答えを決めている値が、その節に1度も出ていないなら止める**（2026-08-17）。
    # 独立評価の1体が `J0QK59pUg-4` について「肝心の年収が一度も画面に出ていない
    # ので検証できない」と書き、実物を見ると**書き手は出しようが無かった** ——
    # `last_step(4_600_000)` の 4,600,000 がどの行にも入っていなかった。
    # **前提と計算式を全部画面に出すのがこの作りの根幹**（`CLAUDE.md`）なので、
    # ここは「作ってから直す」ではなく生成の前で止めます。実測 91節中3件。
    from . import premise
    holes = premise.scan(module.__file__, stdout)
    if holes:
        raise RuntimeError(
            f"src.calc.{name} に、画面に出しようがない前提があります:\n  "
            + "\n  ".join(holes))

    # **渡さない表は、そもそもプロンプトに入れない。**
    #
    # 2026-08-09、長尺の angle に「cliff() と grid() は使うな。ショートで
    # 既に出している」と書いた。**6回作り直して6回とも使われた。**
    # 理由は単純で、(1) 禁止した表だけが標準出力に入っており、
    # (2) 代わりに使えと書いた表を `main()` が印字していなかった。
    # **モデルは従いようがなかった。**
    #
    # 「使うな」は、目の前に置いたまま言っても効かない。**取り除くこと。**
    # topics.yaml に `calc_sections: ["売上と経費"]` と書くと、
    # `=== ... ===` の見出しがその語を含む節だけを残す。
    wanted = topic.get("calc_sections") or []
    if wanted:
        blocks, current = [], []
        for line in stdout.splitlines():
            if line.startswith("==="):
                if current:
                    blocks.append(current)
                current = [line]
            elif current:
                current.append(line)
            # 見出しより前の行（検査の通過表示など）は捨てる
        if current:
            blocks.append(current)
        kept = ["\n".join(b) for b in blocks
                if any(w in b[0] for w in wanted)]
        if not kept:
            raise RuntimeError(
                f"calc_sections {wanted} に当たる節が src.calc.{name} の出力にありません。"
                f"見出しは {[b[0] for b in blocks]}。"
                "**`main()` がその表を印字しているか確かめること。**"
                "印字していない表を angle で指定しても、モデルには渡りません"
            )
        stdout = "\n\n".join(kept)

    assumptions = getattr(module, "ASSUMPTIONS", [])
    if isinstance(assumptions, str):
        assumptions = [assumptions]
    # **前提に値が入っていないまま、書き手に渡さないこと**（2026-08-16。8回持ち越し）。
    # ここが渡すのは `ASSUMPTIONS` の文だけで、表は渡りません。値の無い前提を渡すと、
    # 書き手は黙って落とす（→ verify が1本まるごと捨てる）か、自分で数字を作る
    # （→ 裏の取れない数字が動画に入る）しかありません。**生成に入る前に止めます。**
    _checks.assumption_values(assumptions, name=name)
    used = used_bars(exclude=str(topic.get("id", "")))
    used_block = ""
    if used:
        used_block = (
            "\n# すでに他の動画で出した数値（**これらを chart に使わないこと**）\n\n"
            "同じ数値の棒を並べると、チャンネルを続けて見た人に「繰り返し」と映ります。\n"
            "YouTube はそれを収益化の対象外にしています。**別の行を選んでください。**\n"
            "2本以上が一致すると投稿前の検査で落ちて、作り直しになります。\n\n"
            "```\n" + "・".join(used[:60]) + "\n```\n"
        )
    return f"""
# この動画で使う数字（計算済み）

**ここに出ている数字だけを使ってください。** 数字を自分で作らないこと。
足し算や割り算で新しい数字を導くのも禁止です。ここに無い数字が必要になったら、
その話題自体を落としてください。裏の取れない数字を動画に入れないためです。

```
{stdout.strip()}
```

# 計算の前提（そのまま画面と音声に出すこと）

{chr(10).join(f"- {a}" for a in assumptions)}
{used_block}"""


#: 題を問いの形にする割合。**0 にすると振り分けが止まります**（＝ 何も測れなくなる）。
TITLE_ASK_SHARE = 0.5


def title_form(topic_id: str, share: float = TITLE_ASK_SHARE) -> str:
    """この本の題を「問い」にするか「断定」にするか。**テーマIDで決まります。**

    ## なぜ振り分けるのか（2026-08-19 16:2x に測って足した）

    `scripts/eta.py` が名指しする律速は **1本あたりの再生**で、`scripts/status.py`
    の実測ではそこに最も強く効く率が **engaged（すぐスワイプされなかった割合）+0.62** です。
    `scripts/build_perf.py` に特徴を足して測り直したところ、**測れた8つの特徴は
    どれも engaged と無関係**（|ρ| ≤ 0.23）でした。engaged の実測幅は **3.8倍**
    あるので、効いているのは**一覧に無いもの**の側です。

    そして同じ道具が、こう言いました ——

        題が問いか   19本とも同じ値＝**一度も試していない**

    **「効かない」ではありません。「まだ1本も出していない」です。**
    `status.py` も別の道で「**動画が視聴者に何も問いかけていない**」と書いています。
    向きを知る道は1つしかなく、**違う値の本を作って出すこと**です。

    ## なぜ「テーマIDで決める」のか

    - **乱数にしないこと。** 同じテーマを作り直すたびに形が変われば、
      落ちて撃ち直した本が別の群に移り、比較が壊れます
    - **日付や順番にしないこと。** `batch_build` は1日ぶんをまとめて撃つので、
      日で分けると「その日の題材の当たり外れ」と混ざります（M14 と同じ形）
    - IDのハッシュなら、**同じ日の中で半々に混ざり**、作り直しでも動きません

    判定は `config/hypotheses.yaml`（2026-09-12）。
    """
    if share <= 0:
        return "断定"
    if share >= 1:
        return "問い"
    h = hashlib.sha1(str(topic_id).encode("utf-8")).digest()
    return "問い" if (int.from_bytes(h[:4], "big") % 10_000) < share * 10_000 else "断定"


#: 問いの側にだけ足す指示。**断定の側には1文字も足しません**（対照群を汚さない）。
ASK_TITLE_RULE = """
# 今回の題の形（**この動画だけの指定**）

タイトルを**問いの形**にしてください。答えを題に書かず、**視聴者が自分の数字を
当てはめたくなる問い**にすること。ここは冒頭でいちばん先に読まれる場所です。

- 例:「医療費20万円で戻るのは何円か」「扶養1人で上限はいくら下がるか」
- **前提の数字（入力の側）は題に残すこと。** 「いくら得するか」だけでは
  何の話か分かりません。**答えの数字（計算の結果）は題に書かない**
- 煽らない。「衝撃」「知らないと損」は禁止のままです
- 全角32文字以内・#Shorts の規則はそのまま
- **サムネイルと first_comment は変えないこと。** 変えると、何が効いたか分かりません
"""


#: 冒頭の主役（1枚目の `note`）を問いの形にする割合。**0 にすると振り分けが止まります。**
HOOK_ASK_SHARE = 0.5


def hook_form(topic_id: str, share: float = HOOK_ASK_SHARE) -> str:
    """冒頭1枚目の主役を「問い」にするか「条件」にするか。**テーマIDで決まります。**

    ## なぜ「冒頭の note」なのか（2026-08-19 20:4x に測って足した）

    `scripts/eta.py` は6帯とも「1日の上限まで出しても月20万に届かない」と言い、
    **動くのは「1本あたりの再生」か「RPM」の2つだけ**だと名指しします。
    そのうちこの機械で動かせるのは前者で、`scripts/status.py` の実測では
    **engaged（すぐスワイプされなかった割合）が再生数と同じ向き（+0.61）**です。

    **その engaged が決まるのは1枚目です。** そして1枚目に出ているのは、
    見出しでも数字でもなく `note` でした ——
    `visuals.reveal_variants` は冒頭の `kind=stat` を2枚に割り、
    **1枚目の `stat` と `formula` を空にします**（実測 332/341 ＝ 97%）。
    残った `note` を `visuals.py` が `.note.lead` として大きく出すので、
    **冒頭1〜2秒に画面を占めているのはここ**です。

    在庫341本を型べつに数えると、こうでした（主役が `note` の332本）:

        条件の列挙（`・` で並ぶ）   171 / 332 ＝ 52%
        場合／試算                 57 / 332 ＝ 17%
        比較                       18 / 332 ＝  5%
        **問いかけ                   0 / 332 ＝  0%**
        **「あなた／自分」を含む       0 / 332 ＝  0%**

    `title_form` が題で見つけたのと**同じ形**です —— 「効かない」ではなく
    **「一度も試していない」**。`status.py` も別の道から
    「**動画が視聴者に何も問いかけていない**」と書いています。
    向きを知る道は1つしかなく、**違う値の本を作って出すこと**です。

    ## 割り振りは `title_form` を写しています。**塩だけ変えてあります**

    - **乱数にしない**（作り直しで群が移ると比較が壊れる）
    - **日付や順番にしない**（`batch_build` は1日ぶんをまとめて撃つので題材と混ざる）
    - **塩を `title_form` と変えること。** 同じにすると2つの実験が完全に重なり、
      題の形と冒頭の形の**どちらが効いたのか永久に分かりません**
      （`tests/test_hook_form.py` がそこを見ています）

    判定は `config/hypotheses.yaml`（2026-09-16）。
    """
    if share <= 0:
        return "条件"
    if share >= 1:
        return "問い"
    # **塩 `hook:`**。`title_form` と同じ塩にしないこと（docstring の最後の項）。
    h = hashlib.sha1(("hook:" + str(topic_id)).encode("utf-8")).digest()
    return "問い" if (int.from_bytes(h[:4], "big") % 10_000) < share * 10_000 else "条件"


#: 問いの側にだけ足す指示。**条件の側には1文字も足しません**（対照群を汚さない）。
ASK_HOOK_RULE = """
# 今回の冒頭1枚目（**この動画だけの指定**）

1つ目のセグメント（`kind=stat`）の `note` を、**視聴者への問いかけ**にしてください。
ここは動画の最初の1〜2秒で、**数字より先に読まれる場所**です。

- **前提の数字は消さないこと。** 条件を消すと、何の話か分からない画面になります。
  条件を書いたうえで、**視聴者が自分の数字を当てはめたくなる**言い方にすること
- 例:「月給30万円なら、あなたはいくら戻る？」「扶養1人だと上限はいくつ下がる？」
- **答えの数字は書かない**（2枚目で出ます）。「〇円戻る」と書くと問いになりません
- 全角24文字以内。ここは大きい字で出るので、長いと1枚目で読み切れません
- 煽らない。「知らないと損」「衝撃」は禁止のままです
- **見出し・stat・formula・読み上げ文・サムネイル・first_comment は変えないこと。**
  変えると、何が効いたのか分かりません
"""


def generate(channel: dict, topic: dict) -> VideoScript:
    """台本を1本生成する。尺が足りなければ同じセッションで書き足させる。"""
    cfg = channel["channel"]
    vid = channel["video"]
    model = channel["generation"]["model"]

    target = float(vid["target_minutes"])
    # 上限は「目標＋1.5分」を既定にするが、ショートではこの足し算が効かない。
    # 目標50秒に1.5分を足すと上限が2分22秒になり、**上限が無いのと同じ**になる。
    # 実際それで、60秒のつもりのショートが1.4分で出てきた。
    # max_minutes を明示できるようにして、ショート側から渡す。
    max_minutes = float(vid.get("max_minutes") or (target + 1.5))
    min_chars = int(float(vid["min_minutes"]) * CHARS_PER_MINUTE)
    max_chars = int(max_minutes * CHARS_PER_MINUTE_SLOW)
    if max_chars <= min_chars:
        raise RuntimeError(
            f"尺の上限({max_minutes}分)が下限({vid['min_minutes']}分)を下回っています。"
            "config/channel.yaml の max_minutes を見直してください"
        )

    # `max_minutes <= 1.5` がショートの判定。**下の follow_up と同じ条件を使うこと。**
    # 別々に持つと、片方だけ直したときに静かにずれます。
    is_short = max_minutes <= 1.5
    seg_lo, seg_hi = segment_range(min_chars, max_chars, is_short)
    if is_short:
        print(f"[script] セグメント数の目安: {seg_lo}〜{seg_hi}"
              f" / 1文 {SHORT_SEGMENT_CHARS}文字まで"
              f"（絵は `src/pipeline.py` で {SLIDE_SECONDS_MAX}秒ごとに割ります）")

    # **ROLE も format すること。** ここは長く素の連結でした。
    # ショートの規則を直値からこの値に差し替えたので、format を通さないと
    # `{short_segment_chars}` がそのまま文字としてモデルに渡ります。
    role = ROLE.format(
        short_segment_chars=SHORT_SEGMENT_CHARS,
        slide_seconds_max=SLIDE_SECONDS_MAX,
        min_segments=seg_lo,
        max_segments=seg_hi,
    )
    prompt = role + "\n" + TASK.format(
        channel_name=cfg["name"],
        niche=cfg["niche"],
        audience=cfg["audience"],
        persona=cfg["persona"].strip(),
        avoid="\n".join(f"- {a}" for a in cfg["avoid"]),
        topic_title=topic["title_seed"],
        topic_angle=topic["angle"],
        calc_block=calc_block(topic),
        min_chars=min_chars,
        max_chars=max_chars,
        target_minutes=target,
        min_segments=seg_lo,
        max_segments=seg_hi,
    )

    # **題の形の振り分け**（`title_form` の docstring に理由）。
    # 断定の側には1文字も足しません —— 足すと対照群でなくなります。
    form = title_form(topic.get("id", ""))
    if form == "問い":
        prompt += ASK_TITLE_RULE
    print(f"[script] 題の形: {form}（テーマIDで決まる。割合 {TITLE_ASK_SHARE:.0%}）")

    # **冒頭1枚目の形の振り分け**（`hook_form` の docstring に理由）。
    # 条件の側には1文字も足しません —— 足すと対照群でなくなります。
    hook = hook_form(topic.get("id", ""))
    if hook == "問い":
        prompt += ASK_HOOK_RULE
    print(f"[script] 冒頭1枚目の形: {hook}（テーマIDで決まる。割合 {HOOK_ASK_SHARE:.0%}）")

    script, session = ask(VideoScript, prompt, model=model)
    chars = _total_chars(script)
    print(f"[script] 初稿: {len(script.segments)}セグメント / {chars}文字")

    if chars < min_chars and session:
        script, _ = follow_up(
            VideoScript,
            session,
            (
                f"narration の合計が{chars}文字しかなく、目標の{min_chars}文字に届いていません。"
                "内容を薄めずに、具体例・数値・手順・よくある間違いを足してセグメントを増やし、"
                "同じ JSON 形式で全体を出し直してください。"
            ),
            model=model,
        )
        chars = _total_chars(script)
        print(f"[script] 加筆後: {len(script.segments)}セグメント / {chars}文字")

    if chars < min_chars:
        print(f"[script] 警告: 目標{min_chars}文字に届きませんでした（{chars}文字）")

    # **落ちた事実を渡して、同じセッションで直させる輪。**
    #
    # ショート: 2026-08-09、指示に「60文字以内」と書いても 86〜93文字で返ってきて、
    # 前倒し検査に3回続けて落ちた。**文章での指示は守られない。**
    # 短すぎる側には書き足させる仕組みがあるのに、長すぎる側には無かった（片方だけ）。
    #
    # 長尺: **2026-08-24 まで、この輪は `max_minutes <= 1.5` の中にありました** ——
    # つまりショート専用で、長尺には直す口が1つもありませんでした。実測は
    # ショート 10/10・長尺 0/3・0/8 で、落ちた 3/3 は全部
    # 「過去の図と棒が2本以上共通」。**書き直しで直る種類の指摘**を、
    # `claude -p` に約250秒使ったあと `pipeline.py` で捨てていました。
    # **輪はどちらにも要ります。** 違うのは「何を見るか」と「どう直せと言うか」だけ。
    # `is_short` は上（セグメント数を決めるところ）で1度だけ作っています。
    # **ここで作り直さないこと** —— あちらのコメントが「下の follow_up と
    # 同じ条件を使うこと。別々に持つと、片方だけ直したときに静かにずれます」。
    problems_of = short_script_problems if is_short else long_script_problems
    kind_label = "ショート" if is_short else "長尺"
    fix_guidance = SHORT_FIX_GUIDANCE if is_short else LONG_FIX_GUIDANCE
    if session:
        for attempt in range(3):
            problems = problems_of(script, topic.get('id', ''))
            if not problems:
                break
            print(f"[script] {kind_label}の条件を満たしていません（{attempt + 1}回目）:")
            for p in problems:
                print(f"  - {p}")
            script, _ = follow_up(
                VideoScript,
                session,
                (
                    "**この台本は投稿前の検査に落ちます。** 直してください:\n"
                    + "\n".join(f"- {p}" for p in problems)
                    + "\n\n"
                    + fix_guidance
                ),
                model=model,
            )
        remaining = problems_of(script, topic.get('id', ''))
        if remaining:
            print(f"[script] 警告: {len(remaining)}件がまだ残っています。"
                  "パイプラインが合成前に止めます")

    return script


