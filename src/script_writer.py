def short_script_problems(script, topic_id: str = "") -> list[str]:
    """ショートの台本の不備を並べる。空なら合格。

    **ここが唯一の正本。** `generate()` は生成中にこれを見て直させ、
    `src/pipeline.py` は音声合成の前にこれを見て落とす。
    **2つの場所に同じ規則を書かない**（片方だけ直す形を 2026-08-08〜09 に
    5回やっている）。

    直させる側と落とす側で条件がずれると、**生成側が通したものを
    パイプラインが落とし続ける**。実際 2026-08-09、長さだけを直させていて
    「明日やること」を返していなかったため、長さが直った台本が
    別の理由で落ち続けた。

    **さらに `verify` との間にも同じずれがあった。** ここは長さしか見ず、
    `verify` は「1枚目が stat か」「過去の図と重なっていないか」まで見る。
    そのため長さの直った台本が**レンダリングまで終わってから**落ちた。
    **台本だけで判定できるものは、全部ここに集める。**
    `verify` は最後の砦として残す（音声や画像が絡むものはあちらでしか見えない）。
    """
    problems = []
    for i, seg in enumerate(script.segments):
        n = len(seg.narration)
        if n > SHORT_SEGMENT_CHARS:
            problems.append(
                f"{i}番目のセグメントが{n}文字（上限{SHORT_SEGMENT_CHARS}）。"
                f"読み上げ約{n / 5.2:.0f}秒。**内容を削ること。**"
                f"文を2つに分けても、合計140文字を超えたままなら直っていません"
            )
    # **冒頭は別の上限。** 落差は 4.7〜5.7秒に来るのに、1枚目が 8〜14秒あると
    # **画面が一度も変わらないまま**その時刻を通過する（上の定数のコメント）。
    for i, limit in ((0, SHORT_FIRST_SEGMENT_CHARS), (1, SHORT_SECOND_SEGMENT_CHARS)):
        if len(script.segments) > i:
            n = len(script.segments[i].narration)
            if n > limit:
                problems.append(
                    f"{i}番目のセグメントが{n}文字（冒頭の上限{limit}）。"
                    f"読み上げ約{n / 5.2:.1f}秒。**離脱は4.7〜5.7秒に来ます。**"
                    "そこまでに画面が変わっていないと、何を出しても届きません。"
                    "**削るのであって、後ろへ回すのではありません**"
                    "（合計140文字は変わらないので、内容そのものを1つ落とすこと）"
                )
    total = sum(len(s.narration) for s in script.segments)
    if total > SHORT_TOTAL_CHARS:
        problems.append(
            f"ナレーション合計が{total}文字（上限{SHORT_TOTAL_CHARS}）。"
            f"動画の尺で約{total / EFFECTIVE_CHARS_PER_SECOND:.0f}秒"
            "（無音込みの実効 4.63文字/秒）でショートとして長すぎます。"
            "**セグメントを分けるのではなく、内容を1つに絞って削ること。**"
            "1本＝1つの計算結果。派生は別の動画にする"
        )

    # **2枚目が「前提」だと、5秒で動画が再スタートして離脱する**（8/9 実測）。
    # 指示に書いても守られないので機械で見る。前提そのものは残す（後ろに置く）。
    if len(script.segments) > 1:
        head2 = (script.segments[1].visual.headline or "") + script.segments[1].narration[:24]
        if "前提" in head2:
            problems.append(
                "2枚目が「前提」になっています。**ここで動画が再スタートし、"
                "5秒地点で離脱します**（2026-08-09 実測、3本とも4.7〜5.7秒で最大の落差）。"
                "前提は残したまま**後ろへ移し**、2枚目は結論の内訳や次の疑問にすること"
            )
    problems += _subject_missing(script, topic_id)

    if script.segments and "明日やること" in script.segments[-1].narration:
        problems.append(
            "最後のセグメントに「明日やること」が入っています。"
            "これは長尺だけの型です。ショートの最後は手順ではなく、"
            "**登録の依頼を1文**にしてください（2026-08-24 に解禁。"
            "「この場所で毎回何が手に入るか」型は 2,720再生で登録0人ですが、"
            "その標本では効きなしでも38%が0人になるので**証拠になっていません**。"
            "`python -m src.verdict_power`）"
        )

    # `verify` が持っている検査のうち、**台本だけで判定できるもの**をここでも当てる。
    # 関数はあちらから借りる（同じ規則を2か所に書かない）。
    from . import config, verify

    data = script.model_dump()
    problems += [p.strip() for p in verify._check_short_opening(data)]
    # **この2つは 2026-08-15 に足した。生成中に直させるのが本命です。**
    # どちらも「独立評価の3体が独立に書いたのに、機械の検査はどこも見ていなかった」もの。
    # レンダリングまで待つ理由が無い（台本だけで判定できる）ので、ここで当てる。
    problems += [p.strip() for p in verify._check_adjacent_repeat(data)]
    problems += [p.strip() for p in verify._check_formula_shown(data)]
    # **前提の値が画面に届いているか**（2026-08-16 に足した）。
    # 独立評価の3体が**2本続けて**「手取り率が何パーセントか最後まで画面に出ない
    # ＝検算できない」と書いた。式の形は上の検査が見ているが、
    # **その式に入れる値が画面に無い**ことは誰も見ていなかった。
    # 台本だけで判定できるので、レンダリングを待たずここで直させる。
    problems += [p.strip() for p in verify._check_assumption_value_shown(data)]
    if topic_id:
        problems += [p.strip() for p in
                     verify._check_not_repeat(config.BUILD_DIR / topic_id, data)]
        # **数字の出どころの2件は 2026-08-15 22:5x に足した。歩留まりのためです。**
        #
        # 8/15 22:2x の batch は 6本中2本しか予約できず、**落ちた4本のうち3本が
        # これ**だった（タイトル・サムネ・冒頭 stat の数字が計算出力に無い）。
        # どちらも `verify` にしか無く、**当たるのはレンダリングが全部終わったあと。**
        # そこには直す口が無いので、その1本は丸ごと捨てになっていました。
        # 1本2.7分（同時6の実測）なので、**3本＝8分がここで消えていた。**
        #
        # **2つとも台本だけで判定できます**（calc を走らせて突き合わせるだけで、
        # 音声も画像も要らない）。この関数の冒頭に「台本だけで判定できるものは
        # 全部ここに集める」と書いてあるのに、この2件だけ集め忘れていました。
        # ここに置けば `generate()` の作り直しの輪に入り、**同じセッションが
        # 計算出力を見たまま書き直します**（丸めた数字を戻すのはその場が一番安い）。
        problems += _calc_source_problems(topic_id, data)
    return problems


def long_script_problems(script, topic_id: str = "") -> list[str]:
    """長尺の台本の不備を並べる。空なら合格。**`short_script_problems` の長尺版。**

    **なぜ要ったか**（2026-08-24 の実測）。`generate()` の作り直しの輪は
    `max_minutes <= 1.5`、つまり**ショートにしか掛かっていませんでした。**
    そのため長尺は、**直る種類の指摘で1本まるごと捨てになっていました**:

        ショート  08-24 は 10/10 通過   ← 落ちても3回まで書き直せる
        長尺      0/3・0/8              ← 書き直す口が1つも無い

    落ちていた 3/3 は全部 `verify._check_not_repeat`（過去の図と棒が2本以上共通）で、
    当たるのは `claude -p` に約250秒使ったあとの `pipeline.py` です。そこには
    直す口が無い。**「この棒は等差の梯子で、`s-nisa-…` と3本かぶっている。
    計算結果の桁で書き直せ」と言えば直る指摘**を、捨てるために使っていました。

    **並べる検査は、長尺に対して `verify.run` が実際に当てるものと同じにします。**
    厳しくしないこと —— ここで余分に落とすと、通る台本が
    書き直しの回数（3回）を使い切って、**かえって歩留りが下がります。**
    なので `_check_headline_from_calc` は入れません（`verify` は
    portrait のときしか当てていない）。

    `_check_slides` は `work/slides` がまだ無いので chart の枚数だけを見ます
    （画像の重複はレンダリング後にしか見えないので、そこは `verify` に残す）。
    """
    from . import config, verify

    data = script.model_dump()
    work = config.BUILD_DIR / (topic_id or "_no_topic")

    problems = []
    problems += [p.strip() for p in verify._check_visual_wrap(data, False)]
    problems += [p.strip() for p in verify._check_count_matches(data)]
    problems += [p.strip() for p in verify._check_adjacent_repeat(data)]
    problems += [p.strip() for p in verify._check_formula_shown(data)]
    problems += [p.strip() for p in verify._check_assumption_value_shown(data)]
    # **耳で言った数が、目に出ているか**（2026-08-26 に足した）。
    #
    # `verify` はこれを `if portrait:` の中に置いていたので、**長尺は1本も
    # 通っていませんでした。** 控え430本の実測で、門が入った 08/17 より後の
    # 漏れは **ショート 0/397・長尺 7/33（21%）＝ 100% が長尺**。
    # 同じ回に `verify` 側を `portrait` の外へ出したので、**ここにも要ります**
    # —— この関数の冒頭が「並べる検査は `verify` が実際に当てるものと同じにする」
    # と書いており、`verify` が当てるようになったからです。
    #
    # **そして、ここに置く理由のほうが本体です。** `verify` で落とすと
    # 1本まるごと捨て（`claude -p` 約250秒＋合成＋レンダリング）ですが、
    # ここなら**同じセッションが計算結果を見たまま3回まで書き直せます。**
    # 直し方も1行（言った数を棒か行か見出しに足す／その数を言わない）なので、
    # `_check_not_repeat` を 2026-08-24 にここへ移したときと同じ形です。
    #
    # `work/slides_plan.json` はまだ無いので、`verify._plan_frames` が
    # 台本の `visual` で代用します。**長尺は割らない**ので同じものです。
    problems += [p.strip() for p in
                 verify._check_narrated_shown(work, data, from_script=True)]
    problems += [p.strip() for p in verify._check_yomi(data)]
    problems += [p.strip() for p in verify._check_slides(work, data)]
    if topic_id:
        # **本命はこれ。** 3/3 がここで死んでいました。
        problems += [p.strip() for p in verify._check_not_repeat(work, data)]
        problems += [p.strip() for p in
                     verify._check_law_citation_verbatim(work, data)]
        topic = None
        try:
            for t in config.load_topics().get("topics") or []:
                if str(t.get("id")) == topic_id:
                    topic = t
                    break
        except Exception:
            topic = None
        if topic is not None:
            problems += [p.strip() for p in
                         verify._check_title_from_calc(work, data, topic)]
    return problems


def _calc_source_problems(topic_id: str, data: dict) -> list[str]:
    """**タイトル・サムネ・冒頭 stat の数字が、計算出力に実在するか。**

    `verify._check_headline_from_calc` と `verify._check_title_from_calc` を
    そのまま借りる（同じ規則を2か所に書かない）。calc は数十ミリ秒で走るので、
    作り直しの輪の中で毎回当てても費用にならない。

    **落とさないこと。** ここは生成中に呼ばれるので、calc が引けない・
    テーマが見つからないといった事情で例外を投げると、
    **数字とは関係のない理由で台本作りごと止まります。**
    最後の砦は `verify` 側に残っているので、ここは「見つかったら言う」だけでよい。
    """
    from . import config, verify

    work = config.BUILD_DIR / topic_id
    problems = [p.strip() for p in verify._check_headline_from_calc(work, data)]
    # 条文の引用は、書き手が言い換えると壊れる（2026-08-16、`雇用保険法22条23条`）。
    # **ここに置くのは、直せる場所がここだけだから** —— レンダリング後に落とすと
    # 1本まるごと捨てになるが、輪の中なら同じセッションが calc を見たまま写し直す。
    problems += [p.strip() for p in verify._check_law_citation_verbatim(work, data)]

    topic = None
    try:
        for t in config.load_topics().get("topics") or []:
            if str(t.get("id")) == topic_id:
                topic = t
                break
    except Exception:
        topic = None
    if topic is not None:
        problems += [p.strip() for p in verify._check_title_from_calc(work, data, topic)]
    return problems


