#: **締め方の型は、画面の見出しにも当てること**（2026-08-30 夜に足した）。
#:
#: 上の8通りは、どれも**読み上げ（narration）だけ**を指定していました。
#: ところが控えの `*.plan.json` を測ると、揃っているのは画面のほうです
#: （`python -m src.frames`・API 0単位）:
#:
#:     長尺 134本    読み上げの最終行の頭「明日やる」 61%
#:                   **最後のコマの見出し「明日やる」 83%**（実効 2.1本ぶん）
#:     ショート 521本 最後のコマの見出しが「あなたの」29% ＋「あなたは」25%
#:
#: **読み上げだけ4通りに散らしても、画面に同じ見出しが並べば同じ動画に見えます。**
#: 出口は `verify._check_screen_frame_repeat()`（`script_only_problems()` の中 ＝
#: **クリップを焼く前**）。**入口と出口の両方に置くのは、解除条件1・2 と同じ形です。**
CLOSING_HEADLINE_RULE = """
# 最後のコマの**見出し**（`visual.headline`）について

- **上で指定した締め方の型を、見出しのほうにも当てること。**
  読み上げだけ変えて、見出しを前と同じ言葉にしないこと
- **「明日やること」「あなたの◯◯」を見出しに置かないこと。**
  実測で、最後のコマの見出しは長尺の **83%** が同じ4文字で始まっていました
  （読み上げの 61% より揃っています ＝ **目のほうが先に気づきます**）
- 見出しはその回の**題材の語**を入れて言い換えること
  （型の名前をそのまま書かない。「限界」「置換」は見出しではありません）
"""


def generate(channel: dict, topic: dict) -> VideoScript:
    """台本を1本生成する。尺が足りなければ同じセッションで書き足させる。"""
    cfg = channel["channel"]
    vid = channel["video"]
    model = channel["generation"]["model"]

    target = float(vid["target_minutes"])
    # 上限は「目標＋1.5分」を既定にするが、ショートではこの足し算が効かない。
    # 目標50秒に1.5分を足すと上限が2分22秒になり、**上限が無いのと同じ**になる。
    # 実際それで、60秒のつもりのショートが1.4分で出てきた。
    # max_minutes を明示できるようにして、ショート側から渡す。
    max_minutes = float(vid.get("max_minutes") or (target + 1.5))
    min_chars = int(float(vid["min_minutes"]) * CHARS_PER_MINUTE)
    max_chars = int(max_minutes * CHARS_PER_MINUTE_SLOW)
    if max_chars <= min_chars:
        raise RuntimeError(
            f"尺の上限({max_minutes}分)が下限({vid['min_minutes']}分)を下回っています。"
            "config/channel.yaml の max_minutes を見直してください"
        )

    # `max_minutes <= 1.5` がショートの判定。**下の follow_up と同じ条件を使うこと。**
    # 別々に持つと、片方だけ直したときに静かにずれます。
    is_short = max_minutes <= 1.5
    seg_lo, seg_hi = segment_range(min_chars, max_chars, is_short)
    # **`style: outside_short`（外の帯の上位のショートの型）は、尺だけ別の帯です**
    # （2026-09-05 11:xx・サブの回）。`short_total_band()` が **落とす床** を
    # 140〜180秒 の帯へ移すのに、ここで **命じる尺** が 0.5分（140字）のままだと、
    # 長尺が 09/05 03:4x に踏んだ「命じる尺と落とす床が食い違い、書き直しの3回を
    # 食い尽くして1本も出せない」を、そのままショート側で繰り返します。
    # **床と同じ関数から引く**（`outside_short.total_chars_band()`）。
    # 上端だけ 8秒 手前で止めます —— YouTube のショートの区切りは 3分（`forms.SHORT_MAX_SECONDS`）で、
    # 帯の上端 180秒 と同じ数なので、そこへ寄せた本は 1秒 溢れただけで長尺になります。
    outside_short_style = str(topic.get("style") or "") == "outside_short"
    if outside_short_style:
        from . import outside_short as _osh                       # noqa: PLC0415
        is_short = True
        min_chars, band_hi = _osh.total_chars_band()
        max_chars = min(band_hi, int((_osh.LENGTH_BAND[1] - 8) * EFFECTIVE_CHARS_PER_SECOND))
        seg_lo = math.ceil(min_chars / SHORT_SEGMENT_CHARS)
        seg_hi = math.ceil(max_chars / 25)
        print(f"[script] 作り: outside_short —— 尺は外の帯 {_osh.LENGTH_BAND[0]}〜{_osh.LENGTH_BAND[1]}秒"
              f"（命じる {min_chars}〜{max_chars}字・床 {min_chars}〜{band_hi}字・"
              f"セグメント {seg_lo}〜{seg_hi}）。ROLE の『上限140文字』はこの本に当てません")
    if is_short:
        print(f"[script] セグメント数の目安: {seg_lo}〜{seg_hi}"
              f" / 1文 {SHORT_SEGMENT_CHARS}文字まで"
              f"（絵は `src/pipeline.py` で {SLIDE_SECONDS_MAX}秒ごとに割ります）")

    # **ROLE も format すること。** ここは長く素の連結でした。
    # ショートの規則を直値からこの値に差し替えたので、format を通さないと
    # `{short_segment_chars}` がそのまま文字としてモデルに渡ります。
    role = ROLE.format(
        short_segment_chars=SHORT_SEGMENT_CHARS,
        slide_seconds_max=SLIDE_SECONDS_MAX,
        min_segments=seg_lo,
        max_segments=seg_hi,
    )
    prompt = role + "\n" + TASK.format(
        channel_name=cfg["name"],
        niche=cfg["niche"],
        audience=cfg["audience"],
        persona=cfg["persona"].strip(),
        avoid="\n".join(f"- {a}" for a in cfg["avoid"]),
        topic_title=topic["title_seed"],
        topic_angle=topic["angle"],
        calc_block=calc_block(topic),
        min_chars=min_chars,
        max_chars=max_chars,
        target_minutes=target,
        min_segments=seg_lo,
        max_segments=seg_hi,
    )

    # **題の形の振り分け**（`title_form` の docstring に理由）。
    # 断定の側には1文字も足しません —— 足すと対照群でなくなります。
    # **題材の作り**（`style: outside_long`・上の `OUTSIDE_LONG_RULE` に理由）。
    # 題の形の振り分けより先に足す —— こちらは題の形そのものを指定する節なので。
    if not is_short and str(topic.get("style") or "") == "outside_long":
        prompt += OUTSIDE_LONG_RULE
        print("[script] 作り: outside_long（外の帯の上位の長尺の形を写す）")
    # **ショート側の同じ口**（`src/outside_short.OUTSIDE_SHORT_RULE`・脚は `legs_of_script`）。
    # 上の `outside_short_style` の節で尺は帯へ移してあります。ここは**型の本文**だけ。
    if is_short and outside_short_style:
        prompt += _osh.rule_text()
        print("[script] 作り: outside_short（外の帯の上位のショートの形を写す）")

    form = title_form(topic.get("id", ""))
    if form == "問い":
        prompt += ASK_TITLE_RULE
    print(f"[script] 題の形: {form}（テーマIDで決まる。割合 {TITLE_ASK_SHARE:.0%}）")

    # **冒頭1枚目の形の振り分け**（`hook_form` の docstring に理由）。
    # 条件の側には1文字も足しません —— 足すと対照群でなくなります。
    hook = hook_form(topic.get("id", ""))
    if hook == "問い":
        prompt += ASK_HOOK_RULE
    print(f"[script] 冒頭1枚目の形: {hook}（テーマIDで決まる。割合 {HOOK_ASK_SHARE:.0%}）")

    # **登録の依頼を途中にも入れるかの振り分け**（`request_form` の docstring に理由）。
    # 終端のみの側には1文字も足しません —— 足すと対照群でなくなります。
    # **ショートだけ。** 長尺は依頼そのものを書かないので、どちらの群でもありません。
    req = request_form(topic.get("id", ""))
    if is_short and req == "途中あり":
        prompt += MID_REQUEST_RULE
    if is_short:
        print(f"[script] 登録の依頼: {req}（テーマIDで決まる。割合 {MID_REQUEST_SHARE:.0%}）")

    # **入り方と締め方の振り分け**（解除条件3。`opening_form` の docstring に理由）。
    # **上の3つと違い、どちらの側にも指示を足します** —— これは
    # 「どちらが効くか」の実験ではなく、**同じ入り方が並ばないようにする**ためです。
    opening = opening_form(topic.get("id", ""))
    closing = closing_form(topic.get("id", ""), portrait=is_short)
    prompt += OPENING_RULES[opening] + CLOSING_RULES[closing] + CLOSING_HEADLINE_RULE
    print(f"[script] 入り方: {opening} ／ 締め方: {closing}"
          f"（テーマIDで決まる。`python -m src.frames --forms` で散り方を数える）")

    script, session = ask(VideoScript, prompt, model=model)
    chars = _total_chars(script)
    print(f"[script] 初稿: {len(script.segments)}セグメント / {chars}文字")

    if chars < min_chars and session:
        script, _ = follow_up(
            VideoScript,
            session,
            (
                f"narration の合計が{chars}文字しかなく、目標の{min_chars}文字に届いていません。"
                "内容を薄めずに、具体例・数値・手順・よくある間違いを足してセグメントを増やし、"
                "同じ JSON 形式で全体を出し直してください。"
            ),
            model=model,
        )
        chars = _total_chars(script)
        print(f"[script] 加筆後: {len(script.segments)}セグメント / {chars}文字")

    if chars < min_chars:
        print(f"[script] 警告: 目標{min_chars}文字に届きませんでした（{chars}文字）")

    # **落ちた事実を渡して、同じセッションで直させる輪。**
    #
    # ショート: 2026-08-09、指示に「60文字以内」と書いても 86〜93文字で返ってきて、
    # 前倒し検査に3回続けて落ちた。**文章での指示は守られない。**
    # 短すぎる側には書き足させる仕組みがあるのに、長すぎる側には無かった（片方だけ）。
    #
    # 長尺: **2026-08-24 まで、この輪は `max_minutes <= 1.5` の中にありました** ——
    # つまりショート専用で、長尺には直す口が1つもありませんでした。実測は
    # ショート 10/10・長尺 0/3・0/8 で、落ちた 3/3 は全部
    # 「過去の図と棒が2本以上共通」。**書き直しで直る種類の指摘**を、
    # `claude -p` に約250秒使ったあと `pipeline.py` で捨てていました。
    # **輪はどちらにも要ります。** 違うのは「何を見るか」と「どう直せと言うか」だけ。
    # `is_short` は上（セグメント数を決めるところ）で1度だけ作っています。
    # **ここで作り直さないこと** —— あちらのコメントが「下の follow_up と
    # 同じ条件を使うこと。別々に持つと、片方だけ直したときに静かにずれます」。
    problems_of = short_script_problems if is_short else long_script_problems
    kind_label = "ショート" if is_short else "長尺"
    fix_guidance = SHORT_FIX_GUIDANCE if is_short else LONG_FIX_GUIDANCE
    if session:
        for attempt in range(3):
            problems = problems_of(script, topic.get('id', ''))
            if not problems:
                break
            print(f"[script] {kind_label}の条件を満たしていません（{attempt + 1}回目）:")
            for p in problems:
                print(f"  - {p}")
            script, _ = follow_up(
                VideoScript,
                session,
                (
                    "**この台本は投稿前の検査に落ちます。** 直してください:\n"
                    + "\n".join(f"- {p}" for p in problems)
                    + "\n\n"
                    + fix_guidance
                ),
                model=model,
            )
        remaining = problems_of(script, topic.get('id', ''))
        if remaining:
            print(f"[script] 警告: {len(remaining)}件がまだ残っています。"
                  "パイプラインが合成前に止めます")

    return script


