# **この判断は正しい。** 8/15 に同じ割り算をやり直しても同じ答えになります。
# 140文字 ÷ 8枚 = 17.5文字。文になりません。
#
# **だから、セグメント数では解けません。** 3体の独立評価が言っていたのは
# 「**絵**が2コマ続く」であって「文が長い」ではない。
# **絵と文を1対1で結んでいたことが、そもそもの制約でした。**
# 1つの文に絵を複数枚あてれば、文を短くせずに絵だけ動かせます
# （`src/pipeline.py` の「1枚ずつ出す」。字幕は文の側に付くので、ずれません）。
#
# ここに残すのは「絵1枚が止まってよい秒数」だけ。**文の長さではありません。**
