#: 1行目の入り方。**4通りとも「結論の数字を先に言い切る」を守ります**
#: （維持率の要件。`ROLE` の「冒頭の1セグメント目で結論を数字ごと言い切る」）。
OPENING_FORMS = ("結論", "差分", "境界", "反転")

#: 長尺の締め方。**「手順」は4通りのうちの1つ**であって、既定ではありません。
CLOSING_FORMS_LONG = ("手順", "置換", "分岐", "限界")

#: ショートの締め方。**4通りとも最終行に「登録」を残します**（下の理由）。
CLOSING_FORMS_SHORT = ("依頼先", "数字先", "条件先", "対比先")


def _pick(salt: str, topic_id: str, forms: tuple[str, ...]) -> str:
    """テーマIDのハッシュで1つ選ぶ。**同じIDなら何度でも同じ答え。**"""
    h = hashlib.sha1((salt + str(topic_id)).encode("utf-8")).digest()
    return forms[int.from_bytes(h[:4], "big") % len(forms)]


def opening_form(topic_id: str) -> str:
    """1行目の**入り方**を4通りから選ぶ。**テーマIDで決まります。**

    返すのは `OPENING_FORMS` のどれか。**どれを引いても、
    1セグメント目で結論の数字を言い切る**という要件は変わりません
    —— 変えるのは**入り口の角度**だけです。

        結論  その動画の答えの数字から始める（前置きなし）
        差分  2つの場合の**差**から始める（「AとBで年に◯円ちがいます」）
        境界  答えが変わる**境目の値**から始める（「◯万円が境目でした」）
        反転  直感と**逆になる場合**から始める（「増やしたほうが手取りは減ります」）

    **「計算しました」という書き出しは、もう既定ではありません。**
    `ROLE` にあった「『調べてみました』ではなく『計算しました』」は、
    *自分で計算した結果を出す*という意図の表明でしたが、**文句がそのまま
    84% の本の先頭4文字になっていました**（`python -m src.frames`）。
    意図（調べ物の要約にしない）は `ROLE` に残し、**文句だけを消しています。**
    """
    return _pick("open:", topic_id, OPENING_FORMS)


def closing_form(topic_id: str, portrait: bool) -> str:
    """最終行の**締め方**を4通りから選ぶ。**テーマIDと向きで決まります。**

    ## 長尺（`CLOSING_FORMS_LONG`）

        手順  明日やること（**4通りのうちの1つ**。既定ではない）
        置換  この計算の数字を、自分の数字に置き換える手順
        分岐  境目のどちら側かで、この先どう変わるか
        限界  この計算が成り立たなくなる条件（前提が崩れる場所）

    **「限界」を入れたのは、ポリシーの側の理由もあります** ——
    計算の効く範囲を自分で言うことは、「汎用テンプレート」の反対側であり、
    `channel.yaml` の `persona`（助言ではなく試算）とも同じ向きです。

    ## ショート（`CLOSING_FORMS_SHORT`）—— **4通りとも「登録」を残します**

        依頼先  依頼を先に置き、そのあとに問いを1つ
        数字先  その動画の答えの数字を1回だけ言い直してから依頼
        条件先  答えが変わる条件を1つ言ってから依頼
        対比先  境目の反対側がどうなるかを言ってから依頼

    **なぜ全部に「登録」を残すのか。** `src/endcard_verdict.is_request()` は
    **最終行に「登録」が入っているか**だけで処置群を作っていて、
    `config/hypotheses.yaml` の期限 2026-10-11
    「ショートの最後で登録を直接1回頼むと、登録率が上がる」がそこにぶら下がっています。
    向こうの docstring は、**この形の事故を名指しで警告しています**:

        **覆る条件**: 依頼の文言が「登録」を含まない形に変わったら、ここに足すこと。
        **変えた回が足さないと、処置群が黙って空になります。**

    **だから足しません。群を1本も減らさない側で解きます** ——
    変えるのは依頼の**位置と前置き**であって、依頼の有無ではありません
    （`tests/test_frame_forms.py` が、4通りとも「登録」を要求していることを見ています）。
    """
    forms = CLOSING_FORMS_SHORT if portrait else CLOSING_FORMS_LONG
    return _pick("close:", topic_id, forms)


