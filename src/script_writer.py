            problems.append(
                f"サムネの `{_name}` が全角 {len(_txt)}文字"
                f"（{OUTSIDE_THUMB_LINE_MAX}文字以内 ＝ 外の上位3本の最大）:「{_txt}」。"
                "**前提を落として縮めないこと** —— `src/thumbnail._create_outside` は"
                "この行を**1行で**刷る（折り返さない）ので、詰めるか `thumbnail_line1` へ移すこと。"
                "例:「75歳まで生きた場合・年180万円」17 →「年180万・75歳まで」11")
