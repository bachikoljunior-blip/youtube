"""**予約の待ち行列に、長尺が何本あるか。**

`eta.py` の `rpm` の天井は、**長尺の面（インプレッション・実測）**から出ています
（`天井 rpm ×14.21 …… 長尺の面 73.0回/日 × CTR100% ＝ 再生の 11.7% が上限`）。
そして同じ出力が、こう書いています ——
**「長尺を出せば面が増え、次の回の測り直しでこの天井は上がります。」**

つまり **`rpm` の腕の実体は、待ち行列に長尺が何本あるか**です。

**その計器がどこにもありませんでした**（2026-08-24 の実測）:

    予約 約300本のうち長尺 **6本（2%）**
    `status.py` の印字 ——「この数字に入っていない公開 **40本**／うち長尺 **0本**」
    `lever_hint` は 8/23 からずっと **`rpm`** を名指し

**名指しされている腕の実体が 0 のまま、40本進んでいた**わけです。
`status.py` の `schedule_gaps` は **ショートの空きしか見ません** ——
露出がショートにしか出ていなかった頃の正しい判断で、註にもそう書いてあります。
**`rpm` が律速になった時点で、その判断は片肺になりました。**
消さずに、もう片方をここに足します。

**`batch_build.py` の既定はショートです**（`--long` を渡した回だけ長尺）。
既定を変えていないのは、ショートの空きが最大の損失であることは変わらないから
—— 変えるべきは既定ではなく、**「長尺が0でも誰も鳴らさない」ほう**です。

**覆る条件**: `rpm` が `lever_hint` から外れたとき（＝律速が再生数以外に移ったとき）。
そのときこの警告は鳴りっぱなしの側に回るので、**閾値ではなく節ごと畳むこと。**
"""
from __future__ import annotations

# 長尺が待ち行列のこれを下回ったら、既定（ショート）のまま撃った疑いを出す。
# **実測の 2% から置いた見当**で、天井から解いた数ではありません。
LOW_SHARE = 0.10


def lines(sched_long: int, sched_short: int) -> list[str]:
    """待ち行列の長尺／ショートを、印字する行にする。**空の待ち行列では何も出さない。**"""
    total = sched_long + sched_short
    if total <= 0:
        return []
    share = sched_long / total
    out = [
        "=== 予約の待ち行列の中身（**`rpm` の腕はここです**）===",
        f"  長尺 **{sched_long}本** ／ ショート {sched_short}本"
        f"（長尺は待ち行列の **{share * 100:.1f}%**）",
        "  `eta.py` の `rpm` の天井は **長尺の面（インプレッション・実測）**から出ていて、"
        "同じ出力が「**長尺を出せば面が増え、次の回の測り直しでこの天井は上がります**」"
        "と書いています。**待ち行列の長尺の本数が、そのまま腕の実体です。**",
    ]
    if sched_long == 0:
        out.append(
            "  [!] **長尺が1本もありません。** `lever_hint` が `rpm` を名指ししている間、"
            "この状態で回すと**腕を引かずに進んだ回**になります。"
            "`batch_build.py --long` を撃つこと（**既定はショートです**）。")
    elif share < LOW_SHARE:
        out.append(
            "  [!] **`batch_build.py` の既定はショートです**（`--long` を渡した回だけ長尺）。"
            "名指しが `rpm` の回は、`--long` を付けたか確かめること。")
    return out
