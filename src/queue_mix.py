"""**予約の待ち行列に、長尺が何本あるか。**

`eta.py` の**実効RPMの天井**は、分子が **長尺の面（インプレッション・実測）**です
（`src/rpm_mix.surface_ceiling`）。そして同じ出力が、こう書いています ——
**「長尺を出せば面が増え、次の回の測り直しでこの天井は上がります。」**

つまり **面を増やす手は「長尺を出す」しかなく、その実体は
待ち行列に長尺が何本あるか**です。

**腕の名前では書きません**（2026-08-24 に、書きかけて撤回した）。
この節を最初 `rpm` の名前で書いた**同じ日のうちに**、別の回が
`surface_ceiling()` の分母を直して（38日の平均 → 最大の1日）
天井が **¥287 → ¥1,420**、名指しが **`rpm` → `per_video`** に動きました。
**1時間で腐る書き方でした。** 面はどちらの腕の下でも分子のままなので、
**面の側の言葉で書いてあります。**

**その計器がどこにもありませんでした**（2026-08-24 の実測）:

    予約 約300本のうち長尺 **6本（2%）**
    `status.py` の印字 ——「この数字に入っていない公開 **40本**／うち長尺 **0本**」
    `lever_hint` は 8/23 からずっと **`rpm`** を名指し

**名指しされている腕の実体が 0 のまま、40本進んでいた**わけです。
`status.py` の `schedule_gaps` は **ショートの空きしか見ません** ——
露出がショートにしか出ていなかった頃の正しい判断で、註にもそう書いてあります。
**`rpm` が律速になった時点で、その判断は片肺になりました。**
消さずに、もう片方をここに足します。

**`batch_build.py` の既定はショートです**（`--long` を渡した回だけ長尺）。
既定を変えていないのは、ショートの空きが最大の損失であることは変わらないから
—— 変えるべきは既定ではなく、**「長尺が0でも誰も鳴らさない」ほう**です。

**覆る条件**: **長尺の面が、実効RPMの天井の分子でなくなったとき**
（`src/rpm_mix.py` を作り替えたとき、または長尺をやめると決めたとき）。
そのときこの警告は鳴りっぱなしの側に回るので、**閾値ではなく節ごと畳むこと。**
**腕の名前が変わっただけでは畳まないこと** —— 上に書いたとおり、
それは同じ日のうちに一度起きています。
"""
from __future__ import annotations

# 長尺が待ち行列のこれを下回ったら、既定（ショート）のまま撃った疑いを出す。
# **実測の 2% から置いた見当**で、天井から解いた数ではありません。
LOW_SHARE = 0.10


def lines(sched_long: int, sched_short: int) -> list[str]:
    """待ち行列の長尺／ショートを、印字する行にする。**空の待ち行列では何も出さない。**"""
    total = sched_long + sched_short
    if total <= 0:
        return []
    share = sched_long / total
    out = [
        "=== 予約の待ち行列の中身（**長尺の面は、ここからしか増えません**）===",
        f"  長尺 **{sched_long}本** ／ ショート {sched_short}本"
        f"（長尺は待ち行列の **{share * 100:.1f}%**）",
        "  `eta.py` の**実効RPMの天井**は、分子が **長尺の面（インプレッション・実測）**で、"
        "同じ出力が「**長尺を出せば面が増え、次の回の測り直しでこの天井は上がります**」"
        "と書いています。**待ち行列の長尺の本数が、そのまま面の供給です。**",
    ]
    if sched_long == 0:
        out.append(
            "  [!] **長尺が1本もありません。** この状態で回すと、"
            "**長尺の面は今日の値から1回も動きません**（実効RPMの天井もそのまま）。"
            "`batch_build.py --long` を撃つこと（**既定はショートです**）。")
    elif share < LOW_SHARE:
        out.append(
            "  [!] **`batch_build.py` の既定はショートです**（`--long` を渡した回だけ長尺）。"
            "面が律速に出てくる回は、`--long` を付けたか確かめること。")
    return out
