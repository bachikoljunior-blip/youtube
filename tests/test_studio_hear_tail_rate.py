"""`studio/hear.tail_rate` —— 末尾が音に在るかを**秒数の側**から見る（2026-09-09 06:5x・optimizer・Opus）。

**なぜ足したか（`tail_probe` が、初めて出会った新しいコマで外した）**:

05:5x が足した `tail_probe` は「末尾 5秒 だけを同じ模型に渡す」手で、
09/10 の本の コマ8 では正しく働きました（末尾 5秒 に「おおければけいさんがかわります」が在り 0差）。
**06:5x に本文を直して焼き直したら、同じ本の コマ7 で逆を答えました**:

    コマ7 全部 (small→medium+prompt)  …ごじゅまんへんがいぞくのぶんとして   ← 「たされます」が無い
    コマ7 **末尾 5秒** medium         ごじゅまんえんまでたりないごじゅまんえんが
                                      ← **窓の中の末尾も落ちている**（いぞくのぶんとしてたされます が無い）
    → `tail_probe` は `ok=False` ＝ 「TTS 側を疑う」と印字した

**whisper は「渡された音の終わり」を切ることがあるので、末尾だけを渡しても同じ所で切れます。**
＝ `tail_probe` は**自分が排除したい失敗を、自分でも起こします**。

**秒数は別の物を見ます**（聞き取りではなく音の長さ）。この回に撃った数:

    コマ  字  秒     字/秒     hear
     1    42  7.6    5.53      OK
     2    42  8.8    4.77      OK
     3    64 12.2    5.25      !!  ← 末尾 17字 が無いなら **3.85**
     7    48  9.2    5.22      !!  ← 「たされます」5字 が無いなら **4.67**
     8    50  9.9    5.05      OK  ← 05:5x に切れていたコマ（59字→50字 に縮めたら通った）
    帯（一致したコマだけ） **4.77〜5.53**

＝ コマ3・コマ7 とも、**末尾を落とすと帯の外**（3.85／4.67 < 4.77）。
**音は在り、切ったのは whisper です** —— `tail_probe` の答えと逆。

**分けられるのは「音が無い」か「音は在る」かの1つだけ**で、
**誤読 と 切り落とし は分けません**（誤読でも長さは残る）。そちらは `tail_probe` が見ます。
"""
from studio.hear import tail_rate

#: この回に実際に測った帯（09/10 の本・一致した 8コマ から）。**写しではなく凍らせた数**。
BAND = (4.77, 5.53)


def test_コマ7_末尾を落とすと帯の外():
    """`tail_probe` が「TTS 側を疑う」と答えた当のコマ。秒数の側は「音には在る」。"""
    r = tail_rate(exp_len=48, gap_len=5, dur=9.2, band=BAND)
    assert r["rate"] == 5.22
    assert r["without"] == 4.67
    assert r["present"] is True


def test_コマ3_末尾17字を落とすと大きく帯の外():
    r = tail_rate(exp_len=64, gap_len=17, dur=12.2, band=BAND)
    assert r["without"] == 3.85
    assert r["present"] is True


def test_本当に読んでいないコマは帯の中に残る():
    """**陰性対照**。末尾が本当に音に無ければ、残りの字が残りの秒数を素直に説明する。

    作り物ではなく、同じ本の コマ8 を使った当てはめ —— 50字/9.9秒 = 5.05 は帯の中で、
    仮に末尾 1字 だけが無くても 4.95 で帯の中に残る ＝ この手は「短い欠け」を拾いません。
    拾えるのは、**落とすと速さが説明できなくなるほど長い末尾**だけです。
    """
    r = tail_rate(exp_len=50, gap_len=1, dur=9.9, band=BAND)
    assert r["present"] is False


def test_帯の下端ちょうどは拾わない():
    # 境目で鳴らせると、速く読んだだけのコマを「切られた」と読む
    r = tail_rate(exp_len=48, gap_len=0, dur=48 / 4.77, band=BAND)
    assert r["present"] is False


def test_秒数が0でも落ちない():
    r = tail_rate(exp_len=48, gap_len=5, dur=0.0, band=BAND)
    assert r["rate"] == 0.0
