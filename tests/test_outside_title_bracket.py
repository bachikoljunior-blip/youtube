def _bracket_problems(title: str) -> list[str]:
    return [p for p in sw.outside_title_problems({"title": title})
            if "【 】が相手でも場面でもない" in p]


def test_百万回を超えた帯の題は_相手か場面だけが通る():
    """**通す側の証拠。** 語の表は、この 9本 が通る最小の形で置いてあります。"""
    上 = [(t, v, k) for t, v, k in 帯の上位 if v >= 1_000_000]
    通った = {k for t, v, k in 上 if not _bracket_problems(t)}
    落ちた = {k for t, v, k in 上 if _bracket_problems(t)}
    assert 通った == {"相手", "場面"}, f"通った種別が想定と違います: {通った}"
    assert 落ちた == {"形式"}, (
        "100万回を超えた帯で落ちてよいのは【漫画】（形式）だけです。"
        f"落ちた種別: {落ちた}")


