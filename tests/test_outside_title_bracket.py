#: **写す先の帯が、規則の2つの節をどれだけやっているか**（2026-09-04 20:4x に数えた）。
#: `data/niche_ceiling.jsonl` 2026-09-03 の長尺上位のうち 100万回超 **15本**::
#:
#:     題に金額（`_OUTSIDE_MONEY_RE`）                   **3/15 ＝ 20%**
