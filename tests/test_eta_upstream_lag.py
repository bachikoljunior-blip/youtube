"""**齢の隣に、上流が作る間隔を置く**（2026-09-01・定期の回に足した）。

## この回が実際に踏んだこと

`eta.instrument_ages()` は 08-28 から齢を正しく出し、その隣で

    取り直す手は `scripts/reach.py` … **日枠が尽きていても、
    前の3つは別の枠なので通ります**

と言っています。**枠の話は正しい。** それでも、この回は齢
「面（インプレッション） **67時間**」を読んで `scripts/reach.py` を撃ち、

    [reach] channel_reach_basic_a1: 報告 49本 / 未読 0本 を落とします
    [reach] **新しい報告はありません**（積み済み 49本）

でした。**Reporting API はその場で数字を返しません** —— ジョブを作ると
YouTube が**自分の都合で1日1回 CSV を置いていく**ので、
**こちらが撃つ回数を増やしても、控えは1行も増えません。**

実測（`jobs.reports.list` の `createTime` − `endTime`・ジョブ作成後の 15日ぶん。
遡って埋まった分は除く）: 最小 **20.8時間** ／ 中央値 **34.0時間** ／
最大 **113.6時間**。**＝ この控えは 21時間 より新しくなりません。**

**齢だけでは、次の2つが区別できません**:

    67時間   上流がまだ作っていない（**帯の中**。撃っても 0行）
    168時間  止まっている（**帯の外**。08/24 の ¥184 → ¥287 はこちら）

**どちらも「古い」としか読めない**ので、次に来た側は毎回 同じ 30分 を使って
「撃ってみて 0本 だった」を確かめ直します。**だから帯を隣に置きます。**

## この検査が留めている向き（`tests/test_eta_instrument_ages.py` の向き1 を壊さない）

**しきい値ではありません。何も黙りません。** 齢は毎回そろって出ます。
足したのは**事実がもう1つ**だけで、機械は「古い／新しい」を判定しません ——
判定を持たせると、こんどは「何時間で鳴らすか」を次の回が世話します。
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import eta  # noqa: E402


def test_面の齢の隣に上流の作る間隔が出る():
    line = eta.instrument_ages()[0]
    head, sep, _ = line.partition(" ／ 混ざり方")
    assert sep, "**並びが変わっています。**（面 → 混ざり方 の順が前提）"
    assert "上流の作る間隔" in head, (
        "**面（Reporting API）の齢の隣に、上流の作る間隔が出ていません** ——"
        " これが無いと、次の回は『67時間 は止まりか、待ちか』を"
        " 撃って確かめるところからやり直します（この回は 30分 使いました）"
    )
    assert "これより新しくはなりません" in head


def test_帯の数は実測から出す():
    """**中央値と最大の両方**を出すこと。片方だけだと帯になりません。"""
    med, mx, n, why = eta._UPSTREAM_LAG["data/reach.jsonl"]
    assert 0 < med < mx, "**中央値 < 最大** でなければ帯として読めません"
    assert n >= 10, "**n が小さすぎます。**（遡って埋まった分を混ぜていないか）"
    assert why, "**何の待ちかを書くこと**（枠の待ちと区別が付きません）"


def test_しきい値にしていない():
    """**判定を機械に持たせないこと。** 齢は帯の中でも外でも、同じ形で出ます。"""
    line = eta.instrument_ages()[0]
    for word in ("古すぎ", "止まっています", "[!]"):
        assert word not in line, (
            f"**`{word}` は判定です。** この行は事実だけを並べます"
            "（`tests/test_eta_instrument_ages.py` の向き1）"
        )
    assert "面（インプレッション）" in line and "本べつの形" in line, \
        "**しきい値で控えを間引いていないか**（黙ると 08/24 に戻ります）"


def test_撃っても増えないことが行に書いてある():
    """**「別の枠なので通ります」だけを残さないこと。**

    通ることと、増えることは別です。**この回はそこで空振りしました。**
    """
    line = eta.instrument_ages()[0]
    assert "別の枠なので通ります" in line, "**枠の事実を消さないこと**（08/28 の実測）"
    assert "上流がまだ作っていなければ" in line, (
        "**『通る』の隣に『それでも増えないことがある』が無いと、"
        "次の回は同じ空振りをします**"
    )
