"""**09/03 に出す本の読みを、耳で聞ける形にする前に見つけた2件。**

オーナー原文（`CLAUDE.md` 固定その3）:

> **「ナレーションの漢字の読み方全部正しくして」**

## 実物（2026-09-02・`MqQKSnbM0OI`＝09/03 に出す本）

本番エンジン（open-jtalk）に読み上げ全文を通したら、こう出ました:

    低所得I     → 低[テー] 所得[ショトク] Ｉ[アイ]
    低所得II    → …            ＩＩ[アイアイ]
    現役並みIII → 現役[ゲンエキ] 並み[ナミ] ＩＩＩ[アイアイアイ]
    主役はこの行です。→ … この[コノ] 行[クダリ] です[デス]

**段の名前がこの本の背骨です**（18コマ中9回）。「アイアイアイ」で鳴ります。
「行」は表の行（ぎょう）で、クダリ（＝文章のひとくだり）ではありません。

## なぜ `FIXES` に手で足したか

`src/yomi.py` の註は「**手で足すのは、上の輪（耳の台帳）が届かないと
実測で分かった形だけ**」と言っています。この2件はどちらもそれです:

- ローマ数字 …… 耳の台帳は**表層1語に正しい読みを1つ**決めます。
  `Ｉ` 単独の正しい読みは存在しません（英字の I のこともある）。
  正しさは**直前の段の名前**で決まる ＝ 語ではなく**形**です
- 「行」 …… 同じ表層が ギョウ／クダリ／ユキ に割れます
  （`yomi_gate.inspect()` が R1 として毎回 名指ししていました。
   **名指しはされていたが、直す形が無かった**）

## 実測（控え 695本・6,224行。**推測を混ぜていません**）

    日本語の直後のローマ数字   **9回 / 1本**（全部 段の名前）  誤爆 0件
    「行」                    総 **740回**
      この規則が拾う           **423回**
      拾わなかった「の行」      **2回** ＝ どちらも「分の行き先」（ユキサキ・触らない側）

## 覆る条件

- 日本語の直後に**英字の I** が出る本が来たら、直前の語で絞ること
  （いまは corpus に1件も無いので、絞ると次の段の名前を取りこぼします）
- 「〜の行く先」で表の行を指す文が出たら、除外の仮名を見直すこと
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.yomi import to_speech  # noqa: E402


# --------------------------------------------------------------- 段のローマ数字
def test_段のローマ数字を日本語の数にする():
    assert to_speech("低所得Iの年間限度額は19万円です。").startswith("低所得いちの")
    assert "低所得に" in to_speech("低所得IIは95.2パーセントです。")
    assert "現役並みさん" in to_speech("現役並みIIIが14万100円です。")


def test_IIIを先に当てること():
    """**順番が本体です。** `I` を先に当てると III が「いちいちいち」になります。"""
    got = to_speech("現役並みIIIと現役並みIIと低所得I。")
    assert "現役並みさん" in got and "現役並みに" in got and "低所得いち" in got, got
    assert "いちいち" not in got, got


def test_英字の語は触らない():
    """後ろに英字が続く形（型番・略語）は段の名前ではありません。"""
    for s in ["IT", "ISO", "IFRS", "III", "Income"]:
        assert to_speech(f"制度のIN{s}") == f"制度のIN{s}", s


def test_行頭のローマ数字は触らない():
    """**直前が日本語の字のときだけ**です（`(?<=[漢字かなカナ])`）。"""
    assert to_speech("III期の話です。") == "III期の話です。"


# --------------------------------------------------------------------- 表の行
def test_表の行はぎょうにする():
    for s in ["主役はこの行です。",
              "いちばん上の行から見ます。",
              "自分がどの行に近いかを見てください。",
              "最後の行まで画面に出しています。",
              "1万円の行では、負担が2倍になります。"]:
        assert "ぎょう" in to_speech(s), s


def test_動詞の行くと行き先は触らない():
    """**拾わなかった2件が、これです**（控え 695本 の実測）。"""
    for s in ["上限に当たった分の行き先はありません。",
              "増えた分の行き先を見ます。"]:
        assert to_speech(s) == s, s


def test_のが前に無い行は触らない():
    """「右へ行く」「施行規則」「銀行」「一行」—— 残る 317回 はここです。"""
    for s in ["右へ行くほど大きくなります。",
              "上に行くほど負担が増えます。",
              "第4項と施行規則で決まります。",
              "銀行の口座に振り込まれます。",
              "この一行から読み取れます。"]:
        assert to_speech(s) == s, s


def test_行から_は表の行として拾う():
    """**「か」を除外に入れないこと** —— 実測 12回 とも表の行です
    （「下の行から上の行へ」「どの行かが決まります」）。"""
    got = to_speech("下の行から上の行へ大きくなります。")
    assert got.count("ぎょう") == 2, got
