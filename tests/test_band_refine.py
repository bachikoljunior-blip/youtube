"""「帯」の両端が、掃引の格子の点のまま出ていないか。

`_classify` の帯が返す `帯の入口` は **帯の中に入った最初の格子点**、
`帯の出口` は **まだ帯の中にある最後の格子点**です。本当の境目は
`(入口の手前, 入口]` と `[出口, 出口の先)` のどこかにあり、
**格子が粗いほど帯は内側へ縮んで見えます。**

実物（2026-08-26 に踏んだ）: `keihi` の掃引が「**帯 age 46〜62**」と出しました。
**介護保険は実際には 40〜64歳**です。46〜62 は目盛りが粗いだけで、
そのまま節にすると誤情報になります。同じ形は `崖`（`_refine_cliff`）と
`頭打ち`（`_refine_plateau`）で 2026-08-27 に直っており、
**`帯` にだけ刻み直しがありませんでした**（3周 続けて申し送りに残っていた）。

**故障注入を両向きに掛けます**（`tests/test_cliff_refine.py` と同じ理由）——
広げるべき帯を広げることと、**広げようのない帯で黙らないこと**は別の性質で、
片方だけでは「全部を広げる検査」と区別がつきません。
"""
import pytest

from src import section_sweep as ss


def _refine(fn, detail, key="返り値", default=1.0):
    """`_refine_band` を、1引数の関数に対して呼ぶ。"""
    return ss._refine_band(fn, {}, "x", default, key, detail)


def _band(lo, hi, inner=1.0, outer=0.0):
    """`lo <= x <= hi` のあいだだけ値が違う関数。"""
    def fn(x):
        return {"返り値": inner if lo <= x <= hi else outer}
    return fn


# ---- 鳴るべき側（粗い格子が帯を内側へ縮めている） --------------------------

def test_粗い格子で縮んだ帯が広がる():
    """本当の帯は 40〜64。格子が 46 と 62 しか踏んでいない、という形。"""
    d = _refine(_band(40, 64), {"帯の入口": 46, "帯の出口": 62,
                                "帯の中": 1.0, "帯の外": 0.0,
                                "帯の入口の手前": 38, "帯の出口の先": 70})
    assert d["細かくした帯の入口"] == 40.0, d
    assert d["細かくした帯の出口"] == 64.0, d


def test_広げた端の外側は帯の外():
    """`〜の外` は、**帯の外に居る最初の点**であること（挟んで示す）。"""
    d = _refine(_band(40, 64), {"帯の入口": 46, "帯の出口": 62,
                                "帯の中": 1.0, "帯の外": 0.0,
                                "帯の入口の手前": 38, "帯の出口の先": 70})
    assert d["細かくした帯の入口の外"] == 39.0, d
    assert d["細かくした帯の出口の外"] == 65.0, d


def test_整数の軸に小数を渡さない():
    """**行のあいだに点を置かないこと**（`_fine_xs`）。

    `keihi.care_age_gap` は既定値が `39.0`（float）で返るので、等分すると
    64.5歳 を渡します。介護は 40〜64歳 なので 64.5 は「乗らない」側に落ち、
    刻み直した出口が **63.625** と出ました —— 粗い格子を直しにいって、
    **行のあいだの数を作っています。**
    """
    seen: list[float] = []

    def fn(x):
        seen.append(x)
        return {"返り値": 1.0 if 40 <= x <= 64 else 0.0}

    _refine(fn, {"帯の入口": 40, "帯の出口": 61, "帯の中": 1.0, "帯の外": 0.0,
                 "帯の入口の手前": 33, "帯の出口の先": 68})
    assert seen, "1点も引いていません"
    assert all(float(x).is_integer() for x in seen), seen


def test_端が整数でなければ等分のまま():
    """率のような連続量の軸まで整数に丸めないこと。"""
    d = _refine(_band(0.20, 0.60), {"帯の入口": 0.25, "帯の出口": 0.55,
                                    "帯の中": 1.0, "帯の外": 0.0,
                                    "帯の入口の手前": 0.10, "帯の出口の先": 0.70},
                default=0.5)
    assert 0.10 < d["細かくした帯の入口"] <= 0.25, d
    assert 0.55 <= d["細かくした帯の出口"] < 0.70, d
    assert not float(d["細かくした帯の入口"]).is_integer(), d


# ---- 鳴るべきでない側（広げようが無い／広げてはいけない） ------------------

def test_格子がぴったりなら動かさない():
    """帯の端が本当の境目なら、刻み直しても同じ値を返すこと。"""
    d = _refine(_band(40, 64), {"帯の入口": 40, "帯の出口": 64,
                                "帯の中": 1.0, "帯の外": 0.0,
                                "帯の入口の手前": 33, "帯の出口の先": 70})
    assert d["細かくした帯の入口"] == 40.0, d
    assert d["細かくした帯の出口"] == 64.0, d


def test_掃引の端では黙らずに理由を残す():
    """外側の点が無いときは、**刻めなかったことを言う**（黙って通さない）。"""
    d = _refine(_band(40, 64), {"帯の入口": 40, "帯の出口": 64,
                                "帯の中": 1.0, "帯の外": 0.0})
    assert d["帯の入口を刻めなかった"], d
    assert d["帯の出口を刻めなかった"], d
    assert "細かくした帯の入口" not in d, d


def test_関数が落ちたら理由を残す():
    def boom(x):
        raise ValueError("こわれた")

    d = _refine(boom, {"帯の入口": 46, "帯の出口": 62, "帯の中": 1.0,
                       "帯の外": 0.0, "帯の入口の手前": 38, "帯の出口の先": 70})
    assert d["帯の入口を刻めなかった"] == "ValueError", d


def test_同じ欄が消えたら理由を残す():
    def gone(x):
        return {"別の欄": 1.0}

    d = _refine(gone, {"帯の入口": 46, "帯の出口": 62, "帯の中": 1.0,
                       "帯の外": 0.0, "帯の入口の手前": 38, "帯の出口の先": 70})
    assert d["帯の入口を刻めなかった"] == "同じ欄が出ませんでした", d


