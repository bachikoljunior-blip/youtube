# ---- 実物（この直しの出どころ） ---------------------------------------------

def test_実物の_keihi_の帯は_40から64歳と出る():
    """`keihi.burden（age）` の帯。**粗い格子では 46〜62 と出ていた。**

    介護保険第2号被保険者は **40〜64歳**（`src/calc/keihi.py`）。
    刻み直しが 40 と 64 を名指しし、その外側 39 と 65 で挟めること。
    """
    from src.calc import keihi

    params = ss._sweepable_params(keihi.burden, skip={})
    base = {pn: d for pn, d in params}
    detail = {"帯の入口": 46, "帯の出口": 62,
              "帯の中": keihi.burden(**{**base, "age": 50})["合計"],
              "帯の外": keihi.burden(**{**base, "age": 30})["合計"],
              "帯の入口の手前": 38, "帯の出口の先": 70}
    d = ss._refine_band(keihi.burden, base, "age", base["age"], "合計", detail)
    assert (d["細かくした帯の入口"], d["細かくした帯の出口"]) == (40.0, 64.0), d
    assert (d["細かくした帯の入口の外"], d["細かくした帯の出口の外"]) == (39.0, 65.0), d
