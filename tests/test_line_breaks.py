def _problems(text: str, limit: int, forbidden) -> list[str]:
    lines = _chunk(text, limit)
    out = []
    # 1. 枠に収まること。**溢れたら画面側が勝手に折る**ので、ここが一番大事。
    for line in lines:
        if len(line) > limit:
            out.append(f"{limit}文字を超えた: {line!r}（{len(line)}文字）")
    # 2. 短すぎる行を作らないこと（一瞬だけ映って読めない）
    for line in lines:
        if line.strip() and len(line.strip()) < MIN_LINE_CHARS:
            out.append(f"短すぎる行: {line!r}")
    # 3. 過去に壊れた位置で割っていないこと
    for i in range(len(lines) - 1):
        for tail, head in forbidden:
            if lines[i].endswith(tail) and lines[i + 1].startswith(head):
                out.append(f"禁じた位置で割れた: {lines[i]!r} / {lines[i + 1]!r}")
    # 4. 元の文字が落ちていないこと（改行を入れるだけで、削ってはいけない）
    if "".join(lines).replace(" ", "") != text.replace(" ", ""):
        out.append(f"文字が変わった: {lines!r}")
    return out


def test_line_breaks():
    failures = []
    for text, limit, forbidden in CASES:
        for p in _problems(text, limit, forbidden):
            failures.append(f"{text!r} (limit={limit}): {p}")
    assert not failures, "\n".join(failures)


