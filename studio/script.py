def _bigrams(s: str) -> set[str]:
    """**2字の並び**の集合（句読点と空白は落とす）。1字 だと別の文どうしでも重なる（上の註）。"""
    s = "".join(c for c in s if c not in SUB_IGNORE_CHARS)
    return {s[i:i + 2] for i in range(len(s) - 1)} or ({s} if s else set())


