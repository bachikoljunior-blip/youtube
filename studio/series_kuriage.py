def man(v: int) -> str:
    """114000 → 11万4000円・6840000 → 684万円・7200 → 7200円。"""
    if v == 0:
        return "0円"
    m, r = divmod(v, 10_000)
    return (f"{m}万" if m else "") + (f"{r}" if r else "") + "円"


def figures(age: int) -> dict:
    """その歳から受け取るときの数（**全部 整数**）。"""
    m = (65 - age) * 12                       # 早めた月数
    cut = P * RATE_PERMIL * m // 1000         # 毎月 減る分
    amt = P - cut                             # 毎月 受け取る分
    head = amt * m                            # 65歳までに先に受け取る合計
    even = 250 - m                            # 追いつかれるまでの月数（＝ head // cut）
    assert head // cut == even and head % cut == 0, (age, head, cut, even)
    y, mo = divmod(even, 12)
    return {"age": age, "months": m, "cut": cut, "amt": amt, "head": head,
            "even": even, "even_y": y, "even_mo": mo, "even_age": 65 + y,
            "pct": f"{RATE_PERMIL * m / 10:g}"}


