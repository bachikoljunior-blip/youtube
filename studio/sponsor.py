# **帯の出どころ**（**未測** ＝ `trend.SPONSOR_YEN_PER_VIEW_BAND` と同じ扱い）:
#   うちは **1通 も送っていません**（`short()` の行）＝ 返事率も成約率も 0件 の上に在ります。
#   帯は「知らないチャンネルから法人の問い合わせフォームへ 1通」という形の、
#   **一般的な冷たい打診の幅**を置いたものです。**測っていないので、数として扱わないこと** ——
#   **この帯が決めているのは『40社 だ』ではなく『4社 では足りない』のほうです**
#   （**帯の 3点 が 3点 とも 4社 より大きい** ＝ どこを取っても同じ答えが出る所だけを読む）。
#
# **覆る条件**:
#  (1) **1通 でも返事が来たら、帯を捨ててその数で引き直すこと。** 分母は「送った通数」で、
#      `docs/FOR_OWNER.md` の出した窓を数えれば出ます（`SENT_LOG` は持ちません ＝ 写しを作らない）。
#  (2) **C=80% は この file の選びです**（オーナーの言葉ではない）。期限が縮んだら C を上げること
#      —— C=95% なら N は **中段で 74社**（ln0.05/ln0.96）。**C を下げて「足りている」と
#      読まないこと** ＝ それは数えるのをやめるのと同じです。
#  (3) **相手の質は N の中で一様ではありません。** `TARGETS` は扉が開いている順に並ぶので、
#      **上のほうの p は帯の高い側・下のほうは低い側**です ＝ 40社 目 の 1通 は 1社 目 の 1通 より弱い。
#      **だから N を満たすことは、p を上げる手（文面・媒体資料）の代わりにはなりません。**
#  (4) **代理店 1社 は広告主 1社 ではありません。** ドリーム・クルー／オースタンスのような
#      「媒体を仕入れる側」は、1通 の後ろに複数の広告主が居ます ＝ **p が構造的に高い側**。
#      **数えるときは 1社 として数えていますが、それは過小です**（この回は直していません）。
#  (5) **6本/日 が戻らなければ、立った yes の額は ¥224,070 ではありません**
#      （いまの 1,600回/日 なら ¥71,980/月 ＝ 0.36本ぶん）＝ **N を満たしても目標に届きません。**
#      **N（相手の数）と 6本/日（枠）は、どちらか一方では足りない 2つ の掛け算です。**
# ---------------------------------------------------------------------------

#: **1通 → 有料の契約** が立つ確率の帯（低/中/高・**未測**）。上の註のとおり、
#: この帯が決めているのは「40社 だ」ではなく「**4社 では足りない**」のほうです。
SPONSOR_WIN_BAND = (0.01, 0.04, 0.10)

#: 「1社 の yes を立てる」と言ってよい信頼（上の 覆る条件 (2)）。
NEED_CONFIDENCE = 0.80

#: 1つ の窓に入る宛先の数（実寸・09/21 の窓 ＝ 695字／4社・`scripts/for_owner.BODY_MAX` は 700）。
TARGETS_PER_WINDOW = 4


def need_targets(confidence: float = NEED_CONFIDENCE) -> dict:
    """**信頼 `confidence` で 1社 の yes を立てるのに要る 相手の数**（**API 0単位**）。

    返り: `{"band", "confidence", "need": {level: N}, "have", "listed",
             "p_at_least_one": {level: 確率}, "windows": {level: 窓の数},
             "per_window"}`

    **決めと覆る条件は上の註 ＝ ここへ写さないこと。**
    """
    import math

    c = float(confidence)
    have = len(checked_targets())
    need, p1, wins = {}, {}, {}
    for lv, p in zip(("低", "中", "高"), SPONSOR_WIN_BAND):
        n = math.ceil(math.log(1.0 - c) / math.log(1.0 - p))
        need[lv] = n
        # いまの一覧で 1社 でも立つ確率
        p1[lv] = 1.0 - (1.0 - p) ** have
        wins[lv] = math.ceil(n / TARGETS_PER_WINDOW)
    return {"band": SPONSOR_WIN_BAND, "confidence": c, "need": need,
            "have": have, "listed": len(TARGETS), "p_at_least_one": p1,
            "windows": wins, "per_window": TARGETS_PER_WINDOW}


def need_short(confidence: float = NEED_CONFIDENCE) -> str:
    """`status`／`trend` に足す 1行。**決めは上の註 ＝ ここへ書かないこと。**"""
    d = need_targets(confidence)
    n = d["need"]
    return ("。**その 1社 が立つ見込み**: 1通→有料 の確率 **未測**・帯 "
            f"{d['band'][0]:.0%}／**{d['band'][1]:.0%}**／{d['band'][2]:.0%} ＝ "
            f"信頼 {d['confidence']:.0%} で 1社 を立てるのに要る相手は "
            f"**{n['低']}社／{n['中']}社／{n['高']}社**。"
            f"**いまの口を読んだ相手は {d['have']}社** ＝ 1社 でも立つ確率は "
            f"**{d['p_at_least_one']['低']:.0%}／{d['p_at_least_one']['中']:.0%}／"
            f"{d['p_at_least_one']['高']:.0%}** —— **帯のどこを取っても足りません。** "
            f"**送る側は期限に入ります**（{d['per_window']}社/窓 × 1窓/日 ＝ 中段 {d['windows']['中']}日"
            "・残り 84日）＝ **律速は「相手を探して口を開く周」で、そこはオーナーの手も API も 0 です**"
            "（derivation と覆る条件は `studio/sponsor.need_targets` の註）")


# ---------------------------------------------------------------------------
# **N を 1通ずつ 足す以外の道が 1つ あります —— 探される側に立つこと**
# （2026-09-20 07:xx・optimizer・Opus 5・ultracode・**この回は手を置いていません**）
# ---------------------------------------------------------------------------
#
# 上の `need_targets` は、**こちらから 1通ずつ送る形**だけを数えています
# （N社 ÷ 4社/窓 ÷ 1窓/日）。**その形の外に、日本の広告の商習慣で立っている口が 1つ** あります:
#
#   **メディアレーダー**（`media-radar.jp`）—— **媒体資料のダウンロードサイト**。
#   広告主と代理店が「シニア向け」「YouTube広告」などで**媒体を探して**資料を落とす所で、
#   **媒体社の側は 無料プランで資料を掲載でき、案件マッチング機能が在る**（下の「出どころ」）。
#   ＝ **こちらが 40社 を探す代わりに、探している側がこちらを見つける形**です。
#   **1回の登録が、以後ずっと分母になります**（1通 1窓 の掛け算に乗りません）。
#
# **なぜこの回は手を置かなかったか（2つ・どちらも正直に）**:
#
#  (1) **こちらの口からは読めていません。** `media-radar.jp` はこの環境から **403**
#      （トップ・`entry_baitai.php`・個別ページの 3つ とも）。
#      **読めていない口を「読んだ」に混ぜない**のが この file の (3) の規則です
#      ＝ だから `TARGETS` にも、オーナーの窓にも入れていません。
#      **出どころは二次情報 2つ**: 検索の索引が `media-radar.jp/entry_baitai.php` を
#      「**資料掲載企業・無料プラン登録｜メディアレーダー**」の題で持っていること、
#      および `shopowner-support.net` の解説（「**提携企業登録および資料・動画の掲載は無料**」）。
#      **どちらも一次ではありません。**
#  (2) **掲載する「媒体資料」の実物が在りません。** `sheet()` が出すのは**字**で、
#      あちらに置くのは **1枚の資料（PDF）**です。**持っていない物を約束しない**
#      （`letter` の註と同じ向き）＝ **資料を焼くほうが先**です。
#
# **次に立った回への 1手**（順番に意味があります）:
#   a. `sheet()` の中身を **1枚の資料**に焼く口を作る（`studio/slides.py`／`render.py` が在る・
#      **API 0単位**・オーナーの手 0）。**これが無いと、登録しても置く物がありません。**
#   b. 別の経路から `media-radar.jp` が読めたら、`TARGETS` ではなく**登録の窓**として
#      `docs/FOR_OWNER.md` に 1つ 足す（**送る窓とは別の形**: 貼るのではなく登録する）。
#   c. 読めないままなら、**オーナーの窓に「開いてみて、無料でなければ閉じてください」で出す**
#      —— ただし **a が終わってから**。順番を逆にすると、登録の途中で止まります。
#
# **この道が N を置き換えるとは言っていません。** 掲載しても誰も落とさなければ 0 です
# （`ungated_yen` 覆る条件 (2) と同じ向き）。**言えるのは「1通ずつ以外の形が在る」までです。**
# ---------------------------------------------------------------------------


def kit(rows: list[dict], scripts_dir=None) -> dict:
    """媒体資料の数（**API 0単位**・台帳だけ）。**定数は 1つ も持ちません**（上の註）。

    返り: `{"views_month","views_month_cap","per_day_cap","band","goal",
             "price": {level: {"now","cap"}}, "times_cap", "p65","p55","top",
             "audience_measured","audience_window","subs","views_total","n"}`
    """
    from . import trend as _trend

    d = _trend.ungated_yen(rows, scripts_dir)
    g = _trend.channel_growth(rows)
    a = _trend.audience_split(rows) or {}

    vm = float(d["views_month"] or 0.0)
    vc = float((d["cap"] or {}).get("views_month") or vm)
    band = tuple(d["band"])

    price = {}
    for lv, b in zip(_trend.YEN_LEVELS, band):
        price[lv] = {"now": vm * b, "cap": vc * b}

    return {
        "views_month": vm,
        "views_month_cap": vc,
        "per_day_cap": _trend.sponsor_daily_cap_videos(),
        "band": band,
        "goal": float(d["goal"]),
        "need_per_view": d["need_per_view"],
        "times_cap": ((d["cap"] or {}).get("times") or {}).get("中"),
        "price": price,
        "audience_measured": bool(a.get("measured")),
        "p65": a.get("p65"),
        "p55": a.get("p55"),
        "top": a.get("top"),
        "audience_window": (a.get("start"), a.get("day")),
        "subs": g.get("subs"),
        "views_total": g.get("views"),
        # **本数は `channel_growth` の `n` ではありません**（`n` は台帳の行数 ＝
        # チャンネルを読んだ回数）。2026-09-20 04:xx まで `n` を刷っていて、
        # 媒体資料が **359本（実物 293本）** と名乗っていました。`trend` の註を読むこと。
        "n": g.get("videos"),
    }


def sheet(rows: list[dict], scripts_dir=None) -> str:
    """**媒体資料 1枚**（そのまま貼れる字・**API 0単位**）。

    **相手の齢が測れていない周は、その行を落とします**（覆る条件 (3)）——
    測っていない数を売りにすると、返事の 1通目 で崩れます。
    """
    k = kit(rows, scripts_dir)
    lo, mid, hi = k["band"]
    L = [f"# 媒体資料 —— YouTube「{BRAND_NAME}」",
         "",
         "## どんな画面か",
         "",
         "年金・退職金の「手取りが実際にいくらか」を、1本 1分ほどで数字だけ見せるショート動画です。",
         # **本数が読めない周は、その 1語 ごと落とします**（`trend.channel_growth` の
         # 覆る条件）—— 測っていない数を相手に名乗ると、返事の 1通目 で崩れます
         # （`audience_measured` の行と同じ形・覆る条件 (3)）。
         ("本数 {n}・総再生 {v:,}回・チャンネル登録 {s:,}人。".format(
             n=(f"{k['n']:,}本" if k["n"] is not None else "—"),
             v=k["views_total"] or 0, s=k["subs"] or 0)
          if k["n"] is not None else
          f"総再生 {k['views_total'] or 0:,}回・チャンネル登録 {k['subs'] or 0:,}人。"),
         ""]
    if k["audience_measured"] and k["p65"] is not None:
        s, e = k["audience_window"]
        top = k.get("top") or {}
        tl = ""
        if top:
            tl = f"（いちばん多い層は {top.get('age')}・{top.get('gender')} で {top.get('pct')}%）"
        L += ["## 見ている人",
              "",
              f"**55歳以上 {k['p55']:.1f}%・65歳以上 {k['p65']:.1f}%**{tl}。"
              f"（YouTube アナリティクスの実測・{s}〜{e}）",
              "",
              "＝ 登録者数ではなく**年齢の寄り**が、この画面の値打ちです。"
              "供養・終活・介護のように「客が 65歳以上 に寄っている」商材ほど、無駄打ちが減ります。",
              ""]
    else:
        L += ["## 見ている人",
              "",
              "（この期間は年齢の実測が取れていないため、載せていません）",
              ""]
    L += ["## 配る量",
         "",
         f"いま 再生/月 **{k['views_month']:,.0f}回**。"
         f"投稿を 1日 {k['per_day_cap']:.0f}本 に戻すと 再生/月 **{k['views_month_cap']:,.0f}回** です"
         "（1本あたりの再生は動かさずに数えた見込み）。",
         "",
         "## ご提案できる形",
         "",
         "・本編の中で商品・サービスを紹介（タイアップ）",
         "・概要欄・固定コメント・チャンネルのリンク欄への掲載",
         "・上の組み合わせを、月単位の掲載として",
         "",
         "## 費用の目安",
         "",
         "| 単価（円/再生） | いまの月額 | 1日 "
         f"{k['per_day_cap']:.0f}本 に戻した月額 |",
         "|---|---|---|"]
    for lv, b in zip(("低", "中", "高"), (lo, mid, hi)):
        p = k["price"][lv]
        L.append(f"| ¥{b} | ¥{p['now']:,.0f} | ¥{p['cap']:,.0f} |")
    L += ["",
          "※ 相場の一般的な幅で置いた目安です。ご予算に合わせて形をお作りします。",
          "",
          "## 表示について",
          "",
          "広告であることは、景品表示法・ステルスマーケティング規制に沿って"
          "動画内と概要欄に【PR】と明記します。",
          ""]
    return "\n".join(L)


