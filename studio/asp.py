def comment_block() -> str:
    """コメント欄に置く塊。**案件が 1本 も無ければ空**（＝ `cli cta` は撃たない）。

    説明欄の塊（`block()`）より短くします —— コメントは 4行 ほどで畳まれ、
    「続きを読む」の下は説明欄と同じく開く人しか読みません。
    **`【PR】` と「アフィリエイト」の 2語 は、説明欄と同じく必ず 1行目 の塊に出します**
    （景表法・ステマ規制。検査 `tests/test_studio_asp.py`）。
    """
    got = offers()
    if not got:
        return ""
    head = (f"{MARK}動画の数字は一般的な例です。"
            "「自分の場合はいくら？」は、下から無料で相談できます（アフィリエイトです）。\n"
            f"{COMMENT_NOTE}")
    body = "\n".join(f"・{line}\n{url}" for url, line in got)
