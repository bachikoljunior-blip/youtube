# 一方 **コメントは、画面に件数つきのボタンが出ていて 1タップ**です。
# ＝ いまの置き場所は「開く人がいちばん少ない面」で、こちらの取り分になる唯一の口を回しています。
#
# **値段の差がこの手の値打ちです**: 1本 出すのに **1,650単位**、この塊を 1本 に足すのは **50単位**（1/33）。
# 日枠が戻って 5本/日 出しても 250単位 ＝ 測る側（600）にも 5本目 にも当たりません。
#
# **旧 `scripts/post_pending_comments.py`（§8 で止めた自動投稿）とは別物です。**
# 止めた理由は「全本に同じ1文を機械で置く」形そのものではなく、
#   (1) 中身が「この計算は毎日1本ずつ出しています」＝ **分子にならない自己紹介**だったこと、
#   (2) `run_marker` / `ahead_sweep` と同じ **背景の kick から毎時 勝手に走っていた**こと
#       （METHOD §「起こす口を全部 外すこと」）。
# こちらは **(1) 分子そのもの**（門の外の唯一の腕）で、**(2) 背景から呼ぶ口を作りません** ——
# `cli cta` を人（立ったサブ）が撃つときだけ動き、1本ごとに台帳 `cta_comment` が残ります。
#
# **撃てるのは公開ずみの本だけです**（private／予約中の本にはコメントを付けられない ＝ `upload` の口には置けない）。
#
# **覆る条件**:
#  (1) 塊を置いた本の 24h の再生の中位が、置いていない本の **半分 未満**なら、コメントが配りを
#      削っている（コメント欄の1番上が広告だと滞在が落ちる）＝ この口を畳んで説明欄だけに戻すこと。
#  (2) 置いた本のコメントが **`comments` の「消えた」に立った**ら、YouTube 側がリンクを落としています
#      ＝ 口ごと失う手前なので、リンクを外して「コメント欄の固定」ではなく説明欄へ誘う字に替えること。
#  (3) **30日 で成果 0件** なら、面ではなく**当てている案件**を疑うこと（`block()` の覆る条件 (2) と同じ 1か所）。
#  (4) この環境の分類器に止められたら **迂回しないこと**（METHOD §11 15:0x の `reply` と同じ口）——
#      文を `docs/FOR_OWNER.md` に置いて、オーナーが YouTube Studio で貼れる形にする。
#
# **固定にはできない所（オーナーの手）**: **API には「固定（ピン留め）」の口がありません。**
# 付けた直後は件数が 0〜2件 なので「上位のコメント」の先頭に出ますが、
# 伸びた本では下がります。**ピン留めはオーナーが Studio で 1タップ**（`docs/FOR_OWNER.md`）。

#: コメントの上限（YouTube の決め・字）。**越えると `commentThreads.insert` が 400 で落ちます**。
COMMENT_LIMIT = 9000


def comment_block() -> str:
    """コメント欄に置く塊。**案件が 1本 も無ければ空**（＝ `cli cta` は撃たない）。

    説明欄の塊（`block()`）より短くします —— コメントは 4行 ほどで畳まれ、
    「続きを読む」の下は説明欄と同じく開く人しか読みません。
    **`【PR】` と「アフィリエイト」の 2語 は、説明欄と同じく必ず 1行目 の塊に出します**
    （景表法・ステマ規制。検査 `tests/test_studio_asp.py`）。
    """
    got = offers()
    if not got:
        return ""
    head = (f"{MARK}動画の数字は一般的な例です。"
            "「自分の場合はいくら？」は、下から無料で相談できます（アフィリエイトです）。\n"
            f"{PROFILE_NOTE}")
    body = "\n".join(f"・{line}\n{url}" for url, line in got)
    tail = "※申し込みがあるとこのチャンネルに紹介料が入ります。動画の計算は公的な資料だけで出していて、紹介料とは関係ありません。"
    return f"{head}\n{body}\n{tail}"[:COMMENT_LIMIT]
