def deduction(years: int) -> int:
    """退職所得控除（No.1420）。端数の切り上げは呼ぶ側（30年2か月 → 31）。"""
    if years <= 20:
        return max(400_000 * years, 800_000)
    return 8_000_000 + 700_000 * (years - 20)


def tax(amount: int, years: int) -> dict:
    """退職金 amount 円・勤続 years 年（申告書あり・一時金・障害退職ではない）の税金。円の整数。"""
    ded = deduction(years)
    over = max(amount - ded, 0)
    taxable = (over // 2) // 1000 * 1000                 # 2分の1 → 千円未満切り捨て
    for hi, rate, sub in BRACKETS:
        if taxable <= hi:
            income = int(taxable * rate) - sub
            break
    income = max(income, 0)
    income_r = int(income * 1.021) // 100 * 100          # 復興特別所得税を入れて百円未満切り捨て（No.2732 の源泉の形）
    resident = taxable // 10                             # 住民税 10%（市 6% ＋ 県 4%）
    total = income_r + resident
    return {"deduction": ded, "over": over, "taxable": taxable, "income_tax": income_r,
            "resident_tax": resident, "tax": total, "net": amount - total,
            "rate": next(r for hi, r, _ in BRACKETS if taxable <= hi)}


def man(v: int) -> str:
    """19594300 → 1959万4300円・15000000 → 1500万円・0 → 0円。"""
    if v == 0:
        return "0円"
    m, r = divmod(v, 10_000)
    return (f"{m}万" if m else "") + (f"{r}" if r else "") + "円"


