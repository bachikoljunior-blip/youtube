# **札は当てになりません**（同じ本文で語順だけ入れ替えた 2回 で done が True→False に振れた実測 ＝
# `cli.cmd_critique` の註 09/11 12:4x）。そこで **同じ所が、直したあとも 別々の指紋で 何度も `real` に
# 挙がっているか**を数えます —— 直して指紋が動いたのに同じ所がまた 1番目に立つなら、
# 動いていないのは**本文ではなく判じる側**です。09/11 12:4x が `wheres` を台帳に残したのは
# 「次の回が撃たずに比べられるように」でしたが、**それを読む口はどこにもありませんでした**（この関数がその口）。
#
# **覆る条件**:
#  (1) この門で閉じた本の 48h が、閉じるまで回した本の中位を **2本 続けて下回ったら**、門が早すぎる
#     ＝ `REPEAT_GATE` を 4 へ上げること（数は台帳の `critique` と `views_over` だけで出せる・API 0単位）。
#  (2) 逆に、この門が 1度も引かれないまま 5本 過ぎたら、詰まっていたのは札ではなく本文
#     ＝ この段ごと畳んでよい（`loop_done` だけに戻す）。
#  (3) `wheres` の `where` が「コマN」の形をやめたら、`_koma_no` は畳めなくなる ＝ そのときは
#     所ではなく `why` の先頭 20字 で数えること。
REPEAT_GATE = 3


def _koma_no(where: str) -> str:
    """`where` を**先頭のコマ番号**へ畳む（「コマ1」「コマ1〜3（全体の構造）」「コマ1-2」「コマ1冒頭」
    「コマ2→コマ5」は どれも "1" か "2"）。番号が無い行（「コマ全体」など）は字のまま 12字 で持つ。"""
    m = re.search(r"コマ\s*([0-9]+)", where or "")
    return m.group(1) if m else (where or "")[:12]


def repeat_reals(vid: str, rows=None) -> dict:
    """その本の**過去の** critique の行から、`real` で挙がった所 → それを挙げた指紋（`sig`）の集合。

    指紋で数えるのは、**同じ本文で 2回 挙がった**のを 2回 と数えないためです
    （同じ本文なら、同じ所が挙がるのは当たり前で、閉じない理由になりません）。"""
    from .common import ledger_rows
    out: dict = {}
    for r in (ledger_rows() if rows is None else rows):
        if r.get("event") != "critique" or r.get("id") != vid:
            continue
        for w in r.get("wheres") or []:
            if w.get("sev") != "real":
                continue
            out.setdefault(_koma_no(w.get("where") or ""), set()).add(r.get("sig") or r.get("at"))
    return out


def not_converging(vid: str, c: dict, rows=None) -> tuple:
    """(閉じてよいか, 印字する1行)。`loop_done` が閉じない周にだけ意味があります。"""
    items = c.get("items") or []
    if not items or items[0].get("severity") == "nitpick":
        return False, ""
    k = _koma_no(items[0].get("where") or "")
    sigs = repeat_reals(vid, rows).get(k, set())
    if len(sigs) >= REPEAT_GATE:
        return True, (f"1番目の所（コマ{k}）は、**別々の本文 {len(sigs)}つ** で real に挙がっています"
                      f"（門 {REPEAT_GATE}）＝ 直しても同じ所がまた立つ ＝ **動いていないのは判じる側**"
                      f" ＝ 輪を閉じてよい（`critic.not_converging` の覆る条件）")
    return False, ""
