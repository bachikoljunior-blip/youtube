def man(v: int) -> str:
    """162600 → 16万2600円・1800000 → 180万円・1050 → 1050円。"""
    if v == 0:
        return "0円"
    m, r = divmod(v, 10_000)
    return (f"{m}万" if m else "") + (f"{r}" if r else "") + "円"


def figures(age: int) -> dict:
    """その歳まで待ったときの数（**全部 整数**）。"""
    m = (age - 65) * 12                       # おくらせた月数
    add = P * RATE_PERMIL * m // 1000         # 毎月 ふえる分
    amt = P + add                             # 毎月 受け取る分
    lost = P * m                              # 待つ間に受け取らない合計
    assert P * RATE_PERMIL * m % 1000 == 0, (age, add)
    # **143か月目 でこえる**（142か月 では足りない）——「割り切れない」ことを門にする
    assert add * (EVEN - 1) < lost <= add * EVEN, (age, lost, add, EVEN)
    y, mo = divmod(EVEN, 12)                  # 11年11か月
    return {"age": age, "months": m, "add": add, "amt": amt, "lost": lost,
            "even": EVEN, "even_y": y, "even_mo": mo, "even_age": age + y,
            "pct": f"{RATE_PERMIL * m / 10:g}"}


