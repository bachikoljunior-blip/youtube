#: 複製の遅れの実測（最大 2.8時間・`envelope` の註）の **2倍**。
#: この時間を越えて生が包絡を下回ったままなら、遅れでは説明できない ＝ 数え直し。
ENVELOPE_LAG_H = 6.0


def ceiling(pts: list[dict]) -> int | None:
    """**支えられている いちばん高い水準**（＝ 包絡の天井）。API 0単位。

    水準 v が「支えられている」＝ **最後に v 以上を見た点から `ENVELOPE_LAG_H` しか経っていない**。
    それより古い峰は、遅れの窪みでは説明できない（遅れの実測は 最大 2.8時間）＝ **数え直し**なので、
    天井にしない。**まだ 6時間 経っていない峰は必ず支えられている** ので、
    伸び中の本の最新の点は、いつもそのまま上がります。

    **見るのは点1つではなく水準です** —— 同じ峰が 2点 続く回が在り（実測 `nQbVxuWpWw8` の 68 は
    23:03 と 23:08 の 2点）、**点ごとに「この点より後ろに同じ値が在るか」で見ると、
    前の点は後ろの点に支えられ、後ろの点は…と続いて、どの点も『戻らなかった』にならず、
    峰が永久に残ります**（この回に一度そう書いて、実物で外した）。水準を高いほうから見れば、その口が無い。
    **ただし、この行の中の `>=` は効いていません** —— 陽性対照を撃つと落ちませんでした。
    `>=` を `==` に変えても**実物 45本 とも天井は同じ**で、降順に見るかぎり必ず同じ答えになります
    （高い水準が支えられていれば そちらで返るので、低い水準に「より新しい高い点」は残らない）。
    **効いているのは「降順に水準で見る」ほうだけ**なので、`>=` に主張を持たせないこと
    （§5 の教訓の形3つ目「陽性対照は落ちるまで撃つ。落ちなければ、疑うのは道具ではなく検査のデータ」の 3件目）。

    **並びは後ろから読み直します**（天井は系列の最後の点から決まる）—— 台帳は毎周 全部を
    読み直すので、数え直しが分かった回に**過去の点も**その水準へ落ちます（＝ 減りが
    「起きた所」に出る。6時間 遅れて段が付く形にはしない）。
    """
    if not pts:
        return None
    last_age = float(pts[-1]["age_h"])
    for v in sorted({int(p["views"]) for p in pts}, reverse=True):
        seen = max(float(p["age_h"]) for p in pts if int(p["views"]) >= v)
        if last_age - seen <= ENVELOPE_LAG_H:
            return v
    return int(pts[-1]["views"])


def recounts(rows: list[dict]) -> list[dict]:
    """**数え直し**（生が包絡を `ENVELOPE_LAG_H` より長く下回ったまま戻らなかった峰）を並べる。API 0単位。

    §7 (h) は「48h を越えた本で `n_values > 1` が出るか」で数え直しを見張っていましたが、
    **数え直しは周と周のあいだに起き、同じ周の 3回 読みは秒の間隔しか離れていません**
    ＝ その道では構造的に見えません。**数え直しはここで数えること。**

    **【2026-09-10 10:2x に書き直した】**もとは「**`n_values` は必ず 1**（台帳の `n_values > 1` は
    8行 とも伸び中の本・48h 超は 0行）」と書いていましたが、**この回に 48h 超で 1行 出ました**
    （`EkNqtkK49Bw` 96.3h・142 対 141）。**割れること自体は数え直しの印ではありません** ——
    割れるのは**複製の遅れ**で、伸びた直後なら齢がいくつでも起きます。
    同じ周の中で遅れと数え直しを分けるのは `shakes()`（**推定が動かなかった周の数**で見る）。
    """
    out: list[dict] = []
    for vid, pts in series(rows).items():
        cap = ceiling(pts)
        top = max(int(p["views"]) for p in pts)
        if cap is None or cap >= top:
            continue
        seen = max(float(p["age_h"]) for p in pts if int(p["views"]) >= top)
        out.append({
            "id": vid,
            "from": top,
            "to": cap,
            "age_h": seen,
            "hours_below": float(pts[-1]["age_h"]) - seen,
            "points_below": sum(1 for p in pts if float(p["age_h"]) > seen),
        })
    return sorted(out, key=lambda r: -r["hours_below"])

